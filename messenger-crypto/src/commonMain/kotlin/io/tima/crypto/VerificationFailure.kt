package io.tima.crypto

/**
 * Проверка подлинности конверта не прошла: подпись не сошлась или обязательство по
 * ключу указывает на другой ключ.
 *
 * **Почему свой тип, а не `SecurityException`.** До перевода на KMP здесь бросался
 * `java.lang.SecurityException` — и он попадал в код *без единого импорта*, потому
 * что `java.lang` на JVM подставляется сам. Под iOS такого класса нет, и это
 * выяснилось только компиляцией: поиск по `import java.` его не находит.
 *
 * Замена на свой тип — не обход ограничения, а улучшение. `SecurityException` в
 * JVM означает «менеджер безопасности запретил операцию», то есть совсем другое
 * событие; здесь же речь о том, что **данные не подтвердились**. Названный тип
 * отличает это от `IllegalStateException`, которым в том же месте сообщается об
 * отсутствии ключа для устройства: первое — возможная атака, второе — своя
 * несобранная картина.
 */
class VerificationFailure(message: String) : Exception(message)
