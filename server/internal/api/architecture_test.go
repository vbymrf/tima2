// Бюджеты общих мест: сколько методов висит на едином receiver.
//
// Каждый handler, объявленный методом *Server, видит все 19 полей структуры — и
// значит любая новая функция обязана вписаться строкой в общий тип, который правят
// все. Два разработчика, делающие каналы и звонки, не пересекаются по смыслу, но
// обязательно пересекутся здесь.
//
// Программа архитектурных изменений выносит handler-ы в registrar-файлы со своими
// узкими интерфейсами. Бюджет — измеритель этого движения: он может только
// уменьшаться. Понижать его обязан тот же коммит, который вынес группу.
const (
	// 89 → 83: каналы уехали в channels.go свободными функциями (шаг 4).
	// 83 → 68: звонки, групповые звонки и аудио-комнаты — туда же.
	// 68 → 65: медиа.
	// 65 → 47: группы — состав, сообщения, ключи.
	// 47 → 40: устройства и привязка.
	// 40 → 34: чаты — архив, копии, восстановление.
	// 34 → 26: люди и аккаунт.
	// 26 → 22: личные сообщения и состояния — последняя группа шага 4.
	serverMethodBudget = 22
	// 132 → 150: решение заказчика 2026-09-04.
	//
	// Бюджет был красным ДО работ по социальному слою: в дереве лежало 133 метода при
	// пределе 132, то есть правило «только уменьшаться» уже кто-то нарушил и не починил.
	// Этапы Г1…Г6 добавили семь методов по делу — уровень сообщения, аудитория карточки,
	// заявки, разрешения и сроки, — и упереться в чужой невыполненный долг посреди работы
	// было бы неверно.
	//
	// **Расширение — не отмена правила.** Оно по-прежнему означает: новый метод хранилища
	// обязан быть нужен, а не удобен, и потребитель обязан объявлять узкий интерфейс рядом
	// с собой. Сужение интерфейсов у нынешних потребителей — отдельная работа, и когда она
	// случится, этот же комментарий обязан пополниться строкой «150 → …».
	//
	// 150 → 156 (Г8, перенос к себе): лента добавила шесть — своя лента, её создание,
	// автоматическая подписка, перенос ссылкой, выдача с раскрытием ссылок и снятие
	// записи со страницы. Запас тот же и на том же условии: снимается вместе со `slack`,
	// когда работы по социальному слою закончатся.
	//
	// 156 → 160 (Д1, ник): занять, спросить занятость, найти по нику, отдать ники
	// списком. Четыре, а не одна «работа с ником»: у каждой свой ответ и своя цена
	// ошибки, и склеенная ручка отвечала бы «занято» там, где спрашивали «чей».
	//
	// 160 → 164 (Д1б, друзья): добавить, убрать, список, «он мне друг?».
	//
	// 164 → 162 (Д1б-пересмотр и Д10 одним счётом): отдельной таблицы друзей больше
	// нет — список подписчиков ленты и есть список друзей владельца, четыре метода
	// ушли, один пришёл (`FeedSubscribers`). Виртуальные аккаунты добавили три:
	// создать, перечислить и «есть ли телефон»; удаление аккаунта заменило один
	// метод другим (`MarkAccountAndBelongings` вместо `MarkAccountDeleted`).
	//
	// Итог всё равно меньше прежнего — бюджету положено только уменьшаться.
	//
	// 162 → 167 (Д12, передача аккаунта): начать, отменить, найти по коду, засчитать
	// неверную попытку, завершить. Пять, а не один «передать»: между началом и
	// завершением проходит время и два разных человека, и склеенный метод означал бы,
	// что передача происходит одним запросом — то есть без подтверждения фразой.
	//
	// Это рост, и он записан здесь именно поэтому: бюджет поднимается только вместе с
	// объяснением, иначе он перестаёт что-либо значить.
	storeMethodBudget = 167
	// 71 → 65: семь маршрутов каналов свернулись в один RegisterChannels.
	routeBudget = 65
)

var (
	serverMethodRe = regexp.MustCompile(`(?m)^func \(s \*Server\)`)
	storeMethodRe  = regexp.MustCompile(`(?m)^func \(s \*Store\)`)
	routeRe        = regexp.MustCompile(`mux\.HandleFunc`)
)

// TestArchitectureBudgets намеренно НЕ вызывает setup(t).
//
// Тесты пакета уходят в t.Skipf, когда рядом нет базы, — и архитектурная проверка,
// написанная через setup, молча пропускалась бы на любой машине без Postgres. Здесь
// читаются исходники, база не нужна вовсе, и пропуска быть не может.
func TestArchitectureBudgets(t *testing.T) {
	cases := []struct {
		name    string
		dir     string
		pattern *regexp.Regexp
		budget  int
		why     string
		/**
		 * Разрешить запас: фактическое число меньше бюджета — не повод ронять тест.
		 *
		 * Обычно запас запрещён, и правильно: бюджет, до которого «ещё можно расти»,
		 * перестаёт быть измерителем и становится разрешением. Исключение сделано на
		 * время работ по социальному слою (решение заказчика 2026-09-04): этапы Г8…Г10
		 * добавят методы хранилища, и упираться в предел на каждом шаге значило бы
		 * править этот файл в каждом коммите.
		 *
		 * Когда работы кончатся, запас снимается: `slack` убирается, бюджет
		 * опускается до фактического числа.
		 */
		slack bool
	}{
		{
			name:    "методы *Server",
			dir:     ".",
			pattern: serverMethodRe,
			budget:  serverMethodBudget,
			why: "handler на общем receiver видит все поля Server. " +
				"Новый endpoint — это файл-registrar со своим узким интерфейсом, " +
				"а не ещё один метод общего типа.",
		},
		{
			name:    "методы *Store",
			dir:     "../store",
			pattern: storeMethodRe,
			budget:  storeMethodBudget,
			why: "API вызывает часть методов Store и передаёт тот же " +
				"конкретный тип worker-у. Потребитель обязан объявлять узкий " +
				"интерфейс рядом с собой, а не получать всё хранилище.",
			slack: true, // до конца работ по социальному слою — см. комментарий у поля
		},
	}

	for _, tc := range cases {
		got, err := countIn(tc.dir, tc.pattern)
		if err != nil {
			t.Fatalf("%s: %v", tc.name, err)
		}
		if got > tc.budget {
			t.Errorf("%s: стало %d при бюджете %d — бюджет может только уменьшаться.\n%s",
				tc.name, got, tc.budget, tc.why)
		}
		if got < tc.budget && !tc.slack {
			t.Errorf("%s: стало %d при бюджете %d — понизьте бюджет тем же коммитом, "+
				"иначе он перестанет что-либо значить", tc.name, got, tc.budget)
		}
		if got < tc.budget && tc.slack {
			// Не падение, но и не тишина: запас должен быть виден в отчёте, иначе о нём
			// забудут вместе с обещанием его снять.
			t.Logf("%s: стало %d при бюджете %d — запас %d, снять после работ по социальному слою",
				tc.name, got, tc.budget, tc.budget-got)
		}
	}

	routes, err := countInFile("server.go", routeRe)
	if err != nil {
		t.Fatalf("маршруты: %v", err)
	}
	if routes > routeBudget {
		t.Errorf("маршрутов в Register стало %d при бюджете %d: Register — таблица "+
			"вызовов Register<Группа>, а не список из семидесяти строк",
			routes, routeBudget)
	}
}

func countIn(dir string, pattern *regexp.Regexp) (int, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return 0, err
	}
	total := 0
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		got, err := countInFile(filepath.Join(dir, name), pattern)
		if err != nil {
			return 0, err
		}
		total += got
	}
	return total, nil
}

func countInFile(path string, pattern *regexp.Regexp) (int, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return 0, err
	}
	return len(pattern.FindAllIndex(data, -1)), nil
}
