-- 0028: имя устройства — чтобы список устройств в настройках был читаемым
-- («Ноутбук», а не «a3f1c8b2…»), и чтобы человек понимал, что именно отзывает.
--
-- Пустая строка, а не NULL: устройства, зарегистрированные по SMS, имени не
-- сообщают (экран регистрации его не спрашивает), и клиент показывает для них
-- запасную подпись. NULL здесь ничего не добавил бы, кроме ветвления в коде.
ALTER TABLE devices ADD COLUMN IF NOT EXISTS name TEXT NOT NULL DEFAULT ''
    CONSTRAINT devices_name_len CHECK (char_length(name) <= 100);
