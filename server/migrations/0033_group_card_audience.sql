-- 0033: кому открыта карточка группы (ADR-0018 п. 2–3, ПЛАН-СОЦИУМА Г2).
--
-- Личная группа не ищется и не лежит в каталоге: о её существовании узнают по цепочке
-- знакомств. Владелец кладёт группу себе на страницу — и его контакты видят карточку:
-- название и сообщения уровня 0. Больше ничего.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ ФЛАГ У ГРУППЫ. Сервер обязан различать три состояния,
-- а не два: «карточку не передавали» (404 — группы для тебя не существует), «передали,
-- но ты не участник» (карточка) и «участник» (всё). Флагом «группа опубликована» третье
-- от первого не отличить, и любой посторонний увидел бы существование личной группы.
--
-- ПОЧЕМУ СПИСОК ЦЕЛИКОМ, А НЕ ДЕЛЬТА. Адресная книга живёт только на клиенте (решение
-- А3): графа знакомств на сервере нет и не будет. Значит сервер не может помнить прошлое
-- состояние чужой книги, чтобы применить к нему дельту, — клиент присылает список как
-- есть, а сервер заменяет им прежний.
--
-- ЦЕНА, НАЗВАННАЯ ПРЯМО. После этой миграции существование, название и описание личной
-- группы лежат на сервере открытыми и расходятся по цепочке контактов. Это принято
-- сознательно: витрина вне E2E по назначению — её смысл в том, чтобы её прочёл тот, у
-- кого ключа нет и не будет.

CREATE TABLE IF NOT EXISTS group_card_audience (
    group_id   UUID        NOT NULL REFERENCES groups(group_id) ON DELETE CASCADE,
    user_id    UUID        NOT NULL REFERENCES users(user_id)   ON DELETE CASCADE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (group_id, user_id)
);

-- Обратный вопрос — «какие карточки видны этому человеку» — задаёт вкладка «Друзья»
-- окна 2 (Г6), и без этого индекса он читал бы таблицу целиком.
CREATE INDEX IF NOT EXISTS idx_gca_user ON group_card_audience (user_id);
