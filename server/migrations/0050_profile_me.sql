--
-- Картинка лежит в медиа (media_objects), здесь только ссылка. Как у групп в 0005.
-- NULL — аватара нет, показываются буквы имени.
ALTER TABLE persons
    ADD COLUMN IF NOT EXISTS avatar_media_id UUID;

COMMENT ON COLUMN persons.avatar_media_id IS
    'Аватар аккаунта — объект в media_objects. NULL — картинки нет, рисуются буквы';
