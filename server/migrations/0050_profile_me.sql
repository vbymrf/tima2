-- 0050: профиль «кто я» — замок ника и место под аватар (ПЛАН-КОНТАКТОВ.md, Д8;
-- решение заказчика 2026-09-15).
--
-- ── НИК — ОДИН РАЗ НА ЛИЧНОСТЬ ─────────────────────────────────────────────────
--
-- Ник принадлежит аккаунту (persons) и переживает смену личности — иначе ссылка на
-- человека обрывалась бы там, где он как раз остался собой (0037). Но задать его
-- можно ОДИН раз на личность: ник — то, чем человека находят, и менять его по
-- настроению значит рвать чужие ссылки. Личность здесь — строка users, выведенная из
-- секретной фразы; «Начать заново» заводит новую (StartNewIdentity), и у неё право на
-- смену появляется снова. Не воспользовался — прежний ник остаётся по умолчанию.
--
-- Поэтому колонка помнит не «менялся ли», а КТО задал: сравнение с текущим user_id и
-- есть проверка. NULL — ник не задавался этой колонкой (или его нет вовсе).
ALTER TABLE persons
    ADD COLUMN IF NOT EXISTS nickname_set_by UUID REFERENCES users(user_id);

COMMENT ON COLUMN persons.nickname_set_by IS
    'Личность (users.user_id), задавшая нынешний ник. Совпадает с текущей — менять нельзя; иная или NULL — можно один раз';

-- Уже занятые ники считаются заданными текущей личностью: правило «один раз» для
-- них уже исполнено. Иначе каждый, кто занял ник до этой миграции, получил бы
-- вторую попытку просто за то, что успел раньше.
UPDATE persons p
   SET nickname_set_by = u.user_id
  FROM users u
 WHERE u.person_id = p.person_id
   AND u.valid_to IS NULL
   AND p.nickname IS NOT NULL
   AND p.nickname_set_by IS NULL;

