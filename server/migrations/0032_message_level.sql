-- 0032: уровень сообщения (ADR-0019).
--
-- Порядок доступа переезжает с контейнера на сообщение: сервер отвечает на запрос
-- сравнением `уровень ≤ право читателя`, а не ветвлением по виду группы, роли и
-- подписке. Шкала монотонная — чем больше номер, тем уже круг:
--
--   -1  зашифровано групповым ключом; сервер не решает ничего
--    0  всем и всегда — описание группы (бывшая «витрина»)
--    1  всем, даже не вступившим; попадает в ленты
--    2  вступившим
--    3  по разрешению, которое админ дал конкретному участнику
--
-- ПОЧЕМУ УРОВЕНЬ НЕ ВХОДИТ В ПОДПИСЬ. Подпись Ed25519 покрывает
-- group_message_canonical_bytes и неизменна, а уровень по замыслу меняется после
-- отправки: админ сужает чужое сообщение, автор — своё (ADR-0019 §6). Значение,
-- которое обязано меняться, в неизменяемый преимидж класть нельзя. Отсюда следствие,
-- которое надо знать: уровень — решение сервера о выдаче, а не заверенная автором
-- часть сообщения.
--
-- ЗНАЧЕНИЕ ПО УМОЛЧАНИЮ РАЗНОЕ У ДВУХ ВИДОВ ГРУПП. В приватной всё, кроме описания,
-- зашифровано — значит -1. В публичной шифра нет вовсе, а сегодняшняя выдача отдаёт
-- сообщения только участникам — это ровно уровень 2. Ставить всем -1 было бы неправдой
-- о публичных группах.

ALTER TABLE group_messages
    ADD COLUMN IF NOT EXISTS level SMALLINT NOT NULL DEFAULT -1;

UPDATE group_messages m
   SET level = 2
  FROM groups g
 WHERE g.group_id = m.group_id
   AND g.kind = 'public'
   AND m.level = -1;

ALTER TABLE group_messages
    DROP CONSTRAINT IF EXISTS gm_level_range;
ALTER TABLE group_messages
    ADD CONSTRAINT gm_level_range CHECK (level BETWEEN -1 AND 3);

-- Самый частый запрос приложения — «дай сообщения группы до уровня N».
-- Без этого индекса он читает всю группу и фильтрует в памяти (ADR-0019, следствие 1).
CREATE INDEX IF NOT EXISTS idx_gm_group_level
    ON group_messages (group_id, level, message_id DESC);
