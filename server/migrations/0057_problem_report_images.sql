-- 2026-09-29).
--
-- ── ЗАЧЕМ ────────────────────────────────────────────────────────────────────
--
-- Часть бед не видна ни в каком журнале: полосы на видео, рябь, «криво нарисовано».
-- Кадр собеседника из окна 0 или снимок экрана говорят о них сразу, а словами их не
-- описать так, чтобы разобрать.
--
-- ── УСТРОЙСТВО ───────────────────────────────────────────────────────────────
--
-- Отдельная таблица, а не колонка в `problem_reports`: снимков у отчёта от нуля до трёх,
-- а сам отчёт читают чаще снимков, и тянуть мегабайты с каждой строкой списка незачем.
-- Снимок — байтами в базе, а не в хранилище медиа: отчёт принимается и без входа, а
-- хранилище медиа отдаёт ссылки только вошедшим.
--
-- Миграция аддитивная: новая таблица, старые строки и старые клиенты не затронуты.
CREATE TABLE IF NOT EXISTS problem_report_images (
    report_id   UUID        NOT NULL REFERENCES problem_reports(report_id) ON DELETE CASCADE,
    -- Порядок, в котором человек их приложил: с первого начинают смотреть.
    position    INT         NOT NULL,
    mime        TEXT        NOT NULL DEFAULT 'image/jpeg',
    data        BYTEA       NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (report_id, position)
);
