-- 0043: комментарии в каналах и лентах (ADR-0024, ПЛАН-КАНАЛОВ К1).
--
-- КОММЕНТАРИЙ — ЭТО ЗАПИСЬ, У КОТОРОЙ КОНТЕЙНЕР НЕ КАНАЛ, А ДРУГАЯ ЗАПИСЬ. Отсюда и
-- отсутствие новой таблицы: у него тот же автор, то же время, те же узлы и разметка, та
-- же пометка удаления. Отличает его одна колонка — на какую запись он отвечает.
--
-- Соблазн, от которого ADR-0024 и защищает: завести `channel_comments` со своими правами
-- и своей выдачей. Тогда каждое правило (круг, удаление, модерация, перенос) пишется
-- дважды, и второй раз — с ошибкой.
ALTER TABLE channel_posts
    ADD COLUMN IF NOT EXISTS parent_post_id BIGINT;

-- КОРЕНЬ ЛЕЖИТ В ТОМ ЖЕ КАНАЛЕ — это держит база, а не обработчик. Ссылка составная,
-- потому что первичный ключ таблицы составной: (channel_id, post_id). Значит комментарий
-- физически не может указать на запись соседнего канала, каким бы ни был запрос.
ALTER TABLE channel_posts DROP CONSTRAINT IF EXISTS fk_cp_parent;
ALTER TABLE channel_posts ADD CONSTRAINT fk_cp_parent
    FOREIGN KEY (channel_id, parent_post_id)
    REFERENCES channel_posts (channel_id, post_id);

-- ДВУХ УРОВНЕЙ ДОСТАТОЧНО (ADR-0024 §7): ответ на комментарий цепляется к тому же корню
-- и несёт «@имя» в тексте. Третий уровень вложения на телефоне уже не читается.
--
-- Условие «корень сам не комментарий» декларативно здесь не выражается — оно проверяется
-- в INSERT одним запросом (store/channel_comments.go), а не чтением перед записью:
-- проверка отдельным SELECT-ом разъезжается с вставкой ровно в тот момент, когда две
-- вставки идут одновременно.

-- Выдача разговора: комментарии одного корня по возрастанию post_id. Порядок «сверху
-- первые» — решение заказчика 2026-09-08: разговор читают с начала, а ленту с конца.
CREATE INDEX IF NOT EXISTS idx_cp_comments
    ON channel_posts (channel_id, parent_post_id, post_id)
    WHERE parent_post_id IS NOT NULL;

-- ЛЮБАЯ ВЫДАЧА ЛЕНТЫ ОБЯЗАНА ИСКЛЮЧАТЬ КОММЕНТАРИИ (ADR-0024, следствие 1). Комментарий
-- лежит в той же таблице, что и посты; забыли условие `parent_post_id IS NULL` — ветка
-- вылезла в ленту как запись. Условие стоит в ListPosts и ListFeed и покрыто тестом;
-- частичный индекс ниже — чтобы оно ничего не стоило.
CREATE INDEX IF NOT EXISTS idx_cp_roots
    ON channel_posts (channel_id, post_id DESC)
    WHERE parent_post_id IS NULL;
