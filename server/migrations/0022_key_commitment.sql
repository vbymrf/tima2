-- 0022: обязательство по ключу сообщения (ADR-0013, конверт версии 2).
--
-- message_key едет получателю тремя независимыми путями — ratchet, wrapped_key и
-- escrow_blob. Ни один не доказывает, что остальные ведут к тому же ключу: Poly1305
-- не является key-committing, поэтому один шифртекст может валидно раскрыться под
-- ДВУМЯ разными ключами. Без обязательства отправитель мог бы собрать сообщение так,
-- что по ордеру расшифруется один текст, а у получателя на экране будет другой.
--
-- Значение входит в canonical_bytes, то есть защищено подписью. Сервер его не
-- проверяет (он не знает message_key) — он его хранит и отдаёт получателю, который
-- пересчитывает обязательство из добытого ключа и сверяет.
--
-- NULL — конверт версии 1 (до перехода). Обязательность проверяется в коде по
-- format_version, а не ограничением: обе версии сосуществуют на время выкатки.
ALTER TABLE personal_messages
    ADD COLUMN IF NOT EXISTS key_commitment BYTEA
        CHECK (key_commitment IS NULL OR octet_length(key_commitment) = 32);
