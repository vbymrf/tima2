-- 0037: ник — второе имя, по которому человека находят (ПЛАН-КОНТАКТОВ.md, Д1).
--
-- Ник лежит на persons, а НЕ на users. Личность (users) меняется при потере ключей
-- или уходе номера другому человеку — так устроена 0019. Ник обязан пережить такую
-- смену: он и есть то, чем человека зовут, и ссылки на него не должны обрываться.
--
-- Ник хранится ОТКРЫТО, в отличие от телефона и имени (0017: phone_bidx/name_enc).
-- Это не недосмотр: по нику ищут, а искать по зашифрованному нечем. Человек выбирает
-- ник сам и сам решает, называться ли, — тем он и отличается от номера, который у него
-- уже есть, и от имени, которое ему пишет кто-то другой.
ALTER TABLE persons ADD COLUMN IF NOT EXISTS nickname TEXT;

-- Уникальность без учёта регистра: иначе Petr и petr — два разных человека, и это
-- первое, чем воспользуются для подмены. Частичный индекс — ник необязателен, и
-- аккаунты без него друг другу не мешают (то же решение, что у phone_bidx в 0019).
CREATE UNIQUE INDEX IF NOT EXISTS idx_persons_nickname_lower
    ON persons (lower(nickname)) WHERE nickname IS NOT NULL;

-- Границы решены заказчиком 2026-09-05: 10…20 знаков, латиница, цифры, подчёркивание.
-- Короче десяти зарезервировано — короткие ники разбирают первыми и перепродают.
-- Проверка в базе, а не только в коде: ограничение, живущее в одном приложении,
-- перестаёт действовать, как только к базе приходит второе.
ALTER TABLE persons DROP CONSTRAINT IF EXISTS chk_persons_nickname;
ALTER TABLE persons ADD CONSTRAINT chk_persons_nickname
    CHECK (nickname IS NULL OR nickname ~ '^[A-Za-z0-9_]{10,20}$');
