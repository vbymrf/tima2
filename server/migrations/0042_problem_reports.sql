-- 0042: отчёты о проблеме с устройства (ПЛАН-ОТЛАДКИ.md, Б4).
--
-- Отчёт — это то, что человек прислал сам из приложения: слова о поломке, обстановка
-- устройства и журнал последних суток. Второй источник правды об одной поломке; первый —
-- прямой доступ к устройству по проводу. Сходятся они или нет, и есть мера того, годится
-- ли формат отчёта (§2 плана).
CREATE TABLE IF NOT EXISTS problem_reports (
    report_id   UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    -- Короткий номер, который человек называет в разговоре: «отчёт A7K3». UUID для этого
    -- не годится — его не продиктовать.
    number      TEXT        NOT NULL UNIQUE,

    -- ── Кто прислал ──────────────────────────────────────────────────────────
    --
    -- Оба поля СЕРВЕР берёт из токена и НИКОГДА из тела запроса: присланному
    -- идентификатору верить нельзя, иначе чужой отчёт ляжет на чужой аккаунт.
    --
    -- NULL здесь законен и важен: отчёт принимается и без входа — «не могу войти» самая
    -- частая жалоба, и требовать для неё авторизацию значит её не услышать (решение
    -- заказчика 2026-09-06).
    --
    -- Ссылка на `users`, а не на `persons`: в токене лежит идентификатор ЛИЧНОСТИ
    -- (`Claims.Subject`), и он же приходит сюда. Аккаунт (`persons`) достаётся из
    -- `users.person_id`, когда понадобится, — а вот обратное преобразование на приёме
    -- отчёта означало бы лишний запрос в момент, когда у человека и так что-то сломано.
    user_id     UUID        REFERENCES users(user_id) ON DELETE SET NULL,
    device_id   UUID        REFERENCES devices(device_id) ON DELETE SET NULL,

    -- ── Что прислали ─────────────────────────────────────────────────────────
    kind        TEXT        NOT NULL,
    body        TEXT        NOT NULL,
    -- Окно и вкладка, из которых человек ушёл в настройки. Половина жалоб «не работает» —
    -- про конкретное место, и место это чаще всего то, откуда пошли жаловаться.
    origin      TEXT        NOT NULL DEFAULT '',
    platform    TEXT        NOT NULL DEFAULT '',
    model       TEXT        NOT NULL DEFAULT '',
    os          TEXT        NOT NULL DEFAULT '',
    build       TEXT        NOT NULL DEFAULT '',
    stream      TEXT        NOT NULL DEFAULT '',
    -- Ник кладём, номер телефона — нет: ник человек и так показывает собеседникам, а
    -- номер есть у сервера по person_id (решение заказчика 2026-09-06).
    nickname    TEXT        NOT NULL DEFAULT '',
    -- Журнал за сутки. Содержимого переписки в нём нет — это обещание исполняется на
    -- клиенте: пишутся действия и коды ответов, а длинное, похожее на ключ, вырезается.
    log         TEXT        NOT NULL DEFAULT '',

    -- Адрес нужен ровно для одного — предела частоты у отчётов без входа. Хранится в
    -- открытом виде осознанно: без него неопознанный отчёт не отличить от тысячи таких же.
    from_addr   TEXT        NOT NULL DEFAULT '',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Читают отчёты по времени: «что приходило сегодня» — первый вопрос при разборе.
CREATE INDEX IF NOT EXISTS problem_reports_created_idx ON problem_reports (created_at DESC);

-- Предел частоты считается по адресу за последний час; без индекса этот счёт пойдёт по
-- всей таблице, а она растёт.
CREATE INDEX IF NOT EXISTS problem_reports_addr_idx ON problem_reports (from_addr, created_at DESC);
