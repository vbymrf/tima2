-- заказчика 2026-10-01).
--
-- Аддитивная: новые столбцы — NULL-допустимые или с умолчанием, старые не трогаются.

-- ── ВРЕМЕННАЯ ГРУППА ЗВОНКА ──────────────────────────────────────────────────
--
-- Звонок без группы (из журнала контактов, «Создать чат группового звонка») заводит
-- личную группу, которая живёт до этого срока. Каждый звонок в ней срок отодвигает
-- (CALL_GROUP_TTL, по умолчанию 12 ч). Срок вышел и звонка нет — уборщик удаляет группу
-- вместе с перепиской (решение 1).
--
-- NULL — обычная личная группа: срока нет, уборщик её не трогает никогда. Снять срок и
-- сделать временную постоянной нельзя — ручки для этого нет намеренно.
ALTER TABLE groups ADD COLUMN IF NOT EXISTS call_ttl_until TIMESTAMPTZ;

CREATE INDEX IF NOT EXISTS idx_groups_call_ttl
    ON groups (call_ttl_until)
    WHERE call_ttl_until IS NOT NULL AND deleted_at IS NULL;

-- ── ПАУЗА ЗВОНКА ─────────────────────────────────────────────────────────────
--
-- Пауза «висит» (решение 5): все в комнате, звук и видео стоят. Ставит и снимает
-- создатель. Здесь — чтобы вошедший во время паузы узнал о ней из ответа на вход, а не
-- ждал следующей перемены.
ALTER TABLE calls ADD COLUMN IF NOT EXISTS paused_at TIMESTAMPTZ;

-- ── УЧАСТНИК ЗВОНКА ──────────────────────────────────────────────────────────
--
-- invited = false — вошёл сам по полосе «Идёт звонок» в группе, а не был отмечен
-- создателем (решение 15). Вызов и пропущенный достаются только отмеченным.
ALTER TABLE call_participants ADD COLUMN IF NOT EXISTS invited BOOLEAN NOT NULL DEFAULT true;

-- Удалён создателем из звонка (решение 17): обратно в ЭТОТ звонок не пускаем. Из группы
-- он при этом не удаляется — следующий звонок его позовёт.
ALTER TABLE call_participants ADD COLUMN IF NOT EXISTS removed_at TIMESTAMPTZ;

-- Идущий звонок группы ищется по группе.
CREATE INDEX IF NOT EXISTS idx_calls_group_live
    ON calls (group_id)
    WHERE type = 'group' AND state IN ('ringing', 'answered');

-- Звали ли звонком (галочка «Звонить», решение 3). Нужен концу звонка: пропущенный
-- достаётся только тому, у кого телефон звонил, а не всем отмеченным.
ALTER TABLE calls ADD COLUMN IF NOT EXISTS ring BOOLEAN NOT NULL DEFAULT false;
