-- Эпоха escrow, на которую завёрнут ключ версии GK (ADR-0017).
--
-- Хранится рядом с версией, потому что по ней ведётся ротация: инвариант «последняя
-- версия GK группы, где была отправка в эпоху E, имеет escrow_epoch = E» проверяется
-- одним запросом, без похода в анклав за метаданными каждого ключа.
--
-- Аддитивно и обнуляемо: строки, записанные до этой миграции, остаются с NULL. Это
-- не «неизвестно ещё не заполнили», а «ротация была до введения правила» — и такие
-- группы ротируются при первой же активности, потому что NULL никогда не равен
-- текущей эпохе.
ALTER TABLE group_key_history ADD COLUMN IF NOT EXISTS escrow_epoch TEXT;

-- Выборка групп с устаревшей привязкой: последняя версия каждой группы и её эпоха.
-- Индекс по (group_id, gk_version DESC) уже обслуживается первичным ключом, поэтому
-- добавляется только частичный — по строкам без эпохи, которых со временем не
-- останется.
CREATE INDEX IF NOT EXISTS idx_group_key_history_no_epoch
    ON group_key_history (group_id)
    WHERE escrow_epoch IS NULL;
