-- 0029: платформа устройства. Нужна ровно для одного правила: подтверждать
-- привязку нового устройства по QR вправе только телефон (key-lifecycle.md §2) —
-- телефон остаётся якорем доверия, десктоп своё доверие наследует, а не раздаёт.
--
-- ВАЖНО про силу этой проверки: платформу устройство сообщает о себе само, и до
-- аппаратной аттестации (Play Integrity / App Attest, Фаза 6) сервер проверить
-- её не может. Это правило порядка, а не граница безопасности: изменённый клиент
-- объявит себя телефоном. Ценность до аттестации — в том, что штатный десктоп
-- физически не подтвердит привязку, а модель («якорь — телефон») зафиксирована в
-- коде и станет проверяемой в тот день, когда появится аттестация.
--
-- Пустая строка — устройства, зарегистрированные до этой миграции. Подтверждать
-- они не могут, пока клиент не объявит платформу (PUT /devices/me/platform,
-- клиент делает это при запуске) — иначе правило пришлось бы обойти для всех
-- существующих установок, и оно не значило бы ничего.
ALTER TABLE devices ADD COLUMN IF NOT EXISTS platform TEXT NOT NULL DEFAULT ''
    CONSTRAINT devices_platform_check CHECK (platform IN ('', 'android', 'ios', 'desktop'));
