-- 0055: полосы доставки — номер события внутри полосы и внутри устройства.
-- План: doc_mig/ПЛАН-ДОСТАВКИ-ПОЛОСАМИ.md, задача П3.
--
-- ── ЗАЧЕМ ЭТО, ЕСЛИ event_id УЖЕ ЕСТЬ ───────────────────────────────────────
--
-- `event_id` глобально монотонный: устройству достаются 326, 328, 330 — дыры по
-- построению, потому что 327 и 329 чужие. Клиент, увидев 330 после 326, **не может
-- отличить** «моё потерялось» от «это было не моё». Поэтому разрыв сегодня ищет
-- сервер сверкой раз в пять секунд, и стоит это запроса на соединение — живое или нет.
--
-- Номер внутри полосы и внутри устройства плотный: 1, 2, 3. Пропуск виден клиенту
-- сразу и называется полосой.
--
-- ── ПОЧЕМУ ПОЛОС ТРИ, А НЕ ОДНА ─────────────────────────────────────────────
--
-- Критерий разделения — **не объём, а опасность разрыва** (устройство Telegram,
-- doc_add/Bag/dostavka.txt):
--
--   1 (pts) — переписка. Потерянный кадр = потерянное сообщение. Порядок при этом не
--             важен: строки стоят по отметке ИЗ КАДРА, а не по порядку прихода.
--   2 (qts) — ключи. Пропущенная ротация — это не «сообщение опоздало», это
--             «сообщение не откроется никогда». Пакетированию не подлежит.
--   3 (seq) — фон: комментарии, а дальше присутствие и счётчики. Важен факт, не порядок.
--   0       — ВНЕ ПОЛОС: кадры звонка и всё, записанное до этой миграции.
--
-- Полос сегодня хватило бы и одной: мы не пакетируем, и строгость qts досталась бы
-- всем даром. Но **номер полосы живёт на устройстве**, в его курсоре. Завести третий
-- курсор на девятнадцати устройствах — правка; завести его на тысяче — переход с окном
-- совместимости. Решение заказчика 2026-09-23: платить сейчас.
--
-- Аддитивно: колонки с умолчанием 0, сервер без этого знания работает как прежде.
-- Ноль означает «номера нет», и клиент такой кадр не проверяет — см. П5.

ALTER TABLE device_events
    ADD COLUMN IF NOT EXISTS lane     SMALLINT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS lane_seq BIGINT   NOT NULL DEFAULT 0;

-- Счётчики полос живут там, где строка на устройство уже есть.
--
-- Цена названа заранее: это горячая строка на устройство, тогда как раньше запись была
-- одним INSERT с глобальной последовательностью и без блокировок. На наших числах
-- (0,96 события на устройство в сутки) это ничто, но знать об этом надо до, а не после.
ALTER TABLE sync_cursors
    ADD COLUMN IF NOT EXISTS pts BIGINT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS qts BIGINT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS seq BIGINT NOT NULL DEFAULT 0;
