-- 0046: поимённое разрешение у записи канала и ленты (ПЛАН-КАНАЛОВ К4, ADR-0019 §8).
--
-- Уровень 3 значит «по разрешению»: владелец называет, кому открыта эта запись. У групп
-- это уже стоит (`group_level_grants`), у канала и ленты не было ничего — то есть уровень
-- 3 был виден только владельцу и никому больше, и «поимённо» не работало вовсе.
--
-- РАЗРЕШЕНИЕ ДАЁТСЯ НА ЗАПИСЬ, А НЕ НА КОНТЕЙНЕР. В группе разрешение открывает участнику
-- уровень 3 во всей группе; здесь — одну запись. Разница не в реализации, а в том, что
-- просят: «покажи это ему», а не «пусть видит всё моё третьего уровня».
CREATE TABLE IF NOT EXISTS feed_level_grants (
    channel_id UUID        NOT NULL REFERENCES channels(channel_id) ON DELETE CASCADE,
    post_id    BIGINT      NOT NULL,
    user_id    UUID        NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,

    -- СРОК ЗАКРЫВАЕТ БУДУЩЕЕ, А НЕ ПРОШЛОЕ (ADR-0019 §8). Истёк — новые выдачи
    -- прекращаются; прочитанное остаётся прочитанным, и отобрать его нельзя ничем.
    --
    -- NULL значит «бессрочно» — это прямые слова заказчика: «бессрочно или до даты».
    --
    -- Здесь метка времени, а не эпоха вида «2026-09», как у групп. Причина в том, что
    -- просят разное: срок участия в группе меряется месяцами и сравнивается строками,
    -- а «покажи ему это до пятницы» месяцем не выражается.
    until      TIMESTAMPTZ,
    granted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (channel_id, post_id, user_id)
);

-- Выдача спрашивает «есть ли у этого человека живое разрешение на эту запись» на каждой
-- странице ленты, поэтому индекс по читателю, а не только первичный ключ.
CREATE INDEX IF NOT EXISTS idx_feed_grants_user
    ON feed_level_grants (user_id, channel_id, post_id);
