-- 0039: виртуальные аккаунты (ПЛАН-КОНТАКТОВ.md, Д10).
--
-- Виртуальный аккаунт — ОТДЕЛЬНЫЙ ПОЛЬЗОВАТЕЛЬ, а не второе имя: своя фраза, свои
-- ключи, своя переписка, свои права. Со стороны собеседника он неотличим от обычного
-- человека, и это цель, а не побочность.
--
-- Схема к этому оказалась готова: 0019 уже разделила аккаунт (persons) и личность
-- (users), а частичный уникальный индекс по phone_bidx написан так, что аккаунты БЕЗ
-- телефона друг другу не мешают. Значит один номер и несколько аккаунтов не ломают
-- уникальность номера: он остаётся у одного, у прочих его просто нет.
--
-- Добавляется одно поле — чей это аккаунт.
ALTER TABLE persons
    ADD COLUMN IF NOT EXISTS owner_person_id UUID REFERENCES persons(person_id);

-- Считать виртуальные аккаунты владельца приходится на каждое создание (предел 5),
-- и это единственный запрос по этому полю.
CREATE INDEX IF NOT EXISTS idx_persons_owner
    ON persons (owner_person_id) WHERE owner_person_id IS NOT NULL;

-- Владелец у виртуального аккаунта — обычный аккаунт, а не другой виртуальный.
-- Цепочка «виртуал у виртуала» превратила бы предел в пять на каждом уровне, то есть
-- в отсутствие предела; проверяется в коде, потому что в CHECK ссылка на другую строку
-- той же таблицы недоступна.
--
-- Сам себе владельцем аккаунт быть не может: строка о себе прошла бы во все выдачи
-- «мои виртуальные» и в счётчик предела.
ALTER TABLE persons DROP CONSTRAINT IF EXISTS chk_persons_owner_not_self;
ALTER TABLE persons ADD CONSTRAINT chk_persons_owner_not_self
    CHECK (owner_person_id IS NULL OR owner_person_id <> person_id);
