-- 0053: цвет участника в группе — номер оттенка полосы (решение заказчика 2026-09-19).
--
-- ── ЧТО ЭТО ─────────────────────────────────────────────────────────────────────
--
-- У чужой реплики в группе полоса слева — своего цвета у каждого автора. Сто оттенков
-- одной светлоты, у клиента два набора под тему; хранится НОМЕР ОТТЕНКА 0…99, а не цвет:
-- один номер — один оттенок в обоих наборах, и человек с тёмной темой видит тот же
-- оттенок, что человек со светлой. NULL — не выбирал: клиент назначает сам по порядку
-- первого сообщения, обходя выбранные.
--
-- Своё участие, своя группа: в разных группах у человека могут быть разные цвета.
--
-- Совпадения запрещены, пока участников не больше 80 % оттенков (79 из 99 доступных),
-- дальше — разрешены: правило заказчика, проверяется в одном UPDATE (SetMemberHue).

ALTER TABLE memberships ADD COLUMN IF NOT EXISTS hue SMALLINT;

COMMENT ON COLUMN memberships.hue IS
