-- 0052: счётчик изменений профиля (решение заказчика 2026-09-19).
--
-- ── ЗАЧЕМ ───────────────────────────────────────────────────────────────────────
--
-- Клиент держит карточки людей (имя, ник, аватар) в кэше и без сигнала не узнаёт, что
-- собеседник сменил аватар. Сигнал — не хеш и не push, а СЧЁТЧИК: растёт на каждой смене
-- имени, ника или аватара, отдаётся в событии о сообщении (`sender_profile_rev`) и в
-- `POST /users/names` (`profile_revs`). Клиент сравнивает число с запомненным и
-- переспрашивает карточку только при разнице — ноль запросов, пока ничего не менялось.
--
-- Подписанный кадр сообщения не трогается: поле лежит в обёртке события живого канала.
-- Аддитивно: столбец с умолчанием, старые клиенты поля не читают.

ALTER TABLE persons ADD COLUMN IF NOT EXISTS profile_rev INTEGER NOT NULL DEFAULT 0;

COMMENT ON COLUMN persons.profile_rev IS
  'сколько раз менялись имя, ник или аватар; клиент переспрашивает карточку при разнице';
