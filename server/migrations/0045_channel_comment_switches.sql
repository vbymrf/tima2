-- 0045: выключатели обсуждения и модераторы канала (ПЛАН-КАНАЛОВ К3, ADR-0024 §6).
--
-- ДВА ВЫКЛЮЧАТЕЛЯ, А НЕ ОДИН. «Канал без обсуждений» и «эту запись не обсуждаем» — разные
-- желания, и второе просят чаще. Один выключатель заставил бы владельца выбирать между
-- закрытым каналом и открытой записью, о которой он как раз и не хочет разговора.
ALTER TABLE channels
    ADD COLUMN IF NOT EXISTS comments_enabled BOOLEAN NOT NULL DEFAULT TRUE;

ALTER TABLE channel_posts
    ADD COLUMN IF NOT EXISTS comments_closed BOOLEAN NOT NULL DEFAULT FALSE;

-- ВЫКЛЮЧЕНО ЗНАЧИТ «НОВЫХ НЕ ПРИНИМАЕМ», А НЕ «СТАРЫЕ СТЁРТЫ». Иначе одно нажатие молча
-- убирает чужие слова, и человек, у которого разговор исчез, читает это как поломку.
-- Убрать разговор целиком — отдельное действие с отдельным вопросом, и его здесь нет.

-- МОДЕРАТОРЫ КАНАЛА — минимум ради одного ответа заказчика (2026-09-08): «владелец,
-- модератор канала может удалить любое сообщение своего канала; автор — только своё».
--
-- Это НЕ модерация целиком: ни жалоб, ни премодерации, ни медленного режима, ни
-- блокировки участника здесь нет — они в МОДЕРАЦИЯ.md и своей работой. Заведена ровно
-- роль, без которой ответ заказчика не выполняется.
--
-- Ролей две и обе выводятся: владелец — это `channels.owner_id`, модератор — строка
-- здесь. Отдельного поля «роль» с перечислением не заводится: перечисление из двух
-- значений, одно из которых уже хранится в другом месте, — это способ рассинхронизировать
-- их между собой.
CREATE TABLE IF NOT EXISTS channel_moderators (
    channel_id UUID        NOT NULL REFERENCES channels(channel_id) ON DELETE CASCADE,
    user_id    UUID        NOT NULL REFERENCES users(user_id)       ON DELETE CASCADE,
    added_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (channel_id, user_id)
);
