-- 0035: доступ по разрешению и срок участия (ADR-0019 §8–§9, ПЛАН-СОЦИУМА Г4).
--
-- ── СРОК СЧИТАЕТСЯ ЭПОХАМИ, А НЕ ДАТАМИ ──────────────────────────────────────────
--
-- Решение заказчика 2026-09-04. Эпоха escrow месячная (`escrow.EpochOf` → «2026-09»), и
-- плановая ротация ключа по ней уже работает. Выбытие участника обязано менять групповой
-- ключ (ADR-0017), поэтому срок, привязанный к эпохе, обходится нам даром: человек
-- выбывает ровно тогда, когда ключ и так сменится. Точная дата потребовала бы ежедневной
-- фоновой задачи со своей отказоустойчивостью — ради редкого случая.
--
-- Цена названа: человек читает группу до конца месяца, а не до точной даты. Это
-- говорится на экране.
--
-- Формат `YYYY-MM` выбран не для красоты: строки этого вида сравниваются лексикографически
-- так же, как даты — хронологически. Значит `until_epoch >= to_char(now(), 'YYYY-MM')`
-- работает без разбора строки и без отдельной колонки-даты.

ALTER TABLE memberships
    ADD COLUMN IF NOT EXISTS until_epoch TEXT;  -- NULL = бессрочно

-- ── ДОСТУП ПО РАЗРЕШЕНИЮ (уровень 3) ─────────────────────────────────────────────
--
-- Третий уровень — единственный, который не расходится по лентам: админ открывает его
-- поимённо. Здесь же живут ПРОСЬБЫ о доступе: предмет один и тот же, состояния разные.
-- Отдельная таблица под просьбы означала бы две записи об одном человеке и вечный вопрос,
-- какая из них правда.
--
-- Ротации ключа истечение не требует: уровень 3 существует только в публичной группе, а
-- она не шифруется. Опасение, что срок потянет за собой плановую ротацию, снято.

CREATE TABLE IF NOT EXISTS group_level_grants (
    group_id     UUID        NOT NULL REFERENCES groups(group_id) ON DELETE CASCADE,
    user_id      UUID        NOT NULL REFERENCES users(user_id)   ON DELETE CASCADE,
    level        SMALLINT    NOT NULL DEFAULT 3 CHECK (level BETWEEN 0 AND 3),
    state        TEXT        NOT NULL DEFAULT 'asked'
                             CHECK (state IN ('asked', 'granted', 'declined')),
    until_epoch  TEXT,                       -- NULL = бессрочно
    asked_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    granted_at   TIMESTAMPTZ,
    granted_by   UUID,
    PRIMARY KEY (group_id, user_id)
);

-- Очередь админа: «кто просит доступ» — экран Г9.
CREATE INDEX IF NOT EXISTS idx_glg_asked
    ON group_level_grants (group_id, asked_at DESC) WHERE state = 'asked';
