-- 0049: страна и язык (ПЛАН-ЯЗЫКА Я5, решение заказчика 2026-09-08).
--
-- ЗАЧЕМ ОНИ НУЖНЫ — ровно две задачи, и других на этом этапе нет:
--
--   • клиенту — отсеивать ненужное;
--   • серверу — готовить региональные и языковые ленты.
--
-- Отсюда и место колонок: **только у того, что попадает в выдачу**. Личная переписка не
-- попадает ни в одну ленту и ни в один отбор — она приходит адресно тому, кому послана,
-- и поле там никто не прочтёт. Поэтому `personal_messages` эта миграция не трогает вовсе.
--
-- Прежняя редакция плана предлагала колонки у всех сообщений, включая личные. Отменено
-- заказчиком 2026-09-08 вместе с назначением: где нет выдачи, там и полей нет.

-- ── У ЧЕЛОВЕКА ──────────────────────────────────────────────────────────────
--
-- Страна берётся ИЗ НАСТРОЕК и меняется только там: ни по адресу сети, ни по SIM. Поездка
-- не должна молча менять то, что человеку показывают, а адрес сети у половины людей чужой.
--
-- Умолчание языка — русский, страны — пусто. Пустая страна значит «не указана»: такой
-- человек видит всё, а не ничего. Обратное закрыло бы выдачу всем, кто ещё не дошёл до
-- настроек.
ALTER TABLE users
    ADD COLUMN IF NOT EXISTS lang    TEXT NOT NULL DEFAULT 'ru',
    ADD COLUMN IF NOT EXISTS country TEXT NOT NULL DEFAULT '';

-- ── У ЗАПИСИ ────────────────────────────────────────────────────────────────
--
-- Страна ставится ШТАМПОМ при публикации, из профиля автора, а не берётся у автора при
-- чтении. Иначе переезд автора переписывает прошлое: его прежние записи разом уезжают из
-- ленты той страны, где всё это время лежали.
ALTER TABLE channel_posts
    ADD COLUMN IF NOT EXISTS lang    TEXT NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS country TEXT NOT NULL DEFAULT '';

-- У сообщений групп — те же две колонки и по той же причине: сообщение публичной группы
-- уровня ≥ 0 индексируется и ищется (ADR-0019 §5), то есть попадает в выдачу. У
-- зашифрованных (−1) они останутся пустыми: там нечего отбирать, и заполнять их значило
-- бы рассказывать о разговоре, которого сервер не видит.
ALTER TABLE group_messages
    ADD COLUMN IF NOT EXISTS lang    TEXT NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS country TEXT NOT NULL DEFAULT '';

-- Отбор идёт по паре «страна и язык» на каждой странице выдачи, поэтому индекс по паре, а
-- не два по одному: условие всегда стоит вместе.
CREATE INDEX IF NOT EXISTS idx_cp_locale
    ON channel_posts (country, lang, post_id DESC) WHERE parent_post_id IS NULL AND NOT deleted;
