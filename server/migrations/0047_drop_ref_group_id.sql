-- 0047: снятие переходной пары полей адреса (решение заказчика 2026-09-08, вариант B).
--
-- В 0044 адрес принесённой записи стал тройкой «вид, контейнер, запись», а прежняя
-- колонка `ref_group_id` осталась жить пустой — потому что действовало правило «удаление
-- колонки идёт следующим выпуском» (ПРАВИЛА-РАБОТЫ §2.1).
--
-- Правило смягчено заказчиком: на этом этапе таблицы правятся без сохранения старых
-- данных. Значит колонке незачем стоять пустой и объяснять собой отменённое правило —
-- каждый, кто её увидит, примет её за смысл.
--
-- ЭТО ЕДИНСТВЕННЫЙ СЛОМ, И ОН РАЗОВЫЙ. Вместе с колонкой уходят поле `ref_group_id` из
-- ответа ленты и поле `group_id` из запроса переноса. Ни одна другая работа из трёх
-- планов слома не требует: комментарии, модерация, разрешения, сообщества, язык и общая
-- лента — это новые маршруты и новые необязательные поля.
ALTER TABLE channel_posts DROP CONSTRAINT IF EXISTS chk_cp_ref_pair;
DROP INDEX IF EXISTS idx_cp_ref_once;
ALTER TABLE channel_posts DROP COLUMN IF EXISTS ref_group_id;

