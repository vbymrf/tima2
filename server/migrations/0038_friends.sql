-- 0038: друзья — список аккаунта (ПЛАН-КОНТАКТОВ.md, Д1б).
--
-- Раньше друзей не было как сущности: «друг — тот, кто в книге» (интерфейс.md §12).
-- Правило держалось на том, что книга есть у каждого. У виртуального аккаунта её нет
-- и не будет — телефона у него нет по определению, — и правило перестало работать
-- для половины аккаунтов. Отсюда отдельный список, который правит сам аккаунт.
--
-- Связь на persons, а не на users: друзья принадлежат аккаунту, как телефон и ник, и
-- обязаны пережить смену личности (0019). Дружба с личностью означала бы, что потеря
-- ключей стирает круг общения.
CREATE TABLE IF NOT EXISTS friends (
    owner_id   UUID        NOT NULL REFERENCES persons(person_id) ON DELETE CASCADE,
    friend_id  UUID        NOT NULL REFERENCES persons(person_id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (owner_id, friend_id),
    -- Сам себе не друг: строка о себе прошла бы во все выдачи «мои друзья» и
    -- в аудиторию личной группы, где означала бы «показывать себе».
    CONSTRAINT chk_friends_not_self CHECK (owner_id <> friend_id)
);

-- Кто меня добавил. Нужен не для показа (связь односторонняя и взаимности мы не
-- обещаем), а для уборки: удаляемый аккаунт исчезает из чужих списков.
CREATE INDEX IF NOT EXISTS idx_friends_friend ON friends (friend_id);

