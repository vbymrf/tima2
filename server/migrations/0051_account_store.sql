-- 0051: зашифрованная копия личных данных аккаунта — книга и разделы (ПЛАН-РАЗДЕЛОВ Р2а;
-- решение заказчика 2026-09-18).
--
-- ── ЧТО ЭТО ─────────────────────────────────────────────────────────────────────
--
-- Книга контактов и её разделы живут у клиента и должны быть одинаковыми на всех
-- устройствах человека. Сервер держит КОПИЮ — блобом, который не читает: содержимое
-- зашифровано ключом служебной группы аккаунта (группа `private` с единственным
-- участником, ключ заворачивается на каждое устройство человека той же механикой, что у
-- любой группы — group_wrapped_keys, group_key_history). Серверу от блоба нужны две вещи:
-- отдать его другому устройству и не дать двум устройствам затереть друг друга.
--
-- ── ОТКРЫТО — РЕВИЗИЯ И УСТРОЙСТВО ──────────────────────────────────────────────
--
-- revision растёт на каждое сохранение; запись принимается только с revision = текущая + 1,
-- иначе 409 — клиент забирает свежее, сливает и повторяет. device_id — какое устройство
-- сохранило: для человека это подпись «T1 / P2», для разбора — кто последний.
--
-- ── ОДНА СТРОКА НА (АККАУНТ, ВИД) ───────────────────────────────────────────────
--
-- kind — 'book' сейчас; другие виды (настройки, разделы сообществ) заводятся тем же
-- механизмом, своим kind. Строка одна на вид: история ревизий серверу не нужна, слияние
-- делают клиенты у себя, построчно, по штампам внутри блоба.
CREATE TABLE IF NOT EXISTS account_store (
    user_id    UUID        NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    kind       TEXT        NOT NULL,
    revision   BIGINT      NOT NULL,
    device_id  UUID        NOT NULL,
    blob       BYTEA       NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, kind)
);

COMMENT ON TABLE account_store IS
    'Зашифрованная копия личных данных аккаунта по видам; сервер содержимого не читает';
COMMENT ON COLUMN account_store.revision IS
    'Растёт на каждое сохранение; принимается только текущая + 1';
COMMENT ON COLUMN account_store.device_id IS
    'Устройство, сохранившее эту ревизию';

-- Служебная группа аккаунта: одна на человека, private, участник — он сам. Через неё
-- заворачивается ключ копии. Отдельная колонка у users, а не поиск по title: у служебной
-- группы нет ни имени, ни каталога, и находить её надо за один шаг.
ALTER TABLE users
    ADD COLUMN IF NOT EXISTS store_group_id UUID REFERENCES groups(group_id);

COMMENT ON COLUMN users.store_group_id IS
    'Служебная private-группа аккаунта: её ключом шифруется копия личных данных';
