-- 0026: узлы и разметка в постах канала — публичный контур (ADR-0011 §4/§5, Р5б).
--
-- Приватный контур (личные и групповые сообщения) хранит nodes/markup ВНУТРИ
-- зашифрованной нагрузки — база их не видит и не меняется вовсе. Публичный контур
-- наоборот: канал — открытая трансляция (data-model.md §3, communities.md), сервер
-- вправе видеть и со временем искать по содержимому, поэтому nodes/markup здесь
-- лежат открытым текстом отдельными колонками.
--
-- text остаётся: тот же переходный путь, что и в личных сообщениях (ADR-0011,
-- «Последствия») — клиент, ещё не знающий про узлы, прочитает text и покажет пост
-- без оформления вместо пустого поста.
--
-- markup_version — не версия ФОРМАТА markup (та уже есть внутри самого JSON,
-- Markup.version в messenger-crypto), а типизированная колонка метаданных поста
-- (ADR-0011 §5: «основные метаданные — колонками, закрытым списком»), чтобы гейты
-- будущих правок формата могли фильтровать посты по версии без разбора JSONB.

ALTER TABLE channel_posts
    ADD COLUMN nodes          TEXT[]      NOT NULL DEFAULT '{}',
    ADD COLUMN markup         JSONB,
    ADD COLUMN markup_version INT         NOT NULL DEFAULT 1;

-- Существующие посты: единственный узел = их текущий text. Без этого лента старых
-- постов читалась бы как посты без содержимого до первой правки.
UPDATE channel_posts SET nodes = ARRAY[text] WHERE nodes = '{}';
