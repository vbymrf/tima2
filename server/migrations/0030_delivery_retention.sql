-- 0030: сроки доставки переезжают из переменных окружения в retention_policy.
--
-- Почему. В internal/store/retention.go записан замысел: «сроки живут в базе, а не
-- в коде: смена требования должна быть правкой строки, а не пересборкой». Восемь
-- политик ему следуют. А 90 дней — срок, после которого сервер перестаёт выдавать
-- историю устройству, — жили в TIMA_RETENTION_DAYS, то есть менялись только
-- перевыкаткой. Вышло наоборот от замысла: срок жизни аккаунта правится строкой, а
-- срок выдачи истории — нет.
--
-- Одна политика на три таблицы — намеренно. device_events, personal_message_keys и
-- group_wrapped_keys чистятся ОДНИМ сроком: журнал событий ссылается на те же
-- сообщения, и разные сроки дали бы состояние «событие есть, а ключа к нему уже
-- нет». Разделять сроки можно будет отдельным решением, а не побочно.
--
-- Что этот срок НЕ удаляет: конверты personal_messages и group_messages. Они живут
-- до escrow-архива (0008_gc.sql), и personal_message_backup в уборку не входит
-- вовсе — то есть восстановление своей истории на новом устройстве этим сроком не
-- ограничено.
--
-- Аддитивно: строки добавляются, ничего не меняется и не удаляется. Сервер, не
-- знающий про эти политики, их просто не читает.

INSERT INTO retention_policy (name, days, description) VALUES
    ('delivery_retention_days', 90,
     'Сколько сервер ещё может доставить: обёртки ключей (personal_message_keys, group_wrapped_keys) и журнал событий device_events. Конверты сообщений НЕ удаляются'),
    ('appeal_window_days',      30,
     'Окно апелляции: сколько wrapped_GK живут у вышедшего из группы после left_at (crypto-protocol §4.2)')
ON CONFLICT (name) DO NOTHING;
