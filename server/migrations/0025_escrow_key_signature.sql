-- 0025: подпись анклава над записью реестра escrow (ПЛАН-РЕФАКТОРИНГА.md Р2).
--
-- Без неё компрометация бэкенда позволяет подменить public_key, который клиент
-- получает через /api/v1/escrow/*: клиент зашифровал бы сообщение на чужой ключ
-- в обход анклава и всего механизма контролируемого доступа (порог долей,
-- аудит, срок уничтожения). Анклав подписывает запись ключом Ed25519, который
-- живёт только у него; колонка здесь — такой же кэш, как и остальные поля
-- реестра, приватного материала нет.
--
-- escrow_keys — кэш, а не источник истины (см. комментарий SaveEscrowKey):
-- анклав хранит соответствие «область → id» у себя в scope/, поэтому очистка
-- кэша безопасна — при следующем запросе строка перечитается у анклава заново,
-- уже с подписью. Бэкфилла старых строк выдуманной подписью не делаем: заведомо
-- некорректное значение хуже честного пересчёта.

TRUNCATE escrow_keys;

ALTER TABLE escrow_keys
    ADD COLUMN signature BYTEA NOT NULL CHECK (octet_length(signature) = 64);
