-- 0054: журнал звонков — своё поле «кто положил трубку» и свой срок хранения.
-- План: doc_mig/ПЛАН-ЖУРНАЛА-ЗВОНКОВ.md, задачи Ж4 и Ж5.
--
-- ── ended_by: отличить «отменил» от «отклонил» ──────────────────────────────
--
-- POST /calls/{id}/end зовут обе стороны, и состояние выходит одно — `missed`. Но
-- читается оно по-разному: звонивший видит «не дозвонился», вызываемый — либо
-- «пропущенный» (не успел), либо «отклонённый» (нажал отбой). Сегодня различить их
-- нечем: кто нажал первым, в базе не остаётся.
--
-- Человек эти три случая различает и поступает по-разному, поэтому журнал, который
-- их смешивает, лжёт. Лечится одним полем: кто закрыл звонок.
--
-- ── calls_journal_days = 0: журнал звонков не удаляется ─────────────────────
--
-- Уборщик звонков брал `delivery_retention_days` — срок, отвечающий на вопрос
-- «сколько сервер ещё способен доставить». Это чужое число: опусти его до недели
-- ради места, и журнал звонков молча станет недельным.
--
-- Но развязать оказалось мало: **удалять было нечего с самого начала.** В строке
-- звонка нет ничего, кроме метаданных — кто, кому, когда, чем кончилось, — а у нас
-- записано правилом и охраняется тестом (`store/retention.go` PurgeMessageContent,
-- `api/retention_test.go`): у сообщения стирается СОДЕРЖИМОЕ, строка метаданных
-- живёт. Звонок из этого правила выпал по недосмотру: уборка появилась 2026-09-20 с
-- доводом «таблица растёт навсегда», то есть довод был про место, а решение вышло
-- про метаданные.
--
-- **0 означает «не удалять».** Уборщик при нуле задачу пропускает. Строка политики
-- остаётся, а не выбрасывается: исключение должно быть видно в таблице сроков рядом
-- с прочими, а не спрятано в коде, — и передумать тогда можно правкой строки, ради
-- чего `retention_policy` и заведена.
--
-- Стирает звонки по-прежнему ровно одно: стирание аккаунта (`account_purge_days`),
-- то есть ручной запрос человека. Решение заказчика 2026-09-23.
--
-- Аддитивно: колонка с NULL по умолчанию, строка политики добавляется. Сервер, не
-- знающий про них, работает как прежде.

ALTER TABLE calls
    ADD COLUMN IF NOT EXISTS ended_by UUID;

INSERT INTO retention_policy (name, days, description) VALUES
    ('calls_journal_days', 0,
     '0 = НЕ УДАЛЯТЬ. Строка звонка — одни метаданные, а они не удаляются никогда (см. PurgeMessageContent). Число больше нуля включает уборку по этому сроку')
ON CONFLICT (name) DO NOTHING;

-- Журнал спрашивает «мои звонки» — то есть initiator_id ИЛИ peer_id. Индекс на
-- peer_id есть с 0014; для второй половины условия его не было, и выборка шла
-- перебором таблицы.
CREATE INDEX IF NOT EXISTS idx_calls_initiator ON calls(initiator_id, created_at DESC);
