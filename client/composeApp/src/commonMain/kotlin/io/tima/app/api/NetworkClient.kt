package io.tima.app.api

import io.ktor.client.HttpClient
import kotlinx.serialization.json.Json

/**
 * Сроки ожидания сети. Рассчитаны на МОБИЛЬНУЮ связь, а не на Wi-Fi.
 *
 * До этих значений клиент работал на умолчаниях движка — 10 секунд на соединение,
 * 10 на чтение, 10 на запись. На Wi-Fi этого хватало с запасом, и потому промах не
 * был виден. В сети 4G рукопожатие TLS плюс разрешение имени укладываются в 10 секунд
 * не всегда, и приложение переставало работать целиком: ни сообщений, ни истории,
 * ни WS. В журнале это выглядело как ровная череда «Read timed out» с шагом ровно
 * десять секунд — след нашего собственного таймера, а не сети.
 *
 * Общий принцип здесь: ограничение ставим на ОТСУТСТВИЕ ПРОГРЕССА, а не на общую
 * длительность. Файл на 11 МБ по мобильной сети идёт полторы минуты — и это
 * нормальная работа, а не зависание. Зависание — это когда за [SOCKET_MS] не пришло
 * и не ушло ни одного байта.
 */
object NetworkTuning {
    /** Установка TCP+TLS. Мобильная сеть под нагрузкой даёт задержки в секунды. */
    const val CONNECT_MS = 20_000L

    /** Тишина в уже открытом соединении. Дольше — считаем мёртвым. */
    const val SOCKET_MS = 40_000L

    /**
     * Ping WebSocket. Двойная польза: не даёт оператору выбросить простаивающее
     * соединение из таблицы NAT и обнаруживает мёртвый канал — без ping клиент
     * считает себя на связи, пока не попробует написать. Отсюда и «звонок висит
     * бесконечно, сообщения об обрыве нет».
     */
    const val WS_PING_MS = 20_000L
}

/**
 * HTTP/WS-клиент с настроенными сроками ожидания. Создаётся на платформе: движок
 * (OkHttp) в общий код не виден, а сроки задаются именно на движке — плагин
 * HttpTimeout не распространяется на WebSocket.
 */
expect fun createHttpClient(json: Json): HttpClient
