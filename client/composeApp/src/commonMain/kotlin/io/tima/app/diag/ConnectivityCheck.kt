/**
 * Самопроверка связи по шагам.
 *
 * «Приложение не достучалось до сервера» — это не одна поломка, а пять разных, и
 * лечатся они по-разному:
 *
 *  1. имя не разобралось     → сломан DNS оператора (или сеть ещё не поднялась);
 *  2. TCP не установился     → адрес недостижим, порт закрыт, трафик режется;
 *  3. TLS не сложился        → в середине посредник или обрезан размер пакета;
 *  4. HTTP не ответил        → сервер или его edge;
 *  5. WebSocket не поднялся  → посредник не пропускает переход на другой протокол.
 *
 * Отличить их снаружи невозможно, а SIM-карта есть только у испытателя. Поэтому
 * проверку делает сам телефон и называет шаг вслух.
 */
