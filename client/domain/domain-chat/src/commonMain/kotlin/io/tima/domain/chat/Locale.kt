package io.tima.domain.chat

/**
 * Страна и язык человека (ПЛАН-ЯЗЫКА Я7).
 *
 * **Две задачи и никаких других** (решение заказчика 2026-09-08): клиенту отсеивать
 * ненужное, серверу готовить региональные и языковые ленты. Перевода сообщений нет вовсе.
 *
 * **Страна берётся из настроек и меняется только там** — ни по адресу сети, ни по SIM:
 * поездка не должна молча менять то, что человеку показывают, а адрес сети у половины
 * людей чужой.
 */
data class PersonLocale(
    /** Тег языка, на котором человек пишет: `ru`, `en`, `es`. */
    val lang: String = "ru",
    /** Код страны. Пусто — «не указана»: такой человек видит всё, а не ничего. */
    val country: String = "",
)

/**
 * Отбор выдачи (ПЛАН-ЯЗЫКА Я6).
 *
 * **Два независимых переключателя** — решение заказчика 2026-09-08. Выключены оба —
 * приходит всё; выключен один — работает второй.
 *
 * **Настройка живёт здесь, а отбор делает сервер.** Клиент кладёт её в параметры запроса;
 * отфильтровать полученное можно у списка контактов, но не у ленты, которая листается:
 * сервер отдал двадцать записей, показали три — и лента кончилась на середине.
 *
 * **Лента друзей не фильтруется никогда.** Друг уехал или написал на другом языке — он
 * остаётся другом, и прятать его человек не просил. Отбор работает в общей ленте, каталоге
 * и поиске, и потому эти настройки не касаются переписки вовсе.
 */
data class FeedFilter(
    val onlyMyCountry: Boolean = true,
    val onlyMyLanguages: Boolean = true,
    /** Какие языки читать. Пусто — язык приложения: он и есть ответ по умолчанию. */
    val languages: List<String> = emptyList(),
) {
    /** Страна для запроса. Пусто — отбора по стране нет. */
    fun countryFor(locale: PersonLocale): String = if (onlyMyCountry) locale.country else ""

    /** Языки для запроса. Пусто — отбора по языку нет. */
    fun languagesFor(locale: PersonLocale): List<String> = when {
        !onlyMyLanguages -> emptyList()
        languages.isNotEmpty() -> languages
        else -> listOf(locale.lang)
    }
}

/** Порт к серверу: страна и язык в профиле. */
interface PersonLocales {
    suspend fun read(): PersonLocale?
    suspend fun write(locale: PersonLocale): Boolean
}
