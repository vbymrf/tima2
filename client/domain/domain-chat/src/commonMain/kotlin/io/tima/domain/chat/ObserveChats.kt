package io.tima.domain.chat

import kotlinx.coroutines.flow.Flow

/**
 * Список переписок — первый экран, который человек видит чаще чата.
 *
 * **Класс тонкий по той же причине, что [ObserveChat]:** здесь только границы страницы.
 * Порядок, число непрочитанных и то, откуда берётся превью, выражены в SQL и живут в
 * переходнике — там, где видно обе машины состояний.
 *
 * Главное решение лежит ниже, в схеме, и его стоит назвать и здесь: **список выводится
 * из сообщений**, а таблица `chats` только добавляет переписке имя. Поэтому список не
 * может потерять переписку из-за незаведённой строки, и превью не может разойтись с тем,
 * что видно в самом чате. В v1 список чатов лежал одновременно в SQLite и в `chats.json`,
 * и они расходились молча.
 */
class ObserveChats(private val feed: ChatsFeed) {

    /**
     * Поток списка: обновляется сам, когда меняется база.
     *
     * @param limit сколько переписок. Страницами, а не целиком: у человека их бывают
     *   тысячи, а на экране — двадцать строк.
     */
    fun list(limit: Int = DEFAULT_PAGE): Flow<List<ChatSummary>> {
        require(limit in 1..MAX_PAGE) { "страница вне пределов 1..$MAX_PAGE: $limit" }
        return feed.list(limit)
    }

    companion object {
        const val DEFAULT_PAGE: Int = 50

        /** Предел страницы: каждая строка несёт расшифрованное превью, и это память. */
        const val MAX_PAGE: Int = 300
    }
}

/**
 * Строка списка переписок — то, что видит человек.
 *
 * Всё, кроме [title] и [kind], **выведено из сообщений**: превью, время, направление,
 * состояние отправки, число непрочитанных.
 */
data class ChatSummary(
    val chatId: String,
    /**
     * Имя переписки. `null` — имени ещё нет: профиль не приезжал, а выдумывать нечего.
     *
     * Экран в этом случае показывает то, что знает сам, — но переписку не прячет:
     * сообщение есть, значит есть и строка.
     */
    val title: String?,
    val kind: ChatKind,
    /** Собеседник личной переписки: по нему берутся его ключи и открывается страница. */
    val peerId: String?,
    /**
     * Первая строка последнего сообщения. `null` — читать нечего: у входящего ещё не
     * прошёл разбор, либо оно не расшифровалось.
     */
    val preview: String?,
    /** Последнее сообщение — моё. От этого зависит, показывать ли отметку отправки. */
    val lastOutgoing: Boolean,
    /** Что стало с последним сообщением. */
    val lastDisplay: MessageDisplay,
    /** Время последнего сообщения: серверное, если есть, иначе часы устройства. */
    val atMs: Long,
    /**
     * Непрочитанных — **только входящих**: «непрочитанным своё сообщение» не бывает.
     */
    val unread: Int,
)

/**
 * Вид переписки.
 *
 * Столбец в базе, а не вывод из `chat_id`: вид решает, что показывать в шапке и кто
 * участники, а угадывать его по идентификатору значило бы завязаться на способ, которым
 * идентификатор построен.
 */
enum class ChatKind { Personal, Group }

/** Порт к списку переписок. Реализуется `core-database`. */
fun interface ChatsFeed {
    fun list(limit: Int): Flow<List<ChatSummary>>
}
