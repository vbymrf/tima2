package io.tima.domain.chat

/**
 * Журнал звонков **на сервере** — Ж1, `GET /api/v1/calls`.
 *
 * Отдельным портом от [CallLog], хотя возят они одни и те же строки. [CallLog] — местная
 * копия, этот — источник правды. Сложить их в один интерфейс значило бы сделать
 * незаметным главное различие: одно переживает потерю сети, другое её и требует.
 */
interface CallHistory {

    /**
     * Страница прошлого, новые сверху.
     *
     * @param beforeMs продолжить с этого времени; `0` — первая страница.
     * @return `null` — **до сервера не дошли**. Не «звонков нет»: местную копию в этом
     *   случае не трогают, потому что пустой ответ и отсутствие ответа — разные вещи, и
     *   спутать их значит стереть журнал при первом же походе в метро.
     */
    suspend fun page(beforeMs: Long = 0, limit: Int = 30): CallHistoryPage?
}

/**
 * Страница журнала с сервера.
 *
 * @param nextBeforeMs с чего продолжать, если долистают до низа; `0` — продолжения нет.
 *   Обещается только когда страница полна: иначе клиент ходил бы за пустотой один раз на
 *   каждое открытие журнала, и заметно это было бы ровно у тех, у кого звонков мало.
 */
data class CallHistoryPage(
    val records: List<CallRecord>,
    val nextBeforeMs: Long = 0,
)
