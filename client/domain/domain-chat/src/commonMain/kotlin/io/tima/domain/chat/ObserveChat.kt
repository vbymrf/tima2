package io.tima.domain.chat

import kotlinx.coroutines.flow.Flow

/**
 * Чтение переписки — вторая половина К4.1.
 *
 * **Почему класс тонкий, и почему это правильно.** Здесь только то, что решает
 * продукт: границы страницы и отказ на бессмысленный запрос. Перевод состояния очереди
 * в то, что показывают человеку, живёт НЕ здесь — словарь очереди (`OutboxState`) лежит
 * слоем ниже, и `domain-chat` его не видит; видеть и не может, иначе получилось бы
 * кольцо зависимостей (`core-outbox` уже зависит от `domain-chat`). Переводит
 * переходник в `core-database`, там же живёт и порядок — он выражен в SQL.
 *
 * Соблазн написать здесь «перевод», возвращающий то же самое, был, и в первой версии я
 * его написал. Такая функция хуже отсутствующей: выглядит как правило, а не делает
 * ничего.
 *
 * Два правила, которые при этом обязаны держаться и проверяются на переходнике:
 *
 * **1. Видно всё, включая неотправленное.** Незавершённое и видимое — разные вопросы.
 * Сообщение, которое не ушло, из очереди уходит (состояние терминальное), а из
 * переписки — нет: иначе человек не узнает, что оно не дошло, и будет ждать ответа на
 * то, чего собеседник не получал.
 *
 * **2. Порядок устойчив.** Смешанный список — часть сообщений отправлена и получила
 * серверное время, часть ещё лежит в очереди с одним местным — не должен
 * переставляться на глазах. Отсюда сортировка «серверное, если есть, иначе местное», а
 * при равенстве — по порядку появления в базе.
 */
class ObserveChat(private val feed: ChatFeed) {

    /**
     * Поток страницы переписки: обновляется сам, когда база меняется.
     *
     * @param limit сколько последних сообщений. Страницами, а не целиком: переписка
     *   живёт годами, а окно на экране — двадцать строк.
     */
    fun page(chatId: String, limit: Int = DEFAULT_PAGE): Flow<List<ChatLine>> {
        require(chatId.isNotBlank()) { "chatId пустой" }
        require(limit in 1..MAX_PAGE) { "страница вне пределов 1..$MAX_PAGE: $limit" }
        return feed.page(chatId, limit)
    }

    companion object {
        const val DEFAULT_PAGE: Int = 50

        /**
         * Предел страницы. Не «круглое число»: страница целиком лежит в памяти и целиком
         * расшифрована, а бюджет памяти §3.7 — вещь измеримая.
         */
        const val MAX_PAGE: Int = 500
    }
}

/**
 * Строка переписки — то, что видит человек.
 *
 * **Текст здесь есть, и в первой редакции его не было.** Тогда рядом стояло «тела здесь
 * нет: держать в списке тексты всей истории значило бы платить памятью за то, что не
 * показано» — и это противоречило соседнему абзацу про [ObserveChat.MAX_PAGE], где
 * предел страницы обоснован ровно тем, что «страница целиком лежит в памяти и целиком
 * расшифрована». Списка «всей истории» не бывает: страница — это окно на экране, и её
 * тексты как раз те, что показаны. Второй способ, «текст приезжает отдельно по строке»,
 * стоил бы запроса на каждую видимую строку и мигания на прокрутке.
 */
data class ChatLine(
    val dedupKey: String,
    val chatId: String,
    /** Что показать рядом с сообщением. */
    val display: MessageDisplay,
    /**
     * Текст сообщения. `null` — тело не читается: ключа нет, подпись не сошлась или
     * формат из версии новее нашей.
     *
     * Нечитаемое сообщение всё равно остаётся строкой в переписке. Спрятать его нельзя:
     * человек должен видеть, что сообщение было, — иначе он ждёт ответа на то, чего
     * собеседник, по его сведениям, не присылал.
     */
    val text: String? = null,
    val outgoing: Boolean,
    /** Серверное время, если сообщение дошло; иначе местное время постановки. */
    val atMs: Long,
    /** Порядок появления в базе — развязка при равном времени. */
    val localId: Long,
    /**
     * Идентификатор, назначенный сервером. `0` — сообщение ещё не дошло.
     *
     * Нужен для действий над уже отправленным: сузить круг можно только тому, что у
     * сервера есть, и назвать это сообщение можно только его номером. Местный ключ знает
     * лишь наше устройство.
     */
    val serverId: Long = 0,
    /**
     * Кто написал. `null` — своё сообщение либо автор ещё не установлен: он берётся из
     * проверенной подписи, а до разбора его нет.
     *
     * Нужен группе, и только ей: в личной переписке собеседник один, и подписывать
     * каждое сообщение его именем — шум. В группе наоборот: без автора реплика теряет
     * смысл, потому что «кто это сказал» и есть половина сообщения.
     */
    val senderId: String? = null,
    /**
     * Круг сообщения (ADR-0019): −1 шифр, 0…3 открытые.
     *
     * Показывается меткой у реплики — и только когда человек сам включил показ: обычному
     * участнику метка отвечает на вопрос, которого у него нет. Он и так видит ровно то,
     * что ему открыто.
     */
    val level: Int = -1,
)

/**
 * Состояние сообщения глазами человека.
 *
 * Их пять на шесть состояний очереди плюс входящие: различие «в очереди» и «конверт
 * собран» для человека не существует — это одно ожидание, — а вот «получено» и
 * «получено, но не читается» различать обязательно: второе требует показать, что
 * сообщение было.
 */
enum class MessageDisplay {
    /** Ждёт отправки: сеть, срок повтора, очередь. */
    PENDING,

    /** Сервер принял. */
    SENT,

    /** Не ушло и не уйдёт: требует решения человека. */
    FAILED,

    /** Получено от собеседника. */
    RECEIVED,

    /** Получено, но не читается: ключа нет или подпись не сошлась. */
    UNREADABLE,

    /**
     * Служебная строка: её написал не человек, а событие — например сужение круга.
     *
     * Отдельное значение, а не «входящее без автора»: у служебной строки нет подписи, и
     * если бы она выглядела как обычное сообщение, подделку было бы нечем отличить от
     * настоящего оповещения.
     */
    SYSTEM,
}

/**
 * Порт к хранилищу переписки. Реализуется `core-database`.
 *
 * Поток, а не список: экран обязан обновляться сам, когда приходит сообщение или
 * меняется состояние отправки. Опрос по таймеру давал бы в v1 и задержку, и лишние
 * пробуждения.
 */
fun interface ChatFeed {
    fun page(chatId: String, limit: Int): Flow<List<ChatLine>>
}

/**
 * Порт имён авторов. Реализуется составлением в `shared` поверх справочника.
 *
 * Нужен только групповой переписке. В личной собеседник один, его имя стоит в шапке, и
 * повторять его у каждой реплики — шум, от которого экран перестают читать.
 */
fun interface ChatNames {
    /** Имя или номер. Пустого ответа не бывает: строка без автора хуже, чем номер. */
    suspend fun name(userId: String): String
}
