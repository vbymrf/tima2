package io.tima.domain.chat

/**
 * Переписка открыта — значит прочитана.
 *
 * **Правило продукта, а не удобство экрана.** Счётчик непрочитанного отвечает на вопрос
 * «есть ли что-то, чего я не видел». Человек открыл переписку и смотрит в неё — значит
 * видел; оставить янтарную точку в этот момент значит соврать ему в единственном месте,
 * где он на нас полагается.
 *
 * **Прочитанным становится только разобранное.** Неразобранное и нечитаемое остаются
 * непрочитанными: человек их не читал и, возможно, ещё прочитает — когда придёт ключ.
 * Предусловие держит машина входящих, а не этот класс.
 */
class MarkRead(
    private val marks: ReadMarks,
    private val effects: ReadEffects = ReadEffects { _, _ -> },
) {

    /**
     * [upToMs] — время позднейшего входящего на экране (время приёма сервером, как у самих
     * сообщений); 0 — входящих нет.
     *
     * @return сколько сообщений стало прочитанными. Ноль — обычное дело: переписку
     *   открывают чаще, чем в ней появляется новое.
     */
    fun chat(chatId: String, upToMs: Long = 0): Int {
        require(chatId.isNotBlank()) { "chatId пустой" }
        val marked = marks.markChatRead(chatId)
        effects.read(chatId, upToMs)
        return marked
    }

    /** То же правило с последствиями за пределами своей базы — их даёт сборка. */
    fun with(effects: ReadEffects): MarkRead = MarkRead(marks, effects)
}

/**
 * Что ещё следует из «прочитано», кроме своей базы: снять уведомления, отдать отметку своим
 * устройствам, отправить «прочитано» собеседнику (его зелёные галочки).
 *
 * **Одно событие — все последствия разом** (заказчик 2026-11-16: «лучше если код будет единый,
 * тогда меньше вероятность расхождения»). Раньше «прочитано» собеседнику уходило из экрана само,
 * при первом показе входящего, а уведомления снимались через 3 секунды просмотра: отправитель
 * видел зелёные галочки, а у получателя висело уведомление. Теперь решает одно место — `ChatStore`
 * по признаку «переписку видят», — и зовёт [MarkRead.chat], а тот — этот порт.
 */
fun interface ReadEffects {
    fun read(chatId: String, upToMs: Long)
}

/**
 * Порт к отметкам прочтения. Реализуется `core-database` через машину входящих.
 *
 * Отметки для СОБЕСЕДНИКА (галочки у него) — [ReadEffects]: тот же момент, другой порт.
 * Здесь только своё «я видел».
 */
fun interface ReadMarks {
    fun markChatRead(chatId: String): Int
}
