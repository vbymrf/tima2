package io.tima.domain.chat

/**
 * Переписка открыта — значит прочитана.
 *
 * **Правило продукта, а не удобство экрана.** Счётчик непрочитанного отвечает на вопрос
 * «есть ли что-то, чего я не видел». Человек открыл переписку и смотрит в неё — значит
 * видел; оставить янтарную точку в этот момент значит соврать ему в единственном месте,
 * где он на нас полагается.
 *
 * **Прочитанным становится только разобранное.** Неразобранное и нечитаемое остаются
 * непрочитанными: человек их не читал и, возможно, ещё прочитает — когда придёт ключ.
 * Предусловие держит машина входящих, а не этот класс.
 */
class MarkRead(private val marks: ReadMarks) {

    /**
     * @return сколько сообщений стало прочитанными. Ноль — обычное дело: переписку
     *   открывают чаще, чем в ней появляется новое.
     */
    fun chat(chatId: String): Int {
        require(chatId.isNotBlank()) { "chatId пустой" }
        return marks.markChatRead(chatId)
    }
}

/**
 * Порт к отметкам прочтения. Реализуется `core-database` через машину входящих.
 *
 * Отметки для СОБЕСЕДНИКА (галочки у него) — другое дело и другой порт: они уходят на
 * сервер (`POST /chats/{id}/read`) и появятся вместе с ними. Здесь только своё «я видел».
 */
fun interface ReadMarks {
    fun markChatRead(chatId: String): Int
}
