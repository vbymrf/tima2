package io.tima.domain.chat

/**
 * Раздел — тематическая полка внутри набора (`doc/01-product/разделы.md`).
 *
 * **Наборов столько, сколько сущностей** (решение заказчика 2026-09-18): у контактов свой,
 * у групп, каналов, сообществ и аудио — свой. Этот класс описывает раздел любого набора:
 * общее у них — механизм, и класс один.
 *
 * @param id устойчивый ключ. Заводится один раз, не меняется при переименовании — это то,
 *   что позволяет двум устройствам одного человека сойтись в одной копии: телефон
 *   переименовал «Работа» в «Офис», ПК положил туда контакт под старым именем, и при
 *   слиянии оба говорят об одном разделе.
 * @param name имя, данное человеком.
 * @param icon индекс значка в [SectionIcon]. `0` — без значка.
 * @param place порядок в списке; меньше — выше.
 */
data class Section(
    val id: String,
    val name: String,
    val icon: Int = SectionIcon.NONE.index,
    val place: Int = 0,
) {
    /** Значок или `null`, когда его нет либо индекс из будущего набора этому клиенту неизвестен. */
    val glyph: SectionIcon? get() = SectionIcon.byIndex(icon)
}

/**
 * Заданный набор значков разделов — двенадцать рисованных (решение заказчика 2026-09-18).
 *
 * ── ИНДЕКС — НАВСЕГДА ───────────────────────────────────────────────────────
 *
 * В базе и в копии, уезжающей на другие устройства, хранится [index], а не имя. Значит
 * набор можно только **дописывать в конец**. Переставить или убрать значок из середины —
 * подменить значки всем разделам на всех устройствах, где стоит прежняя сборка. Поэтому
 * индексы записаны явно, а не берутся из `ordinal`: `ordinal` меняется от перестановки
 * строк в этом файле, и ничто бы этого не заметило.
 *
 * ── ПОЧЕМУ РИСОВАННЫЕ, А НЕ ЭМОДЗИ ──────────────────────────────────────────
 *
 * Эмодзи рисует прошивка, и каждая по-своему: у одной «дом» синий, у другой красный, а
 * «☑» на Samsung оказался синим системным значком поверх нашего цвета (найдено 2026-09-16).
 * Рисованный значок один на всех платформах и красится цветом темы. Рисует его `core-ui`
 * по индексу; здесь — только состав набора.
 *
 * Названия — латиницей и по смыслу (правило репозитория), русское имя — для подписи в
 * выборе значка.
 */
enum class SectionIcon(val index: Int, val title: String) {
    NONE(0, "без значка"),
    HOME(1, "дом"),
    WORK(2, "работа"),
    STUDY(3, "учёба"),
    FAMILY(4, "семья"),
    FRIENDS(5, "друзья"),
    MONEY(6, "деньги"),
    HEALTH(7, "здоровье"),
    SHOPPING(8, "покупки"),
    TRAVEL(9, "поездки"),
    SPORT(10, "спорт"),
    MUSIC(11, "музыка"),
    STAR(12, "звёздочка"),
    ;

    companion object {
        /** По индексу из базы. Неизвестный индекс — `null`: набор старше клиента. */
        fun byIndex(index: Int): SectionIcon? = entries.firstOrNull { it.index == index }

        /** Что предлагается в выборе: всё, кроме «без значка», — он и так по умолчанию. */
        val choices: List<SectionIcon> get() = entries.filter { it != NONE }
    }
}
