package io.tima.domain.chat

/**
 * Местные записи в переписке: то, что появляется в ней **без** отправителя.
 *
 * Пока таких записей две, и обе про один случай — сужение круга (ADR-0019 §6). Сервер
 * присылает событие, а увидеть человек должен две вещи: метка у самой реплики стала
 * другой, и в группе появилась строка, объясняющая почему.
 *
 * **Строка местная и на провод не уходит.** Её пишет устройство, получившее событие;
 * подписи у неё нет и быть не может. Поэтому она и хранится с отдельным признаком, а не
 * изображается сообщением без автора: иначе подделку было бы нечем отличить от
 * настоящего оповещения.
 */
interface ChatJournal {

    /**
     * Круг у сообщения стал другим.
     *
     * @param messageId серверный идентификатор: событие приходит с ним, а местного ключа
     *   у чужого сообщения мы не знаем.
     */
    fun levelChanged(chatId: String, messageId: Long, level: Int)

    /** Служебная строка в переписке. Повторный вызов с тем же [key] ничего не добавляет. */
    fun note(chatId: String, key: String, text: String, atMs: Long)
}
