package io.tima.domain.chat

import kotlinx.coroutines.flow.Flow

/**
 * Контакты — люди, с которыми уже есть личная переписка.
 *
 * **Другого источника нет, и это решение, а не нехватка.** Адресную книгу телефона мы не
 * читаем: она содержит людей, которые о TIMA не просили, и чтение её означало бы забрать
 * чужие номера без их ведома. Списка контактов на сервере тоже нет — там только поиск по
 * номеру, и заводить хранилище «кто с кем знаком» значит заводить социальный граф на
 * сервере, а это решение заказчика, а не следствие экрана.
 *
 * Поэтому вкладка показывает тех, с кем разговор уже начат. Обещать больше было бы
 * враньём: людей, которых мы не знаем, мы не знаем.
 *
 * **Присутствия здесь нет намеренно.** Макет рисует «онлайн» и «была 5 минут назад», но
 * сервер присутствие не отдаёт (`ws.go`: typing/receipt/presence — следующие итерации).
 * Нарисовать его сейчас значило бы показать выдуманное состояние живого человека.
 */
class ObserveContacts(private val book: ContactBook) {

    /** Список по имени. Имя расшифровывается хранилищем: оно лежит под ключом покоя. */
    fun list(): Flow<List<Contact>> = book.list()
}

/** Порт списка контактов. Реализуется `core-database`. */
fun interface ContactBook {
    fun list(): Flow<List<Contact>>
}

/**
 * @param name `null` — имя не расшифровалось либо его не записали. Строка всё равно
 *   показывается: человек, с которым есть переписка, не должен исчезать из списка
 *   из-за нечитаемого имени.
 */
data class Contact(
    val userId: String,
    val chatId: String,
    val name: String?,
)
