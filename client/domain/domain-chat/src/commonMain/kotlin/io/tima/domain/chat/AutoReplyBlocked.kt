package io.tima.domain.chat

/**
 * Автоответ заблокированному — ПЛАН-СПИСКОВ-КОНТАКТОВ, Л14.
 *
 * Написал заблокированный — ему уходит «Пользователь вас заблокировал», не чаще раза в
 * неделю на человека.
 *
 * ── ТОЛЬКО ЗНАКОМОМУ, И ЭТО ПРО СПАМ ────────────────────────────────────────
 *
 * Решение заказчика 2026-09-24, сужение против первоначальной постановки.
 *
 * Автоответ — **надёжный оракул «этот меня заблокировал»**. Рассыльщик отправляет по
 * десяти тысячам ников и через неделю точно знает, кто его отсёк, — и чистит список. Мы
 * бесплатно делаем за него работу, которую он сам сделать не может: обратной связи у
 * спама нет, в этом вся его слабость. Ограничение «раз в неделю» уменьшает трафик, но
 * оракул не убирает.
 *
 * Поэтому отвечаем только тому, кто **был в контактах до блокировки**: знакомого
 * предупредить вежливо, а незнакомец остаётся в неведении и ничего про нас не узнаёт.
 *
 * ── ТОЛЬКО ИЗ «ЗАБЛОКИРОВАННЫХ», НЕ ИЗ «УБРАННЫХ» ───────────────────────────
 *
 * У убранного переписка видна, и сообщение человек прочтёт. Сказать там «вас
 * заблокировали» было бы враньём.
 *
 * ── СЛАТЬ МОЖЕТ ТОЛЬКО КЛИЕНТ ───────────────────────────────────────────────
 *
 * Сервер ключей не имеет и сообщение «от имени человека» составить не может. Значит
 * ответ уходит только когда телефон блокирующего в сети. Выключен на неделю — ответа не
 * будет вовсе, и обещать «всегда ответим» нельзя.
 *
 * ── «РАЗ В НЕДЕЛЮ» НЕ ХРАНИТСЯ ОТДЕЛЬНО ─────────────────────────────────────
 *
 * Устройств у человека несколько, и каждое захотело бы ответить. Отметка выводится из
 * самой переписки — последнее исходящее `CK_SYSTEM`. Оно приедет на все устройства эхом,
 * и второго хранилища не нужно: у одного факта один источник.
 */
class AutoReplyBlocked(
    private val facts: ChatFacts,
    private val send: SendMessage,
    private val nowMs: () -> Long,
    /** Не чаще этого на одного человека. */
    private val everyMs: Long = WEEK_MS,
) {

    /**
     * Ответить, если положено.
     *
     * @param entry строка книги про написавшего; `null` — его в книге нет вовсе, и тогда
     *   он заведомо незнакомец.
     * @return `true`, если ответ поставлен в очередь.
     */
    fun replyTo(chatId: String, entry: BookEntry?): Boolean {
        if (entry == null || entry.list != BookList.Blocked) return false
        // Признак поставлен В МОМЕНТ блокировки и с тех пор не пересчитывается: сейчас
        // строка книги есть в любом случае — блокировка её и заводит.
        if (!entry.known) return false
        val last = facts.lastSystemOutMs(chatId)
        if (last > 0 && nowMs() - last < everyMs) return false
        // Текст уходит для тех, кто нас не понял: читающий рисует системное сообщение
        // СВОИМИ словами (Л15), а присланное не показывается вовсе. Пустое тело послать
        // нельзя — очередь его отвергнет.
        return send.send(chatId, BODY, kind = KIND_SYSTEM) is SendMessageResult.Queued
    }

    private companion object {
        const val WEEK_MS = 7L * 24 * 60 * 60 * 1000

        /**
         * Тело системного сообщения.
         *
         * Не надпись: её рисует словарь читающего. Это метка на случай, если строку
         * когда-нибудь покажет клиент, не знающий про `CK_SYSTEM`, — пустым телом
         * очередь не примет, а выдуманный текст уехал бы на чужом языке.
         */
        const val BODY = "blocked"
    }
}
