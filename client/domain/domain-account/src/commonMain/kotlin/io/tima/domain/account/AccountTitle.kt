package io.tima.domain.account

/**
 * Подпись аккаунта — **одна на всё приложение** (заказчик 2026-10-07): панель переходов, настройки
 * «Аккаунты», замок пин-кода, вход.
 *
 * Первой строкой — имя; без имени — @ник; без ника — служебное имя, восемь знаков идентификатора.
 * Пустой подписи не бывает: «служебное имя покажем все равно, если нет — получим ошибку или
 * пустоту» (заказчик). До этого каждый экран подписывал по-своему, и на замке realme стояло
 * «69a94f52», а на входе — «…f8c860».
 */
object AccountTitle {

    fun of(name: String, nickname: String, userId: String): String =
        name.trim().ifBlank { null }
            ?: nickname.trim().trimStart('@').ifBlank { null }?.let { "@$it" }
            ?: userId.take(SERVICE_LENGTH)

    /** Сколько знаков идентификатора — служебное имя. */
    const val SERVICE_LENGTH = 8
}
