package io.tima.domain.account

/**
 * Свой профиль: имя и ник — ПЛАН-КОНТАКТОВ.md, Д8.
 *
 * **Имя и ник живут по разным правилам.** Имя своё и любое: его никто не проверяет, и два
 * человека могут назваться одинаково. Ник один на всех и **не освобождается**: занятый
 * однажды остаётся за аккаунтом и после смены — иначе старые упоминания начали бы
 * указывать на другого человека.
 */
interface Profile {

    /**
     * Кто я — то, чем заполняется экран профиля (`GET /users/me`).
     *
     * @return `null`, если сети нет. Экран тогда открывается с тем, что знал, а не с
     *   пустыми полями: пустое поле имени поверх заполненного аккаунта выглядит как
     *   «имя пропало».
     */
    suspend fun me(): Me?

    /** @return удалось ли. Имя не проверяется никем — отказать может только сеть. */
    suspend fun setName(name: String): Boolean

    /**
     * Свободен ли ник — до нажатия «Сохранить».
     *
     * @return `null`, если ответа нет: ник не прошёл границы либо сети не было. Оба
     *   случая означают «не знаю», и показывать их как «свободен» нельзя.
     */
    suspend fun freeNickname(nick: String): Boolean?

    suspend fun setNickname(nick: String): NickStep
}

/**
 * Запись о себе. Пустая строка — не задано.
 *
 * [nickLocked] — ник задан этой личностью и второй раз не задаётся (решение заказчика
 * 2026-09-15). Право вернётся с новой личностью — «Начать заново» с другой фразой; не
 * воспользовался — прежний ник остаётся по умолчанию. Имя такого замка не имеет.
 */
data class Me(
    val phone: String = "",
    val name: String = "",
    val nickname: String = "",
    val nickLocked: Boolean = false,
    val avatarMediaId: String = "",
)

/** Чем кончилась попытка занять ник. */
enum class NickStep {
    Taken,
    /** Занят другим. Это не ошибка написания: границы ник прошёл. */
    Busy,
    /** 10…20 знаков, латиница, цифры, подчёркивание — что-то из этого нарушено. */
    OutOfBounds,
    /** Эта личность свой ник уже задала. Не «занят» и не «неверно» — сменить нельзя вовсе. */
    Locked,
    Offline,
}

/**
 * Границы ника — те же, что в базе (`persons.nickname`, миграция 0037) и в коде сервера.
 *
 * Проверка здесь третья и самая дешёвая: она отвечает человеку, пока он печатает, и не
 * тратит на заведомо негодное ни запроса, ни ожидания.
 */
fun nicknameFits(nick: String): Boolean =
    nick.length in 10..20 && nick.all { it.isLatinLetter() || it.isDigit() || it == '_' }

private fun Char.isLatinLetter(): Boolean = this in 'a'..'z' || this in 'A'..'Z'
