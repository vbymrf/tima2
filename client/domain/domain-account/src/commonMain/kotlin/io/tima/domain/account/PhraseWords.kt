package io.tima.domain.account

/**
 * Секретная фраза из того, что человек набрал в поле.
 *
 * Слова в списке — строчной латиницей, а клавиатура телефона сама делает первую букву
 * заглавной и ставит пробел после запятой (живая проверка на Honor, 2026-10-06). Различать
 * «Fifi» и «fifi» человеку незачем: он переписывает фразу с листка, а не выбирает регистр.
 * Поэтому разбор один на все поля фразы: слово — буквы подряд, всё прочее — разделитель
 * (пробелы, переводы строк, запятые, точки, номера «1.» из записанной по порядку фразы);
 * слова — строчными. Кириллица остаётся в слове: «а» вместо «a» должна показаться человеку
 * как слово не из списка, а не исчезнуть молча.
 */
object PhraseWords {
    private val separators = Regex("[^A-Za-zА-Яа-яЁё]+")

    /** Слова фразы из текста поля. */
    fun parse(text: String): List<String> = clean(text.split(separators))

    /** Те же слова, но уже разбитые: пустые выброшены, регистр снят. */
    fun clean(words: List<String>): List<String> = words.map { it.trim().lowercase() }.filter { it.isNotEmpty() }
}

/**
 * Что не так с фразой — видно до сервера (отчёт DGAR, заказчик 2026-10-06: «нет проверки
 * фразы — меньше слов ввели, символы какие за фразу приняться»).
 *
 * Подробность ничего не подсказывает подбирающему: словарь и контрольная сумма открыты, их
 * проверяет любой без сервера. Закрыто одно — от какой личности фраза, и это проверяет сервер.
 */
sealed interface PhraseFault {
    /** Слов не двенадцать. */
    data class Count(val got: Int, val need: Int) : PhraseFault

    /** Слова не из списка: номер (с единицы) и слово как набрано. */
    data class Unknown(val words: List<Pair<Int, String>>) : PhraseFault

    /** Все слова из списка, но контрольная сумма не сходится — опечатка в слове или порядок. */
    data object Checksum : PhraseFault
}

/** Проверка фразы по словарю и контрольной сумме; `null` — фраза складывается. */
fun interface PhraseChecker {
    fun check(words: List<String>): PhraseFault?
}
