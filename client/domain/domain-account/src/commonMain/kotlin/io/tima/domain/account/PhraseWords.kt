package io.tima.domain.account

/**
 * Секретная фраза из того, что человек набрал в поле.
 *
 * Слова в списке — строчной латиницей, а клавиатура телефона сама делает первую букву
 * заглавной и ставит пробел после запятой (живая проверка на Honor, 2026-10-06). Различать
 * «Fifi» и «fifi» человеку незачем: он переписывает фразу с листка, а не выбирает регистр.
 * Поэтому разбор один на все поля фразы: разделители — пробелы, переводы строк и запятые,
 * слова — без пробелов по краям и строчными.
 */
object PhraseWords {
    private val separators = Regex("[\\s,]+")

    /** Слова фразы из текста поля. */
    fun parse(text: String): List<String> = clean(text.split(separators))

    /** Те же слова, но уже разбитые: пустые выброшены, регистр снят. */
    fun clean(words: List<String>): List<String> = words.map { it.trim().lowercase() }.filter { it.isNotEmpty() }
}
