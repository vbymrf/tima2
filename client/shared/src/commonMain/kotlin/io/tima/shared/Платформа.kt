package io.tima.shared

/**
 * На чём мы работаем — **говорит платформа, а не общий код**.
 *
 * Найдено правкой: строка `platform = "desktop"` стояла в `commonMain`, то есть телефон
 * объявлял себя ПК. Ошибка тихая — регистрация проходит, сообщения ходят, — но сервер
 * разрешает подтверждать привязку нового устройства **только телефону**
 * (`key-lifecycle.md §2`: якорь доверия аттестуемый, ПК своё доверие наследует и дальше не
 * раздаёт). Телефон, объявленный ПК, получил бы `not_a_phone`, и по симптому это
 * неотличимо от поломки самого QR.
 *
 * Значения — ровно те три, которые понимает сервер (`normalizePlatform` в `devices.go`);
 * всё остальное он приводит к пустой строке, а пустая платформа подтверждать не вправе.
 * Поэтому список закрытый, а не строка: строку можно опечатать, и отказ придёт через
 * неделю на живом устройстве.
 */
enum class Платформа(val серверу: String) {
    ПК("desktop"),
    Андроид("android"),
    Айфон("ios"),
    ;

    /**
     * Как устройство назовётся человеку на том конце привязки.
     *
     * Имени мы не спрашиваем: лишний вопрос на экране, где человек и так ждёт. Зато на
     * телефоне он увидит «Компьютер» — и этого хватает, чтобы отличить свой ПК от чужого
     * кода, подсунутого в переписке.
     */
    val имяУстройства: String
        get() = when (this) {
            ПК -> "Компьютер"
            Андроид -> "Телефон"
            Айфон -> "iPhone"
        }
}
