package io.tima.shared

/**
 * Имя файла базы для аккаунта — ПЛАН-КОНТАКТОВ.md, Д11.
 *
 * **Своя база на каждый аккаунт.** У них разные ключи покоя, и общая база означала бы,
 * что переписка виртуального аккаунта открывается ключом основного, — то есть
 * «отдельный пользователь» остаётся словами.
 *
 * **Прежнее имя сохранено за первым аккаунтом.** У людей, которые уже пользуются
 * приложением, база называется `tima.db`; переименовать её значило бы потерять переписку
 * на ровном месте. Поэтому имя с приставкой получают только те аккаунты, что заведены
 * после появления переключателя.
 *
 * Здесь, а не в приложениях: путь к каталогу платформенный, а правило именования — нет,
 * и два одинаковых правила в двух приложениях однажды разошлись бы.
 */
fun databaseFor(userId: String, first: String? = null): String =
    if (first != null && userId == first) LEGACY else "tima-${safe(userId)}.db"

/** Прежнее имя: одна база на приложение, как было до Д11. */
const val LEGACY: String = "tima.db"

/**
 * В имени файла остаются только те знаки, что есть в UUID.
 *
 * Идентификатор приходит от сервера, а из него получается путь: чужое значение, попавшее
 * в имя файла, — это способ написать не туда.
 */
private fun safe(userId: String): String =
    userId.filter { it.isDigit() || it in 'a'..'f' || it in 'A'..'F' || it == '-' }.take(40)
