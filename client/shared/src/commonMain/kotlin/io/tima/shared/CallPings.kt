package io.tima.shared

import kotlinx.coroutines.channels.BufferOverflow
import kotlinx.coroutines.channels.Channel
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.receiveAsFlow

/**
 * События звонка от приёмника к окну — **каждое, по порядку** (Redmi, отчёт FTPB,
 * 2026-09-27).
 *
 * До этого здесь было одно значение (`StateFlow<String>`), и оно хранило только
 * последнее. Лента звонков принесла одной пачкой «звонит» нового звонка и «завершён»
 * прошлого — с разницей 8 мс, потому что собеседник положил трубку и тут же набрал снова.
 * Второе затёрло первое раньше, чем окно успело прочитать: уведомление о входящем
 * встало (оно идёт другим путём), а окно 0 о звонке не узнало. Человек видел прошлый
 * звонок с кнопкой «Перезвонить», жал её — «абонент занят»: занят он был звонком к нам.
 * «Ответить» в уведомлении ждало, пока окно узнает звонок, и не дождалось.
 *
 * **Очередь, а не поток с повтором.** Съеденное событие не приходит второй раз, когда
 * окно пересобрано: повтор старого «звонит» поднял бы входящий по давно кончившемуся
 * звонку. Несъеденное ждёт окна — открыли приложение по уведомлению, и события приходят
 * по порядку, а не последнее из них.
 */
class CallPings {

    private val queue = Channel<String>(capacity = CAPACITY, onBufferOverflow = BufferOverflow.DROP_OLDEST)

    /** Событие строкой: `callId|from|kind` для входящего, `слово|callId|значение` для прочих. */
    fun send(ping: String) {
        queue.trySend(ping)
    }

    /** Читает один получатель — окно. Каждое событие достаётся ему один раз. */
    val pings: Flow<String> = queue.receiveAsFlow()

    private companion object {
        /**
         * Столько событий ждут окна, пока его нет. Звонок даёт их по пять-шесть; старшие
         * за пределом — устаревшие, и терять лучше их, чем свежие.
         */
        const val CAPACITY = 64
    }
}
