package io.tima.shared

/**
 * Слова фразы — **один раз и ненадолго**, от входа по фразе до просьбы о ключе служебной
 * группы (решение заказчика 2026-09-30, 2а).
 *
 * ── ЗАЧЕМ ───────────────────────────────────────────────────────────────────
 *
 * Устройство, вошедшее по номеру и фразе, ключей групп не получает: их отдаёт доверяющее
 * устройство только при «Доверить» по QR (ЖУ8). Без ключа служебной группы нет копии книги.
 * Попросить ключ можно, но сервер требует подписи ключом личности, а он выводится из слов и
 * на устройстве не хранится (ADR-0010 §этап 3). Слова есть ровно в одну минуту — сразу после
 * входа, — и этой минутой и пользуемся.
 *
 * ── ПОЧЕМУ В ПАМЯТИ И С ПРЕДЕЛОМ ────────────────────────────────────────────
 *
 * Слова — секрет: держать их дольше значило бы отдать вместе с устройством заслон против
 * угона номера. Поэтому только в памяти процесса, берутся один раз ([take] стирает) и сами
 * забываются через [KEEP_MS]: если до просьбы дело не дошло, их больше нет.
 */
object PhraseOnce {

    @kotlin.concurrent.Volatile
    private var words: List<String>? = null

    @kotlin.concurrent.Volatile
    private var at = 0L

    /** Вход по фразе удался — запомнить слова для одной просьбы. */
    fun hold(words: List<String>) {
        this.words = words.toList()
        at = msNow()
    }

    /** Взять слова и забыть их. `null` — не входили по фразе или срок вышел. */
    fun take(): List<String>? {
        val held = words
        words = null
        return held?.takeIf { msNow() - at <= KEEP_MS }
    }

    /** Десять минут — с запасом на запуск и первую сверку копии. */
    private const val KEEP_MS = 10 * 60 * 1000L
}
