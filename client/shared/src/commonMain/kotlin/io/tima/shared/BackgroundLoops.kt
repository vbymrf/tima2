package io.tima.shared

import androidx.compose.runtime.Composable
import androidx.compose.runtime.LaunchedEffect
import io.tima.core.diag.Journal
import io.tima.core.database.SqlChatBook
import io.tima.core.diag.LogCode
import io.tima.domain.chat.SyncGroupChats
import io.tima.domain.chat.SyncGroupsStep
import io.tima.core.network.GroupsOverHttp
import io.tima.core.network.PlatformResult
import kotlinx.coroutines.delay

/**
 * Что приложение делает само, пока человек ничего не нажимает.
 *
 * Три цикла и одно объявление. Вынесены из `Root.kt` потому, что это **политика
 * времени**, а не навигация: когда отправлять, как часто повторять, что делать при
 * обрыве. Смешанные с разметкой, они читались как часть окна — и правились вместе с
 * ним, хотя к окну отношения не имеют.
 *
 * **Владелец корутин остаётся у Compose.** Циклы живут ровно столько, сколько живо
 * окно, — так было и раньше, и менять это незачем: приложение без окна ничего не
 * отправляет и никого не слушает.
 */
@Composable
fun BackgroundLoops(
    assembled: Assembled,
    platform: Platform,
    /** Меняется при каждом изменении списка переписок: по нему и идёт отправка. */
    changeSign: Any?,
    /**
     * Сколько осталось неотправленного — списку аккаунтов (Д11).
     *
     * Отдаётся наружу, а не считается в переключателе: чужую очередь не прочитать, её
     * база зашифрована своим ключом покоя. Значит число оставляет тот, кто открыт, —
     * после каждого прохода, когда оно уже изменилось.
     */
    onPending: (Int) -> Unit = {},
) {
    // ── ЗАСТРЯВШАЯ ОЧЕРЕДЬ ПИШЕТСЯ РЕДКО И С ПРИЧИНОЙ ───────────────────────
    //
    // Что было до 2026-09-23 на realme: одно сообщение стояло в очереди **пять суток**,
    // и каждые пять секунд в журнал уходило «повтор не помог, осталось=1». К полудню в
    // дневнике было 815 строк, почти все — эти. Журнал, который сам себя забивает,
    // перестаёт быть журналом: всё остальное вытесняется по сроку хранения.
    //
    // И при этом **ни одной строки о причине**. Она была известна приложению: оба
    // отправителя её вычисляют и кладут в `lastTrouble` — поле, которое не читает никто.
    // Разбор из-за этого упирался в «не уходит», а почему — узнавали пересборкой.
    //
    // Отсюда два правила: писать, только когда что-то изменилось (число или причина),
    // и не реже раза в пять минут — чтобы застрявшая очередь не пропала из виду совсем.
    var saidTrouble: String? = null
    var saidLeft = -1
    var saidAt = 0L
    // Платформа объявляется серверу при каждом запуске — так задуман сервер, и так
    // чинятся установки, заведённые до появления колонки. Не в регистрации:
    // регистрация бывает один раз, а объявление нужно и тем, кто уже завёлся.
    LaunchedEffect(assembled) {
        declarePlatform(assembled.network, platform)
    }

    // Группы — с сервера при каждом запуске: в группу добавляет кто-то другой, и без
    // сверки о ней узнают по первому сообщению, а название — никогда (до 2026-09-18 так и
    // было: у приглашённого в шапке стояло «Группа», у создателя — настоящее имя).
    LaunchedEffect(assembled) {
        val environment = assembled.environment
        val sync = SyncGroupChats(GroupsOverHttp(assembled.network.groups), SqlChatBook(environment.db, environment.cipher))
        // Сеть при запуске может ещё не подняться — повторить, а не ждать следующего запуска.
        var pause = 5_000L
        repeat(4) { attempt ->
            val step = sync.refresh()
            Journal.note(LogCode.GROUPS_SYNC, "группы сверены с сервером", "итог" to step.toString())
            if (step !is SyncGroupsStep.Offline) return@LaunchedEffect
            if (attempt < 3) delay(pause)
            pause *= 3
        }
    }

    // Отправка идёт ОТ ИЗМЕНЕНИЙ, а не по таймеру: список приходит потоком из базы, и
    // новое сообщение в очереди — это его изменение. Опрос по таймеру давал бы в v1 и
    // задержку, и лишние пробуждения.
    LaunchedEffect(changeSign) {
        val before = assembled.environment.queue.pending().size
        assembled.sender.pass()
        // Групповой проход идёт следом, а не вместо: в очереди лежат и личные, и
        // групповые, и каждый берёт своё. Порядок между ними значения не имеет — записи
        // не пересекаются.
        assembled.groupSender.pass()
        val after = assembled.environment.queue.pending().size
        // «Сообщение не ушло» — самая частая жалоба, и ответ на неё живёт здесь: сколько
        // было, сколько осталось. Пустой проход не пишем — журнал должен читаться.
        if (before > 0 || after > 0) {
            Journal.note(LogCode.QUEUE_PASS, "проход очереди", "было" to before, "осталось" to after)
        }
        onPending(after)
    }

    // ── КАНАЛ ДЕРЖИТ ПРОЦЕСС, А НЕ ОКНО (У2) ────────────────────────────────
    //
    // Здесь стояло `LaunchedEffect { receiver.hold() }`, и над ним было записано: «живой
    // канал держится, пока живо окно». Для приложения без уведомлений это было верно —
    // приложение без окна никого не слушало и ничего не показывало.
    //
    // Уведомление переворачивает условие: оно нужно ровно тогда, когда окна нет.
    // `ChannelHost.hold` возвращается сразу — цикл он заводит в своей области, и смерть
    // композиции его не уносит.
    LaunchedEffect(assembled) {
        ChannelHost.hold(assembled)
    }

    // ── ПОВТОРЫ ЖДУТ СВОЕГО СРОКА, А НЕ ТИКАЮТ (У12) ────────────────────────
    //
    // Здесь стояло биение каждые пять секунд — **17 280 пробуждений в сутки**, и почти
    // все впустую: очередь пуста почти всегда. Причём таймер опрашивал нашу же базу о
    // времени, которое мы туда сами и положили: срок повтора лежит в `next_attempt_at`,
    // по нему же идёт и отбор (`Messages.sq`).
    //
    // Пока канал жил вместе с окном, это было безвредно — при открытом окне телефон и
    // так не спит. Служба живёт сутками, и таймер стал бы прямой причиной того, что
    // человек нажмёт «Ограничить».
    //
    // Стало: спим ровно до ближайшего срока, а **пустая очередь не будит вовсе** —
    // цикл кончается. Разбудит его изменение списка переписок: новая запись в очереди
    // это его изменение, и по нему же идёт первая отправка.
    LaunchedEffect(assembled, changeSign) {
        while (true) {
            val ждать = ближайшийСрок(assembled) ?: return@LaunchedEffect
            delay(ждать)
            val before = assembled.environment.queue.pending().size
            assembled.sender.pass()
            assembled.groupSender.pass()
            val after = assembled.environment.queue.pending().size
            // Застрявшая очередь важнее уходящей: одно и то же число из прохода в проход
            // означает, что повторы не помогают, и это надо видеть в отчёте.
            if (before > 0) {
                if (before == after) {
                    // Причины у отправителей свои, и закрывать одну другой нельзя:
                    // ровно этим личный отправитель пять суток прятал групповую беду.
                    val why = listOfNotNull(
                        assembled.sender.lastTrouble?.let { "личные: $it" },
                        assembled.groupSender.lastTrouble?.let { "группы: $it" },
                    ).joinToString(" · ").ifBlank { "причина не названа" }
                    val now = msNow()
                    // Повторяем строку, только если что-то изменилось либо прошло пять
                    // минут: иначе одна застрявшая запись выдавливает из дневника всё
                    // остальное, а именно в нём потом ищут причину.
                    if (why != saidTrouble || after != saidLeft || now - saidAt >= ПРО_ЗАСТРЯВШУЮ_НЕ_ЧАЩЕ_МС) {
                        Journal.trouble(
                            LogCode.QUEUE_STUCK,
                            "повтор не помог",
                            "осталось" to after,
                            "почему" to why,
                        )
                        saidTrouble = why
                        saidLeft = after
                        saidAt = now
                    }
                } else {
                    Journal.note(LogCode.QUEUE_PASS, "повтор", "было" to before, "осталось" to after)
                    saidTrouble = null
                    saidLeft = -1
                }
            }
            onPending(after)
        }
    }
}

/**
 * Через сколько ждёт ближайший повтор; `null` — ждать нечего, очередь пуста (У12).
 *
 * Сроки записаны в самой очереди — их поставил отправитель, когда попытка не удалась.
 * Спрашивать о них таймером значит спрашивать себя же.
 *
 * Пол секунды снизу — не «на всякий случай»: срок мог пройти, пока мы считали, и без
 * нижней границы цикл крутился бы без пауз, пока отправка не начнёт удаваться.
 */
internal fun ближайшийСрок(assembled: Assembled): Long? {
    val pending = assembled.environment.queue.pending()
    if (pending.isEmpty()) return null
    val сейчас = msNow()
    val срок = pending.minOf { if (it.nextAttemptAtMs > 0) it.nextAttemptAtMs else сейчас }
    return maxOf(срок - сейчас, НЕ_ЧАЩЕ_МС)
}

/** Нижняя граница паузы между проходами очереди. */
internal const val НЕ_ЧАЩЕ_МС = 500L

/**
 * Объявить платформу серверу.
 *
 * **Отказ здесь намеренно не показывается человеку.** Единственное, на что платформа
 * влияет, — право подтверждать привязку нового устройства по QR, и там сервер отвечает
 * своими словами («подтвердить может только телефон»), в том самом месте, где человек
 * этого ждёт. Показать беду на старте значило бы напугать сообщением про то, чего он
 * сейчас не делает.
 *
 * Повторы — только для отказа связи: запуск и есть тот момент, когда сети чаще всего
 * ещё нет. Отказ сервера повторять нечего: он не изменится.
 */
internal suspend fun declarePlatform(network: DevicePorts, platform: Platform) {
    repeat(ПОПЫТОК_ОБЪЯВЛЕНИЯ) { attempt ->
        when (network.devices.declarePlatform(platform.server)) {
            is PlatformResult.Declared -> return
            is PlatformResult.Refused -> return
            is PlatformResult.NoConnection -> delay(МЕЖДУ_ОБЪЯВЛЕНИЯМИ_МС * (attempt + 1))
        }
    }
}

/** Три попытки с растущей паузой: 2 с, 4 с, 6 с. Дальше объявит следующий запуск. */
private const val ПОПЫТОК_ОБЪЯВЛЕНИЯ = 3
private const val МЕЖДУ_ОБЪЯВЛЕНИЯМИ_МС = 2_000L

/**
 * Как часто повторять строку о застрявшей очереди, если ничего не изменилось.
 *
 * Пять минут. Реже — и застрявшая очередь пропадёт из виду в длинном разговоре; чаще —
 * она вытеснит из дневника то, ради чего дневник и ведётся. Прежнее «каждые пять секунд»
 * давало семнадцать тысяч строк в сутки об одном и том же.
 */
private const val ПРО_ЗАСТРЯВШУЮ_НЕ_ЧАЩЕ_МС = 5 * 60 * 1000L
