package io.tima.shared

import io.tima.core.outbox.OutboxEntry
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertNull
import kotlin.test.assertTrue

/**
 * Когда просыпается очередь — У12.
 *
 * Здесь стояло биение каждые пять секунд: **17 280 пробуждений в сутки**, и почти все
 * впустую. Причём таймер опрашивал нашу же базу о времени, которое мы туда сами и
 * положили, — срок повтора лежит в `next_attempt_at`.
 *
 * Пока канал жил вместе с окном, это было безвредно: при открытом окне телефон и так не
 * спит. Служба живёт сутками, и это стало бы прямой причиной того, что человек нажмёт
 * «Ограничить».
 */
class QueueWakeTest {

    private fun запись(срок: Long) = OutboxEntry(
        dedupKey = "d-$срок",
        chatId = "chat-1",
        body = byteArrayOf(1),
        nextAttemptAtMs = срок,
    )

    @Test
    fun пустая_очередь_не_будит_вовсе() {
        // Главное этой задачи. `null` означает «цикл кончился», а не «подождём ещё».
        assertNull(ближайшийСрок(emptyList(), сейчас = 1_000))
    }

    @Test
    fun ждём_до_ближайшего_срока_а_не_фиксированную_паузу() {
        val ждать = ближайшийСрок(listOf(запись(10_000), запись(3_000), запись(120_000)), сейчас = 1_000)
        assertEquals(2_000, ждать, "проснулись не к самому раннему сроку")
    }

    @Test
    fun просроченное_берётся_сразу_но_не_крутит_цикл() {
        // Срок мог пройти, пока мы считали. Без нижней границы цикл вертелся бы без
        // пауз, пока отправка не начнёт удаваться, — то есть ровно в той беде, из-за
        // которой очередь и застревает.
        val ждать = ближайшийСрок(listOf(запись(500)), сейчас = 10_000)
        assertEquals(НЕ_ЧАЩЕ_МС, ждать)
        assertTrue(НЕ_ЧАЩЕ_МС > 0)
    }

    @Test
    fun запись_без_срока_берётся_немедленно() {
        // Ноль — «ещё не пробовали»: ждать нечего, но и молотить нельзя.
        assertEquals(НЕ_ЧАЩЕ_МС, ближайшийСрок(listOf(запись(0)), сейчас = 10_000))
    }
}
