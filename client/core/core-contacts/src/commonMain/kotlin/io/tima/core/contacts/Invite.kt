package io.tima.core.contacts

/**
 * Пригласить человека, которого нет в TIMa — ПЛАН-КОНТАКТОВ.md, Д6.
 *
 * **Все три способа — средствами телефона, а не нашими.** Приложения у человека ещё нет,
 * и отправить ему что-либо через TIMa нельзя по определению: некуда.
 *
 * **Текст один на все способы.** СМС и «поделиться» несут одну и ту же строку со
 * ссылкой; разница только в том, чем её понесут.
 *
 * **Отметки «приглашён» нет и не будет.** Приложение не узнаёт, дошло ли СМС и открыл ли
 * человек ссылку: нажатие и отправка — разные события, и показать первое как второе
 * значило бы соврать.
 */
interface Invite {

    /** Открыть приложение сообщений с готовым текстом. */
    fun sms(phone: String, text: String): Boolean

    /** Обычный звонок телефоном. Наш звонок здесь ни при чём. */
    fun call(phone: String): Boolean

    /** Системное «поделиться»: ссылка уходит туда, куда человек выберет сам. */
    fun share(text: String): Boolean
}

/**
 * Приглашение этой платформы.
 *
 * На ПК ничего из трёх нет: ни приложения сообщений, ни звонилки, ни системного
 * «поделиться» в том виде, в каком оно есть у телефона.
 */
expect fun platformInvite(): Invite
