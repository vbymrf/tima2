package io.tima.core.contacts

/**
 * Что произойдёт, если сейчас попросить доступ к телефонной книге — Л1.
 *
 * ── ЗАЧЕМ ЭТО ЗНАТЬ ЭКРАНУ ──────────────────────────────────────────────────
 *
 * До этого экран показывал одну круглую кнопку с глифом «✓», а [askContactsAccess] за
 * ней делал **две разные вещи**: в первый раз — системный диалог, а после отказа, когда
 * система спрашивать больше не станет, — открывал настройки приложения.
 *
 * То есть кнопка «перейти в настройки» была, просто она была той же самой и молчала о
 * себе. Глиф «✓» означает «согласен», а второй раз означает «уйдёшь из приложения».
 *
 * Это тот же случай, за который забраковано долгое нажатие в книге: **действие, о
 * котором не сказали, узнают только случайно.**
 *
 * Состояние вычислимо заранее на обеих платформах, где книга вообще есть, — значит
 * кнопка может себя называть.
 */
enum class ContactsAccessWay {
    /** Система ещё спросит: нажатие поднимет диалог. Надпись — «Разрешить». */
    Ask,

    /**
     * Система больше не спросит; остаётся страница приложения в настройках.
     *
     * Надпись — «Открыть настройки», и она обязана быть другой: человек уйдёт из
     * приложения, и узнать об этом он должен **до** нажатия.
     */
    Settings,

    /**
     * Спрашивать нечего: телефонной книги у системы нет вовсе (ПК).
     *
     * Кнопки тогда нет — не «неактивная», а именно нет: неактивная кнопка тоже зовёт
     * нажать, а нажимать здесь не на что.
     */
    None,
}

/** Каким будет следующий шаг — см. [ContactsAccessWay]. */
expect fun contactsAccessWay(): ContactsAccessWay
