package io.tima.core.outbox

/**
 * Шифр поля: **тело сообщения лежит в базе закрытым**.
 *
 * Plan.md §3.4.2 обещает `body_enc` «под локальным AEAD», §3.4.3 выбирает вариант A —
 * AEAD на поле, метаданные открыто. Порт объявлен здесь, рядом с [OutboxStore] и
 * [InboxStore], потому что это часть их договора: столбец `body_enc` **всегда** закрыт, и
 * ни одна реализация хранилища не имеет права записать в него открытые байты.
 *
 * Реализация — `core-encryption` поверх `LocalStoreCipher`: слой NaCl живёт только в
 * `messenger-crypto`, а ключ покоя выводится из секрета устройства, лежащего в хранилище
 * платформы. В v1 этот секрет лежал открытым файлом рядом с файлом базы, и шифрование
 * покоя было **декоративным**: кто дошёл до базы, доходил и до ключа.
 *
 * **Заглушки «пока без шифрования» здесь быть не должно.** Ровно так теряются такие
 * обещания: подставили сквозной шифр «на время», забыли, и столбец с именем `body_enc`
 * годами лежит открытым — это уже случалось с `secure_delete`, который был обещан и не
 * работал.
 */
interface FieldCipher {

    /** Закрыть поле перед записью. Nonce внутри, поэтому два вызова дают разные байты. */
    fun seal(plaintext: ByteArray): ByteArray

    /**
     * Открыть поле после чтения.
     *
     * @return `null`, если поле не открылось. Это **не поломка кода**: чужой ключ,
     *   испорченный файл, запись другого устройства. Такую строку показывают
     *   нечитаемой — и не роняют из-за неё всю переписку.
     */
    fun open(sealed: ByteArray): ByteArray?
}
