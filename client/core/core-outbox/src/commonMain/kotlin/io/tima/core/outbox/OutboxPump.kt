package io.tima.core.outbox

import kotlinx.coroutines.coroutineScope
import kotlinx.coroutines.launch
import kotlinx.coroutines.sync.Semaphore
import kotlinx.coroutines.sync.withPermit

/**
 * Насос очереди: запечатывает готовое и отдаёт транспорту, соблюдая предел
 * одновременных отправок.
 *
 * **Зачем предел, если очередь и так по одному сообщению.** Требование плана
 * (§3.4): «ограничение одновременных отправок — иначе очередь после суток офлайна
 * выстреливает залпом». Человек, вернувшийся в сеть после дня в самолёте, имеет в
 * очереди сотни сообщений; без предела они уйдут одним пакетом — и получат в ответ
 * `429` от ограничителя частоты, то есть очередь сама себя накажет и растянет
 * доставку вместо того, чтобы ускорить.
 *
 * **Насос — единственная асинхронная часть очереди.** Сами машины состояний
 * ([Outbox], [Inbox]) синхронные и такими остаются: их правильность зависит от
 * порядка переходов, а не от планировщика. Здесь наоборот — планировщик и есть суть.
 *
 * Насос **не решает**, повторять ли: это решает [Outbox] по исходу. И не знает, что
 * такое сеть: транспорт приходит функцией.
 */
class OutboxPump(
    private val outbox: Outbox,
    /**
     * Сколько отправок идёт одновременно. Три — не «магическое число», а компромисс:
     * одна не использует канал, десять упираются в ограничитель частоты сервера.
     * Значение меняется конфигурацией, когда появятся измерения.
     */
    private val maxConcurrent: Int = 3,
) {

    init {
        require(maxConcurrent >= 1) { "предел одновременных отправок не может быть меньше одной" }
    }

    /**
     * Один проход: забрать всё готовое к отправке и отправить.
     *
     * Проход **конечен** намеренно: он берёт то, что готово на момент начала, и
     * заканчивается. Бесконечный цикл внутри насоса лишил бы вызывающего
     * возможности остановиться, а остановка нужна — при потере сети, при уходе
     * приложения в фон, при выходе из аккаунта.
     *
     * @param epochKeyId текущая эпоха escrow. Её смена отменяет запечатанное:
     *   конверт под прошлую эпоху негоден (ADR-0016).
     * @param seal сборка конверта — `core-encryption`.
     * @param send отправка — `core-network`. Обязана не бросать исключений: беда
     *   должна приходить исходом, иначе одно упавшее сообщение останавливает проход.
     * @return сколько сообщений получили исход за этот проход.
     */
    suspend fun runOnce(
        epochKeyId: Int,
        seal: (OutboxEntry) -> ByteArray,
        send: suspend (ReadyToSend) -> SendOutcome,
    ): Int {
        // Сначала запечатываем всё готовое, потом отправляем. Порядок именно такой:
        // запечатывание синхронное и быстрое, а отправка ждёт сеть. Смешав их, мы бы
        // держали открытым окно, в которое может попасть смена эпохи.
        val готовые = mutableListOf<ReadyToSend>()
        while (готовые.size < BATCH_LIMIT) {
            outbox.sealNext(epochKeyId, seal) ?: break
            готовые += outbox.claimForSend() ?: break
        }
        if (готовые.isEmpty()) return 0

        val permits = Semaphore(maxConcurrent)
        coroutineScope {
            for (готовое in готовые) {
                launch {
                    permits.withPermit {
                        val исход = send(готовое)
                        outbox.onOutcome(готовое.entry.dedupKey, исход)
                    }
                }
            }
        }
        return готовые.size
    }

    companion object {
        /**
         * Сколько сообщений берётся за один проход.
         *
         * Предел нужен, потому что проход держит запечатанные конверты в памяти, а
         * конверт — это тело сообщения плюс обёртки ключей на каждое устройство.
         * Очередь из тысячи сообщений после долгого офлайна уйдёт за несколько
         * проходов, и это правильнее, чем один проход на всю память устройства.
         */
        const val BATCH_LIMIT: Int = 50
    }
}
