package io.tima.core.ui

import io.tima.core.words.AppearanceWords

/**
 * Место на экране, у которого своя ручка размера — ПЛАН-ШРИФТОВ Ш3.
 *
 * Пять групп, решение заказчика 2026-09-16. Группы заданы **местами**, а не ролями
 * текста: в шапке и в сообщении встречается одна и та же роль, а укрупнять их человек
 * хочет порознь.
 *
 * ── ПОЧЕМУ СПИСКИ ОТДЕЛЬНО ОТ МЕНЮ ──────────────────────────────────────────
 *
 * Строка списка **обрезается** и обязана быть одной высоты: иначе от чужого длинного
 * имени растёт строка, и список перестаёт быть списком. Меню же переносится. Это разное
 * поведение при тесноте, и человеку, которому нужен крупный текст в переписке, не
 * обязан разъезжаться список контактов.
 *
 * ── ПОЧЕМУ ЧИСЛО, А НЕ ПРОЦЕНТ ──────────────────────────────────────────────
 *
 * Хранится и показывается **размер главной строки группы в точках** — «15», а не
 * «×1.15». Процент — арифметика, человеку он ничего не говорит. Остальные кегли группы
 * едут за главной множителем [scaleOf]: иначе пояснение стало бы крупнее названия.
 *
 * Ступени — настоящие кегли темы, а не круглые проценты.
 */
enum class TextPlace(val base: Int, val steps: List<Int>) {
    /** Текст сообщений в переписке. Главная строка — `sz4`. */
    MESSAGES(base = 15, steps = listOf(13, 15, 17, 19, 22)),

    /** Ряд вкладок, второй ряд, фильтры. Главная строка — `sz5`. */
    TABS(base = 13, steps = listOf(11, 13, 15, 17, 19)),

    /** Настройки и переключение окон. Главная строка — `sz4`. */
    MENU(base = 15, steps = listOf(13, 15, 17, 19, 22)),

    /** Шапка окна и шапка подокна. Главная строка — `sz3`. */
    HEADERS(base = 17, steps = listOf(15, 17, 19, 22, 26)),

    /** Чаты, контакты, каталоги, коллекции, группы, страницы. Главная строка — `sz4`. */
    LISTS(base = 15, steps = listOf(13, 15, 17, 19, 22)),
}

/** Надпись группы — в словаре, а не в перечислении (ПЛАН-ЯЗЫКА Я2). */
fun AppearanceWords.place(place: TextPlace): String = when (place) {
    TextPlace.MESSAGES -> sizeMessages
    TextPlace.TABS -> sizeTabs
    TextPlace.MENU -> sizeMenu
    TextPlace.HEADERS -> sizeHeaders
    TextPlace.LISTS -> sizeLists
}

/**
 * Шрифт и пять размеров — то, что человек выбрал в «Шрифтах и размерах».
 *
 * Размеры картой, а не пятью полями: группы одинаковы по природе, и экран рисует их
 * циклом. Пустая карта — всё по умолчанию; так же читается и испорченная запись.
 */
data class TextLook(
    val font: AppFont = AppFont.byDefault,
    val size: Map<TextPlace, Int> = emptyMap(),
) {
    /** Выбранный размер главной строки группы. */
    fun sizeOf(place: TextPlace): Int = size[place] ?: place.base

    /** Во сколько раз крупнее обычного. Им умножаются ВСЕ кегли группы, а не один. */
    fun scaleOf(place: TextPlace): Float = sizeOf(place).toFloat() / place.base

    fun withSize(place: TextPlace, points: Int): TextLook =
        copy(size = size + (place to points.coerceIn(place.steps.first(), place.steps.last())))
}
