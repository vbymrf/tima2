package io.tima.core.ui

import androidx.compose.runtime.Composable
import androidx.compose.runtime.CompositionLocalProvider
import androidx.compose.runtime.staticCompositionLocalOf
import androidx.compose.ui.text.font.FontFamily

/**
 * Каким шрифтом набран интерфейс.
 *
 * ── ЗАЧЕМ ЭТО ЕСТЬ ──────────────────────────────────────────────────────────
 *
 * Шрифта в сборке нет: `null` означает «системный», и приложение сегодня рисует тем,
 * что даст платформа. На Android это Roboto, на Windows — что найдётся у JVM, на
 * раннере сборки — третье. Пока это никого не трогало, потому что размеры интерфейса
 * заданы числами и от шрифта не зависят.
 *
 * Трогало это только проверки: они мерили настоящую ширину текста — то есть мерили
 * шрифт машины, а не наш интерфейс. Один и тот же тест был зелёным на машине
 * разработки и красным на раннере, и ни один из двух ответов не относился к телефону.
 * Отсюда эта точка: снимочные проверки подставляют сюда **эталонный шрифт**, и их ответ
 * перестаёт зависеть от того, где они запущены ([io.tima.testui] `ReferenceFont`).
 *
 * ── ПОЧЕМУ ЗДЕСЬ, А НЕ В ТЕСТАХ ─────────────────────────────────────────────
 *
 * Потому что это же место понадобится выбору шрифта в «Оформлении»
 * (`doc_mig/ИНТЕРФЕЙС/ШРИФТЫ.md`). Заводить для тестов свой способ подменять шрифт, а
 * для настройки потом второй — значит получить два способа, которые разойдутся.
 *
 * ── ПРАВИЛО, КОТОРОЕ ЭТА ТОЧКА НЕ ОТМЕНЯЕТ ──────────────────────────────────
 *
 * **Шрифт не управляет размерами интерфейса.** Полосы, рейка, высоты рядов — числа в
 * [FormatTima] и [TimaZones], и они не выводятся из измеренного текста. Текст, которому
 * тесно, переносится на новую строку; это решение, а не авария. Проверять, что при
 * ЛЮБОМ шрифте всё влезает в одну строку, не нужно и нельзя: такой проверки не
 * существует.
 */
val LocalFontFamily = staticCompositionLocalOf<FontFamily?> { null }

/**
 * Во сколько раз крупнее обычного набран текст **в этом месте экрана**.
 *
 * ── ПОЧЕМУ МНОЖИТЕЛЬ, А НЕ СВОИ КЕГЛИ ───────────────────────────────────────
 *
 * Решение заказчика 2026-09-16. Групп четыре — сообщения, вкладки окон, меню, шапки, —
 * и у каждой своя ручка. Своими кеглями это дало бы двадцать четыре числа на выбор
 * человеку; множителем — четыре ползунка по четыре ступени, и вёрстка сдвигается
 * предсказуемо.
 *
 * ── ПОЧЕМУ МЕСТО, А НЕ РОЛЬ ТЕКСТА ──────────────────────────────────────────
 *
 * Группы заданы местами на экране, а не ролями ([Name], [Secondary], [Tertiary]): в
 * шапке и в сообщении встречается одна и та же роль, а укрупнять их человек хочет
 * порознь. Поэтому множитель ставит **container** — каркас окна на своей шапке, ряд
 * вкладок на себе, список настроек на себе, — а всякий текст внутри его наследует.
 * Точек подстановки получается несколько штук вместо сотен.
 *
 * Умолчание 1 — обычный кегль. Место, которое множитель не поставило, не меняется:
 * это осознанно, а не пропуск.
 */
val LocalTextScale = staticCompositionLocalOf { 1f }

/** Задать множитель для всего, что внутри. */
@Composable
fun ProvideTextScale(scale: Float, content: @Composable () -> Unit) {
    CompositionLocalProvider(LocalTextScale provides scale, content = content)
}

