package io.tima.core.ui

import androidx.compose.runtime.staticCompositionLocalOf
import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/**
 * Формат: телефон, планшет, ПК.
 *
 * **Ширина добавляет полосы, но не меняет поведение окна.** Это главное правило макета
 * (`широкий.css`), и из него следует всё остальное: телефонное окно переезжает в колонку
 * целиком — со своей шапкой, вкладками и кнопками, — а широкий формат ставит рядом с ним
 * то, что на телефоне лежало поверх. Ничего не переписывается, ничего не прячется.
 *
 * Формат определяется **шириной контейнера, а не экрана**. На ПК окно приложения бывает
 * узким, а на планшете — половиной экрана в разделённом режиме; спрашивать устройство
 * значит однажды получить телефонную раскладку на ПК и наоборот.
 */
enum class Format {
    /** Одна полоса. Список и есть экран, подокно открывается перерисовкой. */
    Phone,

    /** Три полосы: рейка значками, колонка списка, главная область. */
    Tablet,

    /** Четыре полосы: рейка с подписями, колонка шире, справа страница объекта. */
    DESKTOP,
}

/**
 * Раскладка полос — посчитанная, а не выбранная из таблицы.
 *
 * Ширины взяты из `широкий.css`, но пороги из них **выводятся**: порог ПК есть сумма
 * полос, которые на ПК обязаны уместиться. Если панель станет шире, порог сдвинется сам,
 * и не будет случая, когда числа в таблице разошлись с числами в вёрстке.
 */
data class Layout(
    val format: Format,
    /** Ширина рейки окон. `null` — рейки нет: на телефоне переключение окон это подокно. */
    val rail: Dp?,
    /** Подписи у окон рейки. На планшете рейка узкая, там только значки. */
    val railCaption: Boolean,
    /** Ширина колонки списка. `null` — колонка занимает всё окно. */
    val column: Dp?,
    /** Ширина правой панели со страницей объекта. `null` — ширины на неё не хватило. */
    val panel: Dp?,
    /** Колонок в сетке медиа: карточка в одну колонку на широком экране оставляет поле пустым. */
    val mediaColumns: Int,
) {
    val phone: Boolean get() = format == Format.Phone
}

/** Пороги и ширины полос из `широкий.css`. */
object FormatTima {
    /**
     * Порог, за которым появляются полосы, — из Plan.md §К5.
     *
     * Число внешнее, но проверяемое: рейка 76 плюс колонка 360 плюс минимум главной 400
     * дают 836, то есть на 840 три полосы живут — впритык, но живут.
     */
    val PANES_THRESHOLD: Dp = 840.dp

    /** Рейка значками (планшет) и рейка с подписями (ПК). */
    val ICON_RAIL_WIDTH: Dp = 76.dp

    /**
     * Рейка с подписями — **число под самый длинный текст**, а не круглое.
     *
     * 260 = 108 обвязки строки (`RAIL_AROUND_CAPTION`: поля, значок, счётчик, зазоры)
     * плюс 152 — ширина «Свободного общения», самого длинного имени окна, набранного
     * `sz4` полужирным. Замерено измерителем текста, а не на глаз; проверку держит
     * `RailWidthTest`, и она же покраснеет, когда подпись перестанет влезать.
     *
     * Было 196, и подписи молча обрезались многоточием: «Социальн…», «Свободное об…».
     * Причина общая, и она стоит того, чтобы назвать её здесь: **кегли заданы в одном
     * месте (`TimaType`), ширины — в другом (здесь), и друг о друге они не знали.**
     * Теперь знают через проверку.
     *
     * **Другой язык ломает это снова, и это ожидаемо.** Ширину не считают в бегу:
     * от неё зависит `DESKTOP_THRESHOLD`, то есть появится ли четвёртая полоса, — и
     * раскладка, меняющаяся от загруженного перевода, отлаживается хуже, чем красный
     * тест. Перевод роняет `RailWidthTest`, и дальше это решение человека: поднять
     * число или укоротить слово.
     */
    val CAPTION_RAIL: Dp = 260.dp

    /**
     * Колонка списка — **не уже телефона** (заказчик 2026-09-27).
     *
     * Было 296 на планшете и 340 на ПК: колонка задумывалась «уже телефона на четыре
     * десятка точек». Но в колонку переезжает телефонное окно целиком, а его ряды мерены
     * на 360 (`RowFitTest`): на 296 «Группы» и «Вид» уезжали во вторую строку, хотя на
     * телефоне стояли в одной. Код общий — разной была только ширина.
     *
     * Теперь 360 — и ширина по умолчанию, и предел, уже которого колонку мышью не сдвинуть
     * ([COLUMN_MIN]).
     */
    val TABLET_COLUMN: Dp = 360.dp
    val DESKTOP_COLUMN: Dp = 360.dp

    /** Уже колонку не сдвинуть: ряды телефонного окна мерены на эту ширину. */
    val COLUMN_MIN: Dp = 360.dp

    /**
     * Сколько главной области остаётся, как ни тяни колонку, — чтобы её было видно и было
     * за что потянуть назад. Работать в ней на такой ширине не нужно.
     */
    val MAIN_DRAG_MIN: Dp = 120.dp

    /** Правая панель: страница объекта. */
    val PANEL: Dp = 300.dp

    /**
     * Меньше этого главная область бесполезна: там переписка, а не полоска.
     *
     * Ровно из этого числа и берётся ответ на «хватило ли места» третьей полосе.
     */
    val MAIN_MIN_WIDTH: Dp = 400.dp

    /** Читаемый предел содержимого: строка длиной в метр не читается. */
    val CONTENT_MAX_WIDTH: Dp = 720.dp

    /**
     * Порог ПК — **сумма полос, а не выбранное число**: рейка с подписями, колонка,
     * минимум главной и панель. 260 + 360 + 400 + 300 = **1320 dp**. Раньше этого
     * четвёртая полоса не помещается, а «правая панель появляется, только когда на неё
     * хватило места» — правило макета, а не следствие таблицы устройств.
     *
     * В комментарии до 2026-09-03 стояло 1236 — сумма со старой рейкой в 196 точек.
     * Рейку подняли до 260 ([CAPTION_RAIL]), сумма пересчиталась сама, а число в тексте
     * осталось прежним. Ровно то, от чего эта конструкция и защищает: **складываем, а не
     * переписываем**. Число здесь для чтения, и его приходится держать глазами.
     */
    val DESKTOP_THRESHOLD: Dp = CAPTION_RAIL + DESKTOP_COLUMN + MAIN_MIN_WIDTH + PANEL
}

/**
 * Раскладка по ширине контейнера.
 *
 * Это и есть «контейнерный запрос» из Plan.md: спрашивается доступная ширина, а не
 * устройство и не окно. Вызывается из [Стан], и обычно экраны его не вызывают вовсе —
 * им достаточно [LocalРаскладка].
 */
fun layoutFor(width: Dp): Layout = when {
    width < FormatTima.PANES_THRESHOLD -> Layout(
        format = Format.Phone,
        rail = null,
        railCaption = false,
        column = null,
        panel = null,
        mediaColumns = 2,
    )

    width < FormatTima.DESKTOP_THRESHOLD -> Layout(
        format = Format.Tablet,
        rail = FormatTima.ICON_RAIL_WIDTH,
        railCaption = false,
        column = FormatTima.TABLET_COLUMN,
        // Панели нет вовсе: страница объекта открывается перерисовкой главной области —
        // ровно как на телефоне. Показать её сбоку четвёртой полосой значило бы, что
        // переход никуда не читается.
        panel = null,
        mediaColumns = 3,
    )

    else -> Layout(
        format = Format.DESKTOP,
        rail = FormatTima.CAPTION_RAIL,
        railCaption = true,
        column = FormatTima.DESKTOP_COLUMN,
        panel = FormatTima.PANEL,
        mediaColumns = 4,
    )
}

/**
 * Раскладка для всего, что внутри [Стан].
 *
 * Нужна не разметке, а поведению: зона 3 на телефоне висит над списком, а на широком
 * опускается в полосу; пустая главная область на телефоне не существует вовсе. Тянуть
 * это параметром через каждый экран значило бы, что однажды не протянут.
 *
 * **Умолчания у неё нет намеренно, и это найденный случай.** Сначала здесь стояло
 * `раскладкаДля(380.dp)` — «если никто не сказал, считаем телефоном». Экран переписок,
 * нарисованный мимо `Стан`, послушно получил телефонную раскладку на тысяче точек
 * ширины: кнопка создания повисла над списком вместо того, чтобы опуститься в полосу.
 * Поймал это снимок, а не глаз. Молчаливое умолчание, которое бывает неверным, хуже
 * отказа: отказ виден сразу и называет причину.
 */
val LayoutLocal = staticCompositionLocalOf<Layout> {
    error(
        "Раскладка не предоставлена: экран обязан лежать внутри Стан. " +
            "Формат различает контейнерный запрос, и брать его «по умолчанию» нельзя — " +
            "телефонная раскладка на ПК выглядит рабочей.",
    )
}

/**
 * Что человек выставил мышью, передвигая разделители (заказчик 2026-09-27). `null` — как
 * решил формат.
 *
 * Хранится **выбор**, а не посчитанная раскладка: окно в следующий раз может открыться
 * другой ширины, и тогда выбор подгоняется под неё ([withSizes]), а не ломает её.
 */
data class StageSizes(
    /** Рейка с подписями или значками. Двух положений хватает: промежуточное обрезало бы подписи. */
    val railCaption: Boolean? = null,
    /** Ширина колонки списка. */
    val column: Dp? = null,
)

/**
 * Раскладка с учётом выбора человека.
 *
 * **Формат выбор не меняет** — сколько полос, решает ширина, как и прежде: телефон
 * остаётся одной полосой, панель ПК появляется при том же пороге. Меняются только ширины
 * внутри формата, и в пределах: колонка не уже [FormatTima.COLUMN_MIN], главная область
 * не уже [FormatTima.MAIN_DRAG_MIN].
 */
fun Layout.withSizes(sizes: StageSizes, available: Dp): Layout {
    if (phone) return this
    val caption = sizes.railCaption ?: railCaption
    val railWidth = if (caption) FormatTima.CAPTION_RAIL else FormatTima.ICON_RAIL_WIDTH
    val room = available - railWidth - (panel ?: 0.dp) - FormatTima.MAIN_DRAG_MIN
    val widest = maxOf(FormatTima.COLUMN_MIN, room)
    val wanted = sizes.column ?: column ?: FormatTima.COLUMN_MIN
    return copy(
        rail = railWidth,
        railCaption = caption,
        column = wanted.coerceIn(FormatTima.COLUMN_MIN, widest),
    )
}
