package io.tima.core.ui

import androidx.compose.runtime.staticCompositionLocalOf
import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/**
 * Формат: телефон, планшет, ПК.
 *
 * **Ширина добавляет полосы, но не меняет поведение окна.** Это главное правило макета
 * (`широкий.css`), и из него следует всё остальное: телефонное окно переезжает в колонку
 * целиком — со своей шапкой, вкладками и кнопками, — а широкий формат ставит рядом с ним
 * то, что на телефоне лежало поверх. Ничего не переписывается, ничего не прячется.
 *
 * Формат определяется **шириной контейнера, а не экрана**. На ПК окно приложения бывает
 * узким, а на планшете — половиной экрана в разделённом режиме; спрашивать устройство
 * значит однажды получить телефонную раскладку на ПК и наоборот.
 */
enum class Формат {
    /** Одна полоса. Список и есть экран, подокно открывается перерисовкой. */
    Телефон,

    /** Три полосы: рейка значками, колонка списка, главная область. */
    Планшет,

    /** Четыре полосы: рейка с подписями, колонка шире, справа страница объекта. */
    ПК,
}

/**
 * Раскладка полос — посчитанная, а не выбранная из таблицы.
 *
 * Ширины взяты из `широкий.css`, но пороги из них **выводятся**: порог ПК есть сумма
 * полос, которые на ПК обязаны уместиться. Если панель станет шире, порог сдвинется сам,
 * и не будет случая, когда числа в таблице разошлись с числами в вёрстке.
 */
data class Раскладка(
    val формат: Формат,
    /** Ширина рейки окон. `null` — рейки нет: на телефоне переключение окон это подокно. */
    val рейка: Dp?,
    /** Подписи у окон рейки. На планшете рейка узкая, там только значки. */
    val подписиРейки: Boolean,
    /** Ширина колонки списка. `null` — колонка занимает всё окно. */
    val колонка: Dp?,
    /** Ширина правой панели со страницей объекта. `null` — ширины на неё не хватило. */
    val панель: Dp?,
    /** Колонок в сетке медиа: карточка в одну колонку на широком экране оставляет поле пустым. */
    val колонокМедиа: Int,
) {
    val телефон: Boolean get() = формат == Формат.Телефон
}

/** Пороги и ширины полос из `широкий.css`. */
object TimaФорматы {
    /**
     * Порог, за которым появляются полосы, — из Plan.md §К5.
     *
     * Число внешнее, но проверяемое: рейка 76 плюс колонка 296 плюс минимум главной 400
     * дают 772, то есть на 840 три полосы действительно живут, а не притёрты.
     */
    val ПОРОГ_ПОЛОС: Dp = 840.dp

    /** Рейка значками (планшет) и рейка с подписями (ПК). */
    val РЕЙКА_ЗНАЧКИ: Dp = 76.dp
    val РЕЙКА_ПОДПИСИ: Dp = 196.dp

    /** Колонка списка. На планшете она уже телефона на четыре десятка точек. */
    val КОЛОНКА_ПЛАНШЕТ: Dp = 296.dp
    val КОЛОНКА_ПК: Dp = 340.dp

    /** Правая панель: страница объекта. */
    val ПАНЕЛЬ: Dp = 300.dp

    /**
     * Меньше этого главная область бесполезна: там переписка, а не полоска.
     *
     * Ровно из этого числа и берётся ответ на «хватило ли места» третьей полосе.
     */
    val МИНИМУМ_ГЛАВНОЙ: Dp = 400.dp

    /** Читаемый предел содержимого: строка длиной в метр не читается. */
    val ПРЕДЕЛ_СОДЕРЖИМОГО: Dp = 720.dp

    /**
     * Порог ПК — **сумма полос, а не выбранное число**: рейка с подписями, колонка,
     * минимум главной и панель. 1236 dp. Раньше этого четвёртая полоса не помещается, а
     * «правая панель появляется, только когда на неё хватило места» — правило макета, а
     * не следствие таблицы устройств.
     */
    val ПОРОГ_ПК: Dp = РЕЙКА_ПОДПИСИ + КОЛОНКА_ПК + МИНИМУМ_ГЛАВНОЙ + ПАНЕЛЬ
}

/**
 * Раскладка по ширине контейнера.
 *
 * Это и есть «контейнерный запрос» из Plan.md: спрашивается доступная ширина, а не
 * устройство и не окно. Вызывается из [Стан], и обычно экраны его не вызывают вовсе —
 * им достаточно [LocalРаскладка].
 */
fun раскладкаДля(ширина: Dp): Раскладка = when {
    ширина < TimaФорматы.ПОРОГ_ПОЛОС -> Раскладка(
        формат = Формат.Телефон,
        рейка = null,
        подписиРейки = false,
        колонка = null,
        панель = null,
        колонокМедиа = 2,
    )

    ширина < TimaФорматы.ПОРОГ_ПК -> Раскладка(
        формат = Формат.Планшет,
        рейка = TimaФорматы.РЕЙКА_ЗНАЧКИ,
        подписиРейки = false,
        колонка = TimaФорматы.КОЛОНКА_ПЛАНШЕТ,
        // Панели нет вовсе: страница объекта открывается перерисовкой главной области —
        // ровно как на телефоне. Показать её сбоку четвёртой полосой значило бы, что
        // переход никуда не читается.
        панель = null,
        колонокМедиа = 3,
    )

    else -> Раскладка(
        формат = Формат.ПК,
        рейка = TimaФорматы.РЕЙКА_ПОДПИСИ,
        подписиРейки = true,
        колонка = TimaФорматы.КОЛОНКА_ПК,
        панель = TimaФорматы.ПАНЕЛЬ,
        колонокМедиа = 4,
    )
}

/**
 * Раскладка для всего, что внутри [Стан].
 *
 * Нужна не разметке, а поведению: зона 3 на телефоне висит над списком, а на широком
 * опускается в полосу; пустая главная область на телефоне не существует вовсе. Тянуть
 * это параметром через каждый экран значило бы, что однажды не протянут.
 *
 * **Умолчания у неё нет намеренно, и это найденный случай.** Сначала здесь стояло
 * `раскладкаДля(380.dp)` — «если никто не сказал, считаем телефоном». Экран переписок,
 * нарисованный мимо `Стан`, послушно получил телефонную раскладку на тысяче точек
 * ширины: кнопка создания повисла над списком вместо того, чтобы опуститься в полосу.
 * Поймал это снимок, а не глаз. Молчаливое умолчание, которое бывает неверным, хуже
 * отказа: отказ виден сразу и называет причину.
 */
val LocalРаскладка = staticCompositionLocalOf<Раскладка> {
    error(
        "Раскладка не предоставлена: экран обязан лежать внутри Стан. " +
            "Формат различает контейнерный запрос, и брать его «по умолчанию» нельзя — " +
            "телефонная раскладка на ПК выглядит рабочей.",
    )
}
