package io.tima.core.ui

/**
 * Вкладки, фильтры и режимы окон — **ключами, а не надписями** (ПЛАН-ЯЗЫКА Я2).
 *
 * ── ЗАЧЕМ ЭТО ОТДЕЛЬНЫЙ ТИП ─────────────────────────────────────────────────
 *
 * До этой партии вкладка была строкой и служила сразу двумя вещами: надписью на экране и
 * ключом в `when (tab) { "Общая" -> … }`. Перевести такую строку нельзя: перевод сменил бы
 * ключ, и окно перестало бы находить свою вкладку. Это ровно тот случай, ради которого в
 * плане и выбран словарь на Kotlin.
 *
 * Теперь ключ — значение этого перечня, а слово приходит из [TabWords].
 *
 * ── ПОЧЕМУ ОДИН ПЕРЕЧЕНЬ НА ВСЁ ─────────────────────────────────────────────
 *
 * Вкладки, фильтры второго ряда и режимы окна ведут себя одинаково: их выбирают, они
 * помнятся, их надо назвать. Три перечня отличались бы только именем типа, а совпадающие
 * слова («Каталог» и вкладкой, и подвкладкой) пришлось бы заводить дважды и переводить
 * дважды.
 *
 * ── ЧЕГО ЗДЕСЬ НЕТ ──────────────────────────────────────────────────────────
 *
 * **Разделов книги контактов.** Их придумывает человек, они приходят из его телефона —
 * это данные, а не словарь, и переводить их нельзя. Ряд фильтров умеет и строки, и этот
 * перечень: см. `FilterRow`.
 */
enum class WindowTab {
    // Окно 1 «Телефон».
    Chats,
    Contacts,
    Calls,
    View,

    // Фильтры журнала звонков.
    All,
    FromBook,
    Unknown,
    Missed,

    // Окна 2 и 3.
    Common,
    Friends,
    Catalogue,

    // Окно 3: два способа смотреть одно и то же.
    Feed,
    Slides,

    // Окно 4.
    Answers,
    Reactions,
    Collections,

    // Фильтры «Реакций».
    Comments,
    Marks,

    // Окно 5.
    Subscribed,
    Groups,

    // Подвкладки и контур «Коллекций».
    Media,
    Messages,
    Open,
    Personal,
}
