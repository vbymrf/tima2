}

/**
 * Два цвета, которые теме не подчиняются: **чёрный по белому**.
 *
 * ── ЗАЧЕМ ВООБЩЕ БЫВАЕТ ЦВЕТ ВНЕ ТЕМЫ ───────────────────────────────────────
 *
 * Своя тема открыта целиком: семнадцать цветов, и белый текст на белом фоне никто не
 * запрещает. Пока экран подбора цветов рисовался этой же темой, он **сам** становился
 * нечитаемым первым — и человек оставался с экраном, на котором не видно ни строк, ни
 * кнопки возврата. Выход из положения обязан быть виден из самого положения.
 *
 * Заказчик назвал это прямо 2026-09-03: «сделать две отдельные переменные, чёрным по
 * белому фону, и не менять их ни при каких режимах».
 *
 * **Двух цветов мало, чтобы нарисовать список**, поэтому рядом лежит [appearance] —
 * палитра экрана оформления целиком. Она берёт светлую тему и **прибивает в ней ровно
 * эти два значения**: остальное — линии, тихие подложки, салатовая кнопка — светлой темы
 * и правке не подлежит, потому что светлая тема не редактируется вовсе.
 */
object TimaFixed {
    /** Фон. Белый и только белый. */
    val paper: Color = Color(0xFFFFFFFF)

    /** Текст. Чёрный и только чёрный. */
    val ink: Color = Color(0xFF000000)

    /**
     * Чем рисуется экран «Оформление» — при любой выбранной теме.
     *
     * Цена названа: **на этом экране своя тема не показывается**. Раньше он был и
     * подбором, и предпросмотром сразу; теперь предпросмотр остался за образцами цветов
     * в строках и за всем остальным приложением, а сам экран читается всегда.
     */
    val appearance: TimaColors = TimaColors.light.copy(surface = paper, text = ink)
}

/**
 * Формы. **Два языка формы, и они не смешиваются:** квадрат означает «кто-то или
 * что-то», круг — «нажми».
 *
 * Тема на геометрию не влияет: тема — это про значения.
 */
object TimaShapes {
    /** Кнопки, поле ввода, чипы, счётчики. */
    val circle: Dp = 999.dp

    /** Пузырь сообщения. */
    val radius: Dp = 16.dp
    val smallRadius: Dp = 12.dp

    /** Аватары и логотипы: квадрат со скруглёнными краями. */
    val square: Dp = 10.dp
    val smallSquare: Dp = 8.dp
    val bigSquare: Dp = 16.dp
}

/** Отступы: `--о1`…`--о6`. */
object TimaSpacing {
    val about1: Dp = 4.dp
    val about2: Dp = 8.dp
    val about3: Dp = 12.dp
    val about4: Dp = 16.dp
    val about5: Dp = 22.dp
    val about6: Dp = 28.dp
}

/** Кегли: `--щ1`…`--щ6`. */
object TimaType {
    val sz1: TextUnit = 30.sp
    val sz2: TextUnit = 22.sp
    val sz3: TextUnit = 17.sp
    val sz4: TextUnit = 15.sp
    val sz5: TextUnit = 13.sp
    val sz6: TextUnit = 11.sp

    /**
     * Семейство. В макете первым стоит Inter, дальше системные подстановки; шрифт в
     * сборку пока не кладётся — это отдельное решение с лицензией и весом.
     */
    val family: List<String> = listOf(
        "Inter", "Helvetica Neue", "Arial", "Segoe UI", "system-ui", "sans-serif",
    )
}

/**
 * Зоны экрана из макета: шапка и нижняя полоса.
 *
 * Числа взяты из `--зона1`, `--зона4`, `--ава`. Зоны 2 и 3 — содержимое и вкладки,
 * у них своей высоты нет: они занимают остаток.
 */
object TimaZones {
    val zone1: Dp = 56.dp
    val zone4: Dp = 62.dp
    val avatar: Dp = 42.dp

    /**
     * Порог широкого формата (У.4). До него — телефонная раскладка, после — полосы.
     * Одно число на все форматы: контейнерные запросы, а не три разметки.
     */
    val wideThreshold: Dp = 840.dp
}
