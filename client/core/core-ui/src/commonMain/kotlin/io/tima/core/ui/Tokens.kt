/**
 * Токены дизайн-системы — У.1.
 *
 * Значения перенесены из действующего макета: `doc/Layout-UI-light/стиль.css` и слой
 * переопределений `doc/Layout-UI-dark/тьма.css`. **Один набор токенов, две темы** —
 * это и есть признак готовности У.1: экран не знает, в какой теме он рисуется.
 *
 * **Имена сохранены русскими намеренно.** Макет — источник, и сверять его с кодом
 * придётся глазами ещё много раз; `навигация` рядом с `--навигация` сверяется мгновенно,
 * а `navigationAccent` требует держать в голове перевод. Цена перевода — расхождение,
 * которое никто не заметит.
 *
 * Чего здесь нет: `#0077cc` и `#196dff`. В действующей редакции они остались без
 * назначения, и заводить токен без смысла — значит предлагать его применить.
 *
 * Нет и **цвета названия окна**, хотя соблазн был. Он не значение, а следствие места:
 * внутри салатовой плашки название берёт цвет текста на заливке ([onAccent]), в
 * подокне плашки нет и название набрано обычным текстом ([text]). Отдельный токен
 * закрепил бы устаревшую прозу README («набрано салатовым»), которой сам же макет и
 * противоречит: `.имя-окна { color: #ffffff }` в плашке, `var(--текст)` в подокне.
 *
 * С 2026-09-02 отдельный токен не нужен и подавно: [onAccent] белый в обеих темах, то
 * есть ровно `#ffffff` макета.
 */
data class TimaColors(
    /** Навигация и действие: логотип, текущее окно, «назад», «отправить», «написать». */
    val navigation: Color,
    /** Активность: новые сообщения, комментарии, непрочитанное. */
    val activity: Color,
    /** Подтверждено: доставлено, прочитано, E2E. */
    val confirmed: Color,
    /** Фон **моих** сообщений. */
    val my: Color,
    /** Фон сообщений **автора**. */
    val author: Color,
    val text: Color,
    /** Общий фон содержимого: лента и переписка. */
    val surface: Color,
    /**
     * Фон функциональных областей: шапка с логотипом, вкладки, строка ввода.
     *
     * Третий признак поверх формы и цвета: **где приложение показывает — фона нет; где
     * им управляют — есть.** Работает даже там, где цвета не видно.
     */
    val functional: Color,
    /**
     * Текст на зелёной **заливке**: кнопки, плашка шапки, вкладки, чипы.
     *
     * **Белый в обеих темах** — решение заказчика 2026-09-02, и оно же снимает
     * прежнее расхождение с макетом. До этого в светлой теме здесь стоял чёрный
     * (решение 2026-08-23, довод — мелкие подписи), и код был единственным местом,
     * где текст на салатовом не белый.
     */
    val onAccent: Color,

    /**
     * Текст на **янтарной** заливке: счётчики непрочитанного.
     *
     * Чёрный в обеих темах, и это отдельный токен, а не [текст]. Причина в источнике:
     * README говорит «янтарь сохранил чёрный текст, 12,32 : 1, и терять его не за что»,
     * а `стиль.css` задаёт счётчику `var(--текст)` — то есть в тёмной теме белый по
     * янтарю, около 1,7 : 1. Взята версия README: правило про янтарь сформулировано
     * явно, а `var(--текст)` там скорее недосмотр наследования.
     */
    val onAmber: Color,

    /**
     * Заливка элементов **внутри салатовой плашки** шапки: логотип, круглые кнопки.
     *
     * Белая в обеих темах — и это не «жёсткий цвет», а следствие: плашка в обеих темах
     * одна и та же салатовая, значит и то, что лежит на ней, одинаково. Внутри плашки
     * даже «живая» кнопка становится белой: салатовое на салатовом не видно.
     */
    val inPlate: Color,

    /** Рамка сообщения переписки. */
    val border: Color,
    /** Линия между записями списка и ленты. */
    val line: Color,
    /** Приглушённый текст: подписи, время. */
    val text2: Color,
    /** Ещё тише: третий уровень. */
    val text3: Color,
    /** Мягкая подложка акцента: выделение без заливки. */
    val softAccent: Color,

    /**
     * Тихая **нецветная** подложка: `--чёрный-6` макета.
     *
     * Ею залиты невыбранная подвкладка и капсула переключателя режимов. Отличается от
     * [softAccent] тем, что не несёт оттенка навигации, и в этом весь смысл: ряд
     * подвкладок обязан читаться иначе, чем ряд вкладок над ним, иначе экран
     * показывает два одинаковых ряда, из которых один почему-то главнее.
     *
     * **Заметнее фона, а не равна ему.** В светлой теме это 6 % чёрного против 3 % у
     * подложки — ровно как в макете. В тёмной макет задаёт `--чёрный-6` как 7 % белого,
     * то есть **в точности свой же функциональный фон**, и подвкладка там пропала бы
     * вовсе; взята следующая ступень той же лестницы, 14 %.
     */
    val quiet: Color,
    /**
     * Эмоции — **нецветные**. Цвет занят кодом, и раскрасить эмоции значило бы отдать
     * им смысл, которого у них нет: девять цветов рядом с тремя значащими.
     */
    val emotion: Color,

    /**
     * QR-код: чернила и бумага. **Одинаковы в обеих темах, и это не упущение.**
     *
     * Код читает чужая программа, а не человек. Часть сканеров не берёт светлые модули на
     * тёмном фоне, и «код не сканируется» человек прочтёт как поломку привязки, а не как
     * выбранную нами тему. Поэтому код всегда тёмным по светлому — и на тёмной теме
     * выглядит светлым пятном намеренно.
     */
    val inkCode: Color,
    val paperCode: Color,
) {
    companion object {

        /** Светлая тема: `doc/Layout-UI-light/стиль.css`. */
        val light = TimaColors(
            navigation = Color(0xFF8AC44A),
            activity = Color(0xFFFEBB02),
            confirmed = Color(0xFF3BB300),
            my = Color(0xFFBFBFBF),
            author = Color(0xFFFFFFFF),
            text = Color(0xFF000000),
            surface = Color(0xFFFFFFFF),
            functional = Color(0xFFF7F7F7),
            // Белый: решение заказчика 2026-09-02, отменяет чёрный от 2026-08-23.
            // Формулировка — «всё, что на зелёном фоне сейчас во вкладках и
            // навигационное, и текст окон в шапке; по сути как в макете».
            //
            // Цена известна и принята: 2,08 : 1 при пороге 4,5. Прежнее решение брало
            // 10,08, и доводом были мелкие подписи — «E2E», галочки, чипы. Довод
            // проиграл единству: в макете на салатовом белым набрано ВСЁ
            // (`.имя-окна`, `.таб.тек`, `.чип.выбран`, `.чип.акц`, `.икона.жив`,
            // `.режим.тек`), и держать код единственным местом, где это не так,
            // означало сверять с макетом каждый элемент по отдельности.
            onAccent = Color(0xFFFFFFFF),
            onAmber = Color(0xFF000000),
            inPlate = Color(0xFFFFFFFF),
            border = Color(0x47000000),
            line = Color(0x24000000),
            text2 = Color(0xB3000000),
            text3 = Color(0x9E000000),
            softAccent = Color(0x338AC44A),
            quiet = Color(0x0F000000),
            emotion = Color(0xFF111111),
            inkCode = Color(0xFF000000),
            paperCode = Color(0xFFFFFFFF),
        )

        /**
         * Тёмная тема: `doc/Layout-UI-dark/тьма.css`.
         *
         * Отношение фонов сообщений сохранено: **автор светлее меня**, только опущено по
         * серой лестнице (`#ffffff → #3d3d3d`, `#bfbfbf → #1a1a1a`). Цвета кода —
         * салатовый, янтарь, зелёный — те же: перекрашивать их не пришлось.
         */
        val dark = TimaColors(
            // Тёмно-зелёный, а не салатовый: решение заказчика 2026-09-03 — «для тёмной
            // темы навигация и действие устанавливаем цвет ff024408 по умолчанию».
            //
            // **Цена решения известна и она не одна.** Заливкой цвет работает отлично:
            // белым по нему 11,45 : 1 вместо прежних 2,08, то есть плашка, кнопки и
            // текущая вкладка стали читаться ЛУЧШЕ. А вот тонкой чертой по тёмному фону
            // он не работает вовсе — 1,34 : 1 у обводки режима и 1,05 : 1 у полосы
            // автора. Числа держит `TokensTest`, чтобы они не потерялись: это места, где
            // решение ещё предстоит дополнить.
            navigation = Color(0xFF024408),
            activity = Color(0xFFFEBB02),
            confirmed = Color(0xFF3BB300),
            my = Color(0xFF1A1A1A),
            author = Color(0xFF3D3D3D),
            text = Color(0xFFFFFFFF),
            surface = Color(0xFF000000),
            functional = Color(0x12FFFFFF),
            // Белый: решение заказчика 2026-08-23. В тёмной теме весь текст белый, и
            // делать зелёную заливку единственным исключением значило бы вводить
            // правило ради одного места. Цена известна и принята: 2,08 : 1.
            onAccent = Color(0xFFFFFFFF),
