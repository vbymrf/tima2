package io.tima.core.ui

import kotlin.test.Test
import kotlin.test.assertEquals

/**
 * Номер из двух полей — решение заказчика 2026-09-15: на цифровой клавиатуре нет плюса.
 *
 * Одно правило на все пять экранов, где вводят телефон; здесь оно и проверяется, а не
 * пять раз по-своему.
 */
class PhoneFieldsTest {

    @Test
    fun набранное_без_плюса_получает_код_страны() {
        assertEquals("+79990000105", fullPhone("7", "999 000 01 05"))
        assertEquals("+380501234567", fullPhone("380", "(50) 123-45-67"))
    }

    @Test
    fun вставленное_с_плюсом_берётся_целиком_и_код_не_приписывается() {
        // Иначе вышло бы «+77999…» — номер, которого нет. Поймано тестом входа.
        assertEquals("+79990000105", fullPhone("7", "+7 999 000-01-05"))
        assertEquals("+380501234567", fullPhone("7", "+380 50 123 45 67"))
    }

    @Test
    fun пустой_номер_даёт_пустоту_а_не_один_код() {
        assertEquals("", fullPhone("7", ""))
        assertEquals("", fullPhone("7", "   "))
    }

    @Test
    fun в_коде_страны_учитываются_только_цифры() {
        assertEquals("+79990000105", fullPhone("+7 ", "9990000105"))
    }
}
