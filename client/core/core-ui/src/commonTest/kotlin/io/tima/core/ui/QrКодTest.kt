package io.tima.core.ui

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertNotNull
import kotlin.test.assertNull

/**
 * QR-код сверяется **с чужим кодировщиком**, а не сам с собой.
 *
 * Иначе проверять было бы нечего: свой кодировщик и своя проверка договорятся о любой
 * ошибке, а узнается она тем, что телефон не видит код на экране — без единого указания,
 * что именно разошлось с ISO/IEC 18004. Поэтому эталонные матрицы посчитаны сторонней
 * реализацией того же стандарта (`segno`) и здесь закреплены.
 *
 * Три вектора выбраны по тому, **что каждый из них включает**:
 *
 * | Вектор | Что проверяется |
 * |---|---|
 * | 21×21, версия 1 | счётчик знаков 8 бит, один блок, ни выравнивающих узоров, ни номера версии |
 * | 41×41, версия 6 | четыре блока коррекции с чередованием, выравнивающие узоры |
 * | 65×65, версия 12 | счётчик 16 бит, две группы блоков разной длины, номер версии, наш настоящий код привязки |
 *
 * **Что сверка уже поймала.** Первая копия информации о формате была записана с
 * перепутанными столбцом и строкой: различий всего в двух линиях — восьмой строке и
 * восьмом столбце, — но такой код не читается вовсе, потому что сканер начинает именно с
 * формата. Ни один самосогласованный тест этого бы не увидел.
 *
 * **Где эталон пришлось поправить.** `segno` добавляет байт нулей и тогда, когда поток и
 * так лежит на границе кодового слова (`8 - length % 8` даёт 8, а не 0). ISO/IEC 18004
 * §7.4.10 требует добивочных бит только когда граница НЕ достигнута. Сканеру разницы нет —
 * лишний байт стоит после завершителя, — но матрицы расходятся, поэтому векторы посчитаны
 * с этой одной строкой, приведённой к стандарту. Всё остальное в эталоне своё: коррекция,
 * чередование, раскладка, маски, BCH.
 */
class QrКодTest {

    /**
     * Настоящий код привязки: та самая строка, какую строит сервер (`device_link.go`) —
     * 258 знаков, версия 12.
     */
    private val кодПривязки = "tima://link/v1?session_id=aaaaaaaa-0000-0000-0000-00000000c4a7" +
        "&secret=AAECAwQFBgcICQoLDA0ODxAREhMUFRYXGBkaGxwdHh8" +
        "&encryption_key=AAECAwQFBgcICQoLDA0ODxAREhMUFRYXGBkaGxwdHh8" +
        "&signing_key=AAMGCQwPEhUYGx4hJCcqLTAzNjk8P0JFSEtOUVRXWl0" +
        "&name=0JrQvtC80L_RjNGO0YLQtdGA"

    @Test
    fun матрица_версии_1_совпадает_с_эталоном() {
        val матрица = assertNotNull(QrКод.матрица("HELLO WORLD"))

        assertEquals(21, матрица.размер, "11 знаков влезают в первую версию")
        assertEquals(ЭТАЛОН_HELLO, матрица.строки())
    }

    @Test
    fun матрица_с_чередованием_блоков_совпадает_с_эталоном() {
        val матрица = assertNotNull(QrКод.матрица("x".repeat(100)))

        assertEquals(41, матрица.размер, "100 байт — шестая версия при уровне M")
        assertEquals(6879806635924208815L, свёртка(матрица))
    }

    /**
     * Наш настоящий вход. Здесь сходится всё сразу: счётчик 16 бит, две группы блоков
     * разной длины, номер версии — и выбор маски, который делается по штрафам.
     */
    @Test
    fun код_привязки_совпадает_с_эталоном() {
        val матрица = assertNotNull(QrКод.матрица(кодПривязки))

        assertEquals(65, матрица.размер, "258 знаков — двенадцатая версия")
        assertEquals(7384925942544133665L, свёртка(матрица))
    }

    /**
     * Маска выбирается по штрафам, и выбор сходится с эталоном.
     *
     * Проверка отдельная, потому что ошибка здесь своя: матрица собрана верно, а маска
     * взята другая — код при этом **читается** (номер маски записан в самом формате), и
     * расхождение выглядит как «просто другая картинка». Поймать его можно только сверив
     * выбор.
     */
    @Test
    fun маска_выбирается_та_же_что_у_эталона() {
        assertEquals(
            QrКод.матрица("HELLO WORLD", маскаНасильно = 4)?.строки(),
            QrКод.матрица("HELLO WORLD")?.строки(),
            "для этого входа наименьший штраф у маски 4",
        )
        assertEquals(
            QrКод.матрица(кодПривязки, маскаНасильно = 2)?.строки(),
            QrКод.матрица(кодПривязки)?.строки(),
            "для кода привязки — у маски 2",
        )
    }

    /**
     * Что не влезло — **не показывается**.
     *
     * Пятнадцатая версия держит 412 байт. Взять версию побольше значило бы показать
     * человеку код, который его телефон не разберёт, — а «не отсканировалось» он прочтёт
     * как поломку привязки.
     */
    @Test
    fun слишком_длинное_не_кодируется() {
        assertNull(QrКод.матрица("я".repeat(500)))
    }

    /** Пустая строка — тоже код: он валидный, просто ни о чём. Падать здесь нечему. */
    @Test
    fun пустая_строка_кодируется() {
        assertEquals(21, assertNotNull(QrКод.матрица("")).размер)
    }

    /**
     * FNV-1a, 64 бита — свёртка матрицы.
     *
     * Не криптография: нужно короткое сравнимое число, а эталон посчитан тем же способом.
     * Криптографический хеш потребовал бы зависимости в дизайн-системе, которой там быть
     * незачем. Матрица версии 1 записана целиком именно поэтому: свёртка не показывает,
     * что разошлось, а двадцать одна строка показывает.
     */
    private fun свёртка(матрица: QrМатрица): Long {
        var h = -3750763034362895579L // 0xcbf29ce484222325
        for (знак in матрица.строки().joinToString("")) {
            h = (h xor знак.code.toLong()) * 1099511628211L
        }
        return h
    }

    private companion object {

        /** `segno.make_qr("HELLO WORLD", error="m", mode="byte")`, без тихой зоны. */
        val ЭТАЛОН_HELLO = """
            111111101100101111111
            100000100001001000001
            101110100101001011101
            101110101001001011101
            101110101110101011101
            100000101001001000001
            111111101010101111111
            000000001001100000000
            100010111111011111001
            000100001011100001111
            001111110011011010010
            111110001100010000000
            111110101010101100110
            000000001010111101011
            111111101110101011010
            100000100101110110011
            101110101101011000110
            101110100100100011011
            101110100111000111000
            100000100001010000000
            111111101111111110101
        """.trimIndent().lines().map { it.trim() }
    }
}
