package io.tima.core.ui

import androidx.compose.ui.graphics.Color
import kotlin.math.abs
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith
import kotlin.test.assertTrue

/**
 * Токены и контраст.
 *
 * **Главное здесь — не «цвет равен цвету».** Главное — что названные в макете
 * отношения контраста стали числами, которые проверяются. Макет прямо говорит, где
 * решение принято ниже порога и какой у него ценник; пока это живёт только в тексте,
 * любая правка палитры меняет цену молча.
 */
class TokensTest {

    private fun близко(ожидалось: Double, получено: Double, допуск: Double = 0.02) {
        assertTrue(
            abs(ожидалось - получено) <= допуск,
            "ожидалось $ожидалось : 1, получено ${(получено * 100).toInt() / 100.0} : 1",
        )
    }

    // ── отношения, названные в макете ────────────────────────────────────────

    @Test
    fun в_светлой_теме_текст_на_зелёном_чёрный_и_порог_берёт() {
        // Решение заказчика 2026-08-23. В светлой теме белый по салатовому давал
        // 2,08 : 1 при пороге 4,5 — на мелких подписях («E2E», галочки, чипы) это
        // разница между «читается» и «угадывается».
        val отношение = TimaContrast.отношение(TimaColors.светлая.наАкценте, TimaColors.светлая.навигация)
        близко(10.08, отношение)
        assertTrue(отношение >= TimaContrast.ПОРОГ_ТЕКСТА, "чёрный на салатовом обязан брать порог")

        // И на зелёном «подтверждено» тот же чёрный тоже читается.
        близко(7.63, TimaContrast.отношение(TimaColors.светлая.наАкценте, TimaColors.светлая.подтверждено))
    }

    @Test
    fun в_тёмной_теме_текст_на_зелёном_белый_и_цена_принята() {
        // Тоже решение заказчика, и обратное по цвету: в тёмной теме весь текст белый,
        // и делать зелёную заливку единственным исключением значило бы вводить правило
        // ради одного места. Цена — 2,08 : 1, и тест держит её на виду, а не спорит.
        val отношение = TimaContrast.отношение(TimaColors.тёмная.наАкценте, TimaColors.тёмная.навигация)
        близко(2.08, отношение)
        assertTrue(
            отношение < TimaContrast.ПОРОГ_ТЕКСТА,
            "если это однажды возьмёт порог — значит палитру поменяли, и решение надо перечитать",
        )
    }

    @Test
    fun текст_на_зелёном_в_темах_разный_и_это_решение() {
        // Не недосмотр и не наследие: одна и та же салатовая заливка несёт разный по
        // цвету текст, потому что вокруг неё разный фон. Если однажды это сведут к
        // одному цвету — пусть сведут явно, уронив этот тест.
        assertTrue(TimaColors.светлая.наАкценте != TimaColors.тёмная.наАкценте)
    }

    @Test
    fun название_окна_салатовым_по_светлой_шапке_ниже_любого_порога() {
        // 1,95 : 1 — не берётся даже порог крупного текста (3 : 1). Записано в README
        // как известная беда с перечисленными выходами.
        //
        // Смотрим ИМЕННО через названиеОкна, а не через навигацию: это отдельная
        // переменная, и менять её надо будет не задевая текст на заливке.
        val отношение = TimaContrast.отношение(TimaColors.светлая.названиеОкна, TimaColors.светлая.функц)
        близко(1.95, отношение)
        assertTrue(отношение < TimaContrast.ПОРОГ_КРУПНОГО)
    }

    @Test
    fun в_тёмной_теме_то_же_название_читается_хорошо() {
        // 8,99 : 1 — README предлагает это как один из выходов: оставить зелёное
        // название только в тёмной теме.
        val фон = TimaContrast.наложить(TimaColors.тёмная.функц, TimaColors.тёмная.поверхность)
        близко(8.99, TimaContrast.отношение(TimaColors.тёмная.названиеОкна, фон), допуск = 0.15)
    }

    @Test
    fun янтарь_сохранил_чёрный_текст_и_это_видно_по_числу() {
        близко(12.32, TimaContrast.отношение(Color.Black, TimaColors.светлая.активность))
    }

    @Test
    fun фоны_сообщений_читаются_в_обеих_темах() {
        // Светлая: мои 11,42 : 1, автор 21 : 1 — оба с чёрным текстом.
        близко(11.42, TimaContrast.отношение(TimaColors.светлая.текст, TimaColors.светлая.мои))
        близко(21.0, TimaContrast.отношение(TimaColors.светлая.текст, TimaColors.светлая.автор))

        // Тёмная: те же роли, значения опущены по серой лестнице, текст белый.
        близко(10.86, TimaContrast.отношение(TimaColors.тёмная.текст, TimaColors.тёмная.автор), допуск = 0.1)
        близко(17.40, TimaContrast.отношение(TimaColors.тёмная.текст, TimaColors.тёмная.мои), допуск = 0.1)
    }

    @Test
    fun основной_текст_на_поверхности_проходит_порог_в_обеих_темах() {
        for ((имя, тема) in listOf("светлая" to TimaColors.светлая, "тёмная" to TimaColors.тёмная)) {
            val отношение = TimaContrast.отношение(тема.текст, тема.поверхность)
            assertTrue(
                отношение >= TimaContrast.ПОРОГ_ТЕКСТА,
                "$имя: основной текст обязан проходить порог, а даёт $отношение : 1",
            )
        }
    }

    // ── отношения тем между собой ────────────────────────────────────────────

    @Test
    fun автор_светлее_меня_в_обеих_темах() {
        // Отношение выбрано осознанно и сохранено при переносе в тёмную: «автор светлее
        // меня». Если однажды поменяется — пусть меняется явно, а не как побочный эффект
        // правки серой лестницы.
        assertTrue(
            яркость(TimaColors.светлая.автор) > яркость(TimaColors.светлая.мои),
            "светлая: автор обязан быть светлее моих",
        )
        assertTrue(
            яркость(TimaColors.тёмная.автор) > яркость(TimaColors.тёмная.мои),
            "тёмная: отношение обязано сохраниться",
        )
    }

    @Test
    fun цвета_кода_в_темах_совпадают() {
        // Салатовый, янтарь и зелёный работают заливкой в обеих темах, и перекрашивать
        // их не пришлось. Это тоже решение, и оно держится тестом.
        assertEquals(TimaColors.светлая.навигация, TimaColors.тёмная.навигация)
        assertEquals(TimaColors.светлая.активность, TimaColors.тёмная.активность)
        assertEquals(TimaColors.светлая.подтверждено, TimaColors.тёмная.подтверждено)
    }

    @Test
    fun поверхность_и_текст_в_темах_обратны_друг_другу() {
        assertEquals(TimaColors.светлая.поверхность, TimaColors.тёмная.текст)
        assertEquals(TimaColors.светлая.текст, TimaColors.тёмная.поверхность)
    }

    @Test
    fun эмоции_нецветные_в_обеих_темах() {
        // Цвет занят кодом. Раскрасить эмоции значило бы отдать им смысл, которого у
        // них нет: девять цветов рядом с тремя значащими.
        for ((имя, тема) in listOf("светлая" to TimaColors.светлая, "тёмная" to TimaColors.тёмная)) {
            val ц = тема.эмоция
            assertTrue(
                abs(ц.red - ц.green) < 0.01f && abs(ц.green - ц.blue) < 0.01f,
                "$имя: эмоции обязаны быть серыми, а получено $ц",
            )
        }
    }

    // ── инструмент ───────────────────────────────────────────────────────────

    @Test
    fun контраст_прозрачного_цвета_считать_отказывается() {
        // «Контраст рамки» без указания подложки — число ни о чём: полупрозрачный цвет
        // выглядит по-разному на разном фоне.
        assertFailsWith<IllegalArgumentException> {
            TimaContrast.отношение(TimaColors.светлая.линия, TimaColors.светлая.поверхность)
        }
    }

    @Test
    fun наложение_прозрачного_на_фон_даёт_то_что_видит_человек() {
        // Линия 14 % чёрного на белом — это светло-серый, и контраст у него небольшой.
        val видимая = TimaContrast.наложить(TimaColors.светлая.линия, TimaColors.светлая.поверхность)
        assertEquals(1f, видимая.alpha)
        assertTrue(
            TimaContrast.отношение(видимая, TimaColors.светлая.поверхность) < 1.5,
            "линия обязана быть тихой: она разделяет, а не привлекает",
        )
    }

    @Test
    fun крайние_случаи_шкалы_сходятся() {
        близко(21.0, TimaContrast.отношение(Color.Black, Color.White))
        близко(1.0, TimaContrast.отношение(Color.White, Color.White))
    }

    private fun яркость(цвет: Color): Double =
        0.2126 * цвет.red + 0.7152 * цвет.green + 0.0722 * цвет.blue
}
