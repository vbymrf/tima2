package io.tima.core.secrets

import kotlin.jvm.JvmInline

/**
 * Хранилище ключевого материала — К3.8, [Plan.md §3.6](../../../../../../../../doc_mig/Plan.md).
 *
 * **Почему это отдельный модуль и почему хранилище — часть формата.** Ключ покоя
 * локальной базы выводится из секрета устройства: `HKDF(deviceSecret,
 * "tima/local-store/v1")`. В v1 на ПК этот секрет лежал **открытым файлом рядом с
 * файлом базы**, то есть шифрование покоя было декоративным: тот, кто дошёл до базы,
 * дошёл и до ключа. Отсюда правило плана: «хранилище ключа — часть формата, а не
 * деталь реализации».
 *
 * Здесь **только хранение байт**. Ни вывода ключей, ни шифрования, ни знания о том,
 * что за секрет лежит внутри: криптография живёт в `core-encryption`, и тянуть её в
 * модуль, чья задача — сходить в Keychain, значило бы связать несвязанное.
 *
 * Реализации по платформам ([platformVault]): Keystore на Android, Keychain на Apple,
 * DPAPI на Windows. **Реализации «в памяти» или «файлом рядом» в боевом коде нет** —
 * это тот же дефект v1 в другой одежде.
 */
interface SecretVault {

    /**
     * Кладёт секрет, **перезаписывая** прежний под тем же именем.
     *
     * Перезапись, а не отказ: смена секрета устройства — обычный путь (переустановка,
     * повторная привязка), и отдельный `replace` заставлял бы каждого вызывающего
     * помнить, какой из двух вызвать.
     */
    fun put(alias: SecretAlias, secret: ByteArray)

    /** @return `null`, если секрета нет. Отсутствие — не ошибка: первый запуск. */
    fun get(alias: SecretAlias): ByteArray?

    /**
     * Удаляет секрет. Отсутствующий секрет — не ошибка: выход из аккаунта может
     * случиться и после того, как хранилище уже вычистили.
     *
     * @return был ли секрет.
     */
    fun remove(alias: SecretAlias): Boolean
}

/**
 * Имя секрета в хранилище.
 *
 * Проверка не формальность: на ПК хранилище кладёт секреты **файлами**, и имя вида
 * `../../что-нибудь` записало бы за пределы своего каталога. Разрешены строчные
 * латинские буквы, цифры, точка, дефис и подчёркивание — этого хватает, а всё
 * остальное отсекается здесь, один раз, а не в каждой реализации.
 */
@JvmInline
value class SecretAlias(val value: String) {

    init {
        require(value.isNotBlank()) { "имя секрета пустое" }
        require(value.length <= MAX_LENGTH) { "имя секрета длиннее $MAX_LENGTH: $value" }
        require(value.all { it in ALLOWED }) {
            "имя секрета содержит запрещённые знаки: $value (разрешено a-z 0-9 . _ -)"
        }
        require(!value.startsWith(".")) { "имя секрета не может начинаться с точки: $value" }
    }

    override fun toString(): String = value

    private companion object {
        const val MAX_LENGTH = 64
        val ALLOWED = ('a'..'z') + ('0'..'9') + listOf('.', '_', '-')
    }
}

/**
 * Известные секреты. Список короткий намеренно: хранилище платформы — не место для
 * настроек, туда идёт только то, чья утечка стоит переписки.
 */
object Secrets {

    /**
     * Секрет устройства, 32 байта. Из него выводится ключ покоя локальной базы.
     *
     * **Потеря равна потере базы**, восстановления нет: сообщения на устройстве
     * перестают читаться. Версия в имени — не украшение: смена схемы вывода ключа
     * потребует второго секрета рядом с первым, а не молчаливой замены.
     */
    val DEVICE_SECRET = SecretAlias("device-secret.v1")
}

/**
 * Хранилище недоступно или отказало. Отдельный тип: это не логическая ошибка кода.
 *
 * `open`, потому что у платформ бывают отказы, которые вызывающий обязан различать —
 * например «хранилище этому процессу недоступно вообще» против «конкретная запись не
 * читается». Первое лечится окружением, второе — переустановкой.
 */
open class SecretVaultFailure(message: String, cause: Throwable? = null) : Exception(message, cause)

/**
 * Хранилище платформы.
 *
 * @param scope имя, разделяющее хранилища разных установок приложения. На ПК это
 *   каталог, на Apple — `kSecAttrService`.
 */
expect fun platformVault(scope: String): SecretVault
