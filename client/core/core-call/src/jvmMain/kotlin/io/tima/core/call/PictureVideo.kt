package io.tima.core.call

import kotlinx.coroutines.flow.StateFlow

/**
 * Кадр как есть: BGRA, по четыре байта на точку, строки без добивки.
 *
 * BGRA выбран не случайно: в этом порядке лежат точки у Skia на Windows, и экран кладёт
 * байты в картинку без перестановки. Кадр 1280×720 — 3,7 МБ, и переставлять их тридцать
 * раз в секунду было бы заметной работой ради ничего.
 */
class VideoPicture(val width: Int, val height: Int, val bgra: ByteArray)

/**
 * Дорожка видео на ПК — **кадрами, а не поверхностью**.
 *
 * На Android картинку рисует поверхность libwebrtc (`SurfaceViewRenderer`), у ПК такой
 * нет: `livekit-ffi` отдаёт кадры байтами, и рисует их экран сам. Ручка остаётся
 * непрозрачной для общего кода ([VideoHandle]), а платформенный экран ПК знает этот
 * интерфейс — так же, как экран Android знает свою ручку.
 *
 * Поток, а не событие: экран рисует последний кадр, и пропущенный промежуточный не нужен
 * никому. `StateFlow` сам выбрасывает то, что экран не успел нарисовать.
 */
interface PictureVideo : VideoHandle {
    val pictures: StateFlow<VideoPicture?>
}
