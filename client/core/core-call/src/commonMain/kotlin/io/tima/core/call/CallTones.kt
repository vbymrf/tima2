package io.tima.core.call

/**
 * Гудки звонящего (заказчик 2026-10-08): пока дозваниваемся — гудок вызова; занято или
 * отклонили — короткие «занято» несколько секунд.
 *
 * Тоны стандартные телефонные, 425 Гц: вызов — секунда звука и четыре тишины, занято —
 * по 0,35–0,5 с. Файлов мелодий нет: на Android их играет система (`ToneGenerator`), на ПК
 * тон складывается программой.
 *
 * [ringback]`(false)` гасит только гудок вызова: «занято» начинается в ту же секунду, когда
 * звонок кончился, и выключатель гудка не должен его оборвать.
 */
expect object CallTones {
    fun ringback(on: Boolean)
    fun busy()
}

/** Сколько звучит «занято», мс — обычные для телефонов три секунды. */
const val BUSY_TONE_MS: Int = 3_000
