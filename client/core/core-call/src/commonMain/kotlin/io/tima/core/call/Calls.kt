package io.tima.core.call

/**
 * Сигналинг звонка — порт (ПЛАН-СТЕНДА-ЗВОНКОВ С1).
 *
 * **Отдельно от [CallEngine], и это главное решение модуля.** Кто кому звонит, какая
 * комната и какой токен — решает наш сервер, и решает одинаково на всех платформах. Медиа
 * же платформенное целиком. Сложи их в один интерфейс — и наш протокол придётся повторять
 * в каждом `actual`, то есть однажды повторить неодинаково.
 *
 * Ручки на сервере есть все (`server/internal/api/calls_registrar.go`), реализация —
 * `core-network`.
 */
interface Calls {

    /** Позвонить. `kind` — `audio` или `video`; сервер запомнит его в истории. */
    suspend fun start(peerId: String, video: Boolean): CallStep

    /** Ответить на входящий: сервер выдаёт токен той же комнаты. */
    suspend fun answer(callId: String): CallStep

    /**
     * Войти в комнату **заново** — свежий токен того же звонка.
     *
     * ── ЗАЧЕМ ЭТО НУЖНО И ПОЧЕМУ НЕ ГОДИТСЯ `answer` ────────────────────────
     *
     * Токен живёт две минуты (`callTokenTTL`), разговор — дольше. Перезаход в комнату
     * (смена набора публикации на ходу, ПЛАН-СТЕНДА С-В5) — это **новый вход**, и старым
     * токеном он падает с «token is expired», роняя звонок: прежняя комната к этому
     * времени уже закрыта.
     *
     * `answer` для этого не подходит: он отвечает `403 not_callee` звонящему — ответить
     * может только вызываемый. А набор меняют обе стороны.
     */
    suspend fun join(callId: String): CallStep = CallStep.Refused("no_rejoin")

    /**
     * Завершить. Итог сервер запишет сам по вебхуку от SFU; этот вызов — про наше
     * намерение, а не про факт разрыва.
     */
    /**
     * Закончить звонок.
     *
     * @param busy закончить **потому, что мы заняты другим разговором**. Это слово знает
     *   только телефон: сервер состояние «разговаривает» закрыть сам не может, и
     *   проверка по нему однажды заперла всех на пять часов (2026-09-20). Звонящий по
     *   этому слову скажет «собеседник занят» вместо «никто не ответил».
     */
    suspend fun end(callId: String, busy: Boolean = false): Boolean

    /**
     * Что со звонком **прямо сейчас** — `GET /calls/{id}` (П1).
     *
     * ── РАДИ ЧЕГО ЭТО ЗАВЕДЕНО ──────────────────────────────────────────────
     *
     * Вызов приходит подсказкой «посмотри звонок N», а не телом. Подсказка протухнуть
     * не может: телефон, пролежавший офлайн сутки, спросит — и услышит «кончился»
     * вместо того, чтобы зазвонить по мёртвому вызову.
     *
     * `null` означает **«мы не знаем»** — до сервера не дошли. Не «кончился»: спутать
     * эти два случая значит не позвонить человеку из-за моргнувшей сети.
     */
    suspend fun snapshot(callId: String): CallSnapshot? = null

    /**
     * Лента звонков после моего номера — `GET /calls/updates?after=N` (ВЗ0а).
     *
     * `null` — до сервера не дошли: номер не двигаем и не подтверждаем, следующая
     * подсказка или переподключение спросят снова.
     */
    suspend fun updates(after: Long): CallUpdates? = null

    /**
     * Пропущенные просмотрены — `POST /calls/seen`: строка в шторке снимается на всех
     * устройствах человека (решение заказчика 2026-09-26).
     */
    suspend fun seen(callIds: List<String>): Boolean = false
}

/**
 * Страница ленты звонков.
 *
 * @param gap начало ленты уже вычищено (живёт сутки): пропущенные брать из журнала
 *   звонков. Изменения ниже всё равно применяются — среди них может быть идущий звонок.
 */
data class CallUpdates(
    val top: Long,
    val gap: Boolean,
    val more: Boolean,
    val updates: List<CallUpdate>,
)

/**
 * Одно изменение звонка: номер, слово и снимок звонка **на момент чтения**.
 *
 * @param change `ringing` · `delivered` · `unreachable` · `answered` · `declined` ·
 *   `cancelled` · `busy` · `ended` · `missed` · `seen`.
 * @param here у `answered` — трубку взяли на ЭТОМ устройстве.
 */
data class CallUpdate(
    val cts: Long,
    val callId: String,
    val change: String,
    val here: Boolean,
    val call: CallSnapshot,
    /**
     * Когда изменение записал сервер, мс. По нему телефон ставит отметку «о пропущенных
     * уведомил до…» — часами сервера, а не своими: часы телефона врут на минуты.
     */
    val atMs: Long = 0,
)

/**
 * Снимок звонка: та же строка, что в журнале, только про один.
 *
 * Сырая, как и в списке: слова складывает тот, кто смотрит. Здесь смотрит не человек, а
 * `CallHost`, и ему нужно ровно три ответа — идёт ли, какой вид, кто звонит.
 */
data class CallSnapshot(
    val callId: String,
    /** `ringing` · `answered` · `ended` · `missed` · `busy` · `lost`. */
    val state: String,
    val video: Boolean,
    val initiatorId: String,
    val peerId: String,
) {
    /** Вызов ещё звонит — только на это и стоит звонить телефону. */
    val ringing: Boolean get() = state == "ringing"
}

/** Чем кончилась попытка начать или принять звонок. */
sealed interface CallStep {
    /** Дверь открыта: адрес, комната, токен. */
    data class Door(val door: CallDoor) : CallStep

    /**
     * Звонки не настроены на сервере — `503 no_livekit`.
     *
     * Отдельным случаем, а не общим отказом: это не «не получилось», это «у нас звонков
     * нет вовсе», и человеку надо сказать именно так.
     */
    data object NotConfigured : CallStep

    /** Сети нет. `retryAfterMs` — через сколько имеет смысл повторить. */
    data class Offline(val retryAfterMs: Long) : CallStep

    /** Сервер отказал: код причины как есть, без выдуманных слов. */
    data class Refused(val code: String) : CallStep
}
