package io.tima.core.call

/**
 * Сказать системе, что идёт звонок, — и показать это человеку.
 *
 * ── ЗАЧЕМ ЭТО НУЖНО, И ПОЧЕМУ ЭТО НЕ УКРАШЕНИЕ ──────────────────────────────
 *
 * **Свёрнутое приложение теряет микрофон**, если у него нет службы переднего плана. Так
 * записано у Android, и так оно и работает — на тех телефонах, где правило применяют.
 *
 * Обмерено 2026-09-20 на двух телефонах, обоих с Android 11, после сворачивания:
 *
 * | Телефон | `appops get RECORD_AUDIO` |
 * |---|---|
 * | Samsung | `allow; (running)` — сеанс жив час |
 * | realme | `allow; duration=+3s537ms` — сеанс кончился через три с половиной секунды |
 *
 * Разница не в нашем коде, а в том, что одни вендоры правило применяют, а другие нет.
 * Работающий Samsung был случайностью, и опираться на неё нельзя.
 *
 * ── ЧТО ЭТО ДАЁТ СВЕРХ МИКРОФОНА ────────────────────────────────────────────
 *
 * Уведомление в шторке — **единственный видимый след звонка снаружи приложения**. Без
 * него человек, ушедший в другое приложение, не знает, идёт ли ещё разговор, и вернуться
 * в него может только найдя TIMA среди прочих.
 */
expect fun callOngoing(title: String, text: String)

/** Убрать. Зовётся, когда звонка больше нет: висящее уведомление хуже отсутствующего. */
expect fun callOngoingOff()
