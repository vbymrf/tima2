package io.tima.core.call

/**
 * Собеседник пропал из комнаты после ответа — ещё не конец (беда 2026-11-15, «обрыв звонка при смене сети»; решение
 * заказчика 2026-11-16: «Делай все три, 20 секунд»).
 *
 * У собеседника на миг пропадает сеть, его приложение за секунду-две переподключается, и LiveKit меняет старое
 * подключение новым — в этот миг в комнате «никого, кроме меня». Раньше это сразу было концом звонка (стадия
 * `Ended`), и разговор рвал уже этот телефон. Теперь [WAIT_MS] ждём: вернулся — разговор идёт, нет — конец.
 * Положенную собеседником трубку это не задерживает: её сервер присылает лентой звонков сразу.
 */
class PeerAway {
    private var since = 0L

    /** [alone] — в комнате после ответа никого, кроме меня. Вернёт: ждём ли ещё (тогда это не конец). */
    fun waiting(alone: Boolean, nowMs: Long): Boolean {
        if (!alone) {
            since = 0L
            return false
        }
        if (since == 0L) since = nowMs
        return nowMs - since < WAIT_MS
    }

    /** Пропал ли только что — для строки журнала и для таймера пересчёта. */
    val started: Boolean get() = since != 0L

    fun reset() {
        since = 0L
    }

    companion object {
        /** Сколько ждать возврата собеседника — столько же ждёт и сервер. */
        const val WAIT_MS = 20_000L
    }
}
