package io.tima.core.call

import kotlinx.coroutines.flow.StateFlow

/**
 * Звонок — контракт (ПЛАН-ЗВОНКОВ.md, Plan.md §3.8).
 *
 * **Ни один экран не знает, чем звонок исполнен.** На Android это `livekit-android`, на ПК
 * маршрут ещё не выбран (К7.1), на iOS нет машины. Смена исполнения позже — замена одного
 * `actual`, а не правка экранов; ради этого контракт и заведён отдельным модулем.
 *
 * **Сигналинг сюда НЕ входит.** Кто кому звонит, какая комната и какой токен — решает наш
 * сервер (`POST /api/v1/calls`, ручки есть все), а движку отдаётся уже готовый [CallDoor].
 * Причина: сигналинг наш и общий для всех платформ, а медиа — платформенное. Смешать их в
 * одном интерфейсе значило бы переписывать наш протокол в каждом `actual`.
 */
interface CallEngine {

    /** Что со звонком сейчас. Экран рисует это и ничего не вычисляет сам. */
    val state: StateFlow<CallState>

    /**
     * Своя картинка — то, что видит собеседник. `null` — камера выключена.
     *
     * Отдельным потоком, а не полем [CallState]: состояние сравнивается на равенство при
     * каждой перерисовке, а дорожка — живой объект, у которого равенства нет.
     */
    val localVideo: StateFlow<VideoHandle?>

    /** Картинка собеседника. `null` — он себя не показывает или мы отписались. */
    val remoteVideo: StateFlow<VideoHandle?>

    /**
     * Принимать ли чужое видео (ЗВ11).
     *
     * **Отписка, а не занавеска.** Собеседник включает камеру, не спрашивая нас
     * (решение заказчика 2026-09-20), и за приём платит наш трафик. Спрятать картинку,
     * продолжая её качать, значило бы не оставить выхода вовсе.
     */
    suspend fun setRemoteVideo(on: Boolean) = Unit

    /**
     * Подключиться к комнате и начать говорить.
     *
     * @param door куда идти: адрес SFU, комната, токен — всё от нашего сервера.
     * @param publish чем публиковать: кодек, слои, звук. Пресет испытательного режима
     *   (ADR-0006 Поправка-2); `null` — как решит SDK.
     */
    suspend fun connect(door: CallDoor, publish: PublishPreset? = null)

    /** Положить трубку. Повторный вызов на завершённом звонке — не беда, а ничего. */
    suspend fun disconnect()

    /** Микрофон. Выключенный микрофон — не пауза: дорожка остаётся, звук не идёт. */
    suspend fun setMicrophone(on: Boolean)

    /**
     * Камера. Выключается **приглушением**, а не снятием дорожки: возврат тогда стоит
     * одного RTT, а не нового обмена SDP. Это же понадобится, когда полосы не хватит.
     */
    suspend fun setCamera(on: Boolean)

    /**
     * Числа звонка для испытательного стенда: битрейт по дорожкам, выбранный слой,
     * качество связи. `null` — движок их не отдаёт.
     *
     * Отдельно от [state] намеренно: состояние звонка нужно всем, а числа — только
     * стенду, и собирать их при выключенном флаге незачем (ПЛАН-СТЕНДА §4).
     */
    suspend fun stats(): CallStats? = null
}

/**
 * Дверь в комнату — то, что выдал наш сервер на `POST /api/v1/calls` или `/answer`.
 *
 * @param url адрес SFU (`wss://…/livekit`), его говорит сервер, а не клиент: адрес зависит
 *   от развёртывания, и зашивать его в клиент значит ломать при переезде.
 * @param token доступ в комнату, подписан ключом LiveKit на бэкенде; клиент секрета не
 *   знает и знать не должен.
 */
data class CallDoor(
    val callId: String,
    val room: String,
    val url: String,
    val token: String,
)

/**
 * Что со звонком. Порядок значений — порядок жизни, но **переходы проверяет движок**, а не
 * этот перечень: у каждой платформы свои промежуточные состояния, и описывать их здесь
 * значило бы описывать чужое устройство.
 */
enum class CallStage {
    /** Ещё не звонили или уже закончили. */
    Idle,

    /** Идёт подключение к комнате. */
    Connecting,

    /** В комнате; собеседник может ещё не войти. */
    Connected,

    /** Связь потеряна, SDK пытается вернуться. Не конец: окно возврата — 30 с. */
    Reconnecting,

    /** Закончено — сами, собеседником или потерей связи насовсем. */
    Ended,
}

/**
 * Состояние звонка целиком.
 *
 * @param trouble почему закончилось или что мешает. `null` — всё в порядке. Словами не
 *   для человека, а для журнала: экран переводит код в надпись сам.
 * @param notice что происходит **прямо сейчас** и почему. В отличие от [trouble], звонок
 *   при этом продолжается: «камеру не разрешили», «собеседник показывает себя». Заведено
 *   2026-09-20: отказ камеры был единственным исходом, которому некуда было лечь, и он
 *   уронил приложение вместо того, чтобы стать надписью.
 * @param quality оценка связи от SFU. Своей не считаем — это второй источник правды
 *   (ПЛАН-ЗВОНКОВ З8).
 * @param videoPaused видео остановлено нехваткой полосы. Возможно с 2026-09-19:
 *   `allow_pause: true` в `livekit.yaml` — и **человеку это надо показать**, иначе
 *   пропавшая картинка выглядит поломкой (З9).
 */
data class CallState(
    val stage: CallStage = CallStage.Idle,
    val callId: String = "",
    /** Кто ещё в комнате, кроме меня. */
    val others: List<String> = emptyList(),
    /**
     * Мы вошли в комнату SFU.
     *
     * **Это не «нас соединили».** В комнату входят одни и ждут там сколько угодно —
     * собеседник ещё не снял трубку. Разницу нашёл живой прогон 2026-09-20:
     * `Room.State.CONNECTED` принимали за начало разговора, и время начинало идти в
     * момент нажатия «позвонить». Человек видел таймер там, где никто ещё не ответил.
     */
    val inRoom: Boolean = false,
    /**
     * Разговор кончился тем, что **ушёл собеседник**, а не мы и не связь.
     *
     * Отдельно от [trouble] потому, что это не беда: человек положил трубку, и сказать
     * об этом надо спокойными словами. Беда — когда оборвалось само.
     */
    val peerLeft: Boolean = false,
    /**
     * Опубликован ли микрофон.
     *
     * **`false`, пока дорожка не встала на самом деле.** До 2026-09-20 здесь стояло
     * `true` «по умолчанию», и экран честно писал «Микрофон включён» при звонке, в
     * котором не публиковалось вообще ничего: `room.connect` дорожку не заводит, её
     * включают отдельно, а этого не делал никто. Звука не было ни в одну сторону, и
     * интерфейс это скрывал.
     */
    val microphoneOn: Boolean = false,
    val cameraOn: Boolean = false,
    val videoPaused: Boolean = false,
    /** Собеседник показывает себя. Событие, а не наша настройка: решает он. */
    val remoteVideoShown: Boolean = false,
    /** Принимаем ли мы его видео. Выключается кнопкой «скрыть» (ЗВ11). */
    val remoteVideoTaken: Boolean = true,
    val quality: CallQuality = CallQuality.Unknown,
    val trouble: String? = null,
    val notice: String? = null,
)

/** Оценка связи глазами SFU (`connectionquality/scorer.go`: пороги 80 / 40 / 20). */
enum class CallQuality { Unknown, Excellent, Good, Poor, Lost }

/**
 * Числа одного замера — то, ради чего заведён испытательный стенд.
 *
 * Берутся у SDK и SFU; своих счётчиков не заводим. Нагрузка на телефон (процессор, нагрев,
 * батарея) сюда НЕ входит: её знает не звонок, а платформа, и собирает её стенд отдельно.
 */
data class CallStats(
    /** Исходящий битрейт по всем дорожкам, бит/с. */
    val upBitrate: Long = 0,
    val downBitrate: Long = 0,
    /** Какой слой отдаёт SFU подписчику: 0 — нижний. `null` — не сказано. */
    val layer: Int? = null,
    val rttMs: Int? = null,
    val packetsLost: Long = 0,
    /** Чем кодируется видео на самом деле: важно, аппаратный кодер или программный. */
    val videoCodec: String? = null,
    val hardwareEncoder: Boolean? = null,
)
