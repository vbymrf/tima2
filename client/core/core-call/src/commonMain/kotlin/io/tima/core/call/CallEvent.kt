package io.tima.core.call

/**
 * Что случилось во время звонка — строка ленты событий (ЗВ10).
 *
 * ── ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ СОСТОЯНИЯ ─────────────────────────────────────────
 *
 * [CallState] отвечает на вопрос «что сейчас»: камера включена, связь хорошая, идёт
 * четвёртая минута. Событие отвечает на вопрос «что произошло»: собеседник включил
 * камеру, связь пропадала и вернулась, камеру не разрешили.
 *
 * Разница не бухгалтерская. Состояние **затирается** следующим состоянием — и человек,
 * отвернувшийся на десять секунд, не узнает, что за это время случилось. Событие
 * остаётся.
 *
 * ── ПОЧЕМУ НЕ ПОКАЗЫВАЕМ СПИСКОМ ────────────────────────────────────────────
 *
 * Решение заказчика 2026-09-20: копятся списком, показываются по одному. В строке —
 * последнее, «развернуть» открывает его целиком, «далее» и «назад» листают остальные.
 * Лента отъедала бы экран у видео, которое здесь во весь кадр, а нужна она редко: почти
 * всегда человеку хватает последней строки.
 *
 * @param seconds на какой секунде разговора. Показывается только в развёрнутом виде: в
 *   строке важнее текст, а время там заняло бы четверть ширины.
 */
data class CallEvent(
    val seconds: Int,
    val text: String,
    val action: CallAction? = null,
    /**
     * Чем событие перестаёт быть правдой.
     *
     * ── ДВА РОДА СОБЫТИЙ ────────────────────────────────────────────────────
     *
     * | | Пример | Что с ним дальше |
     * |---|---|---|
     * | **случилось** | «Собеседник перестал показывать себя» | остаётся навсегда |
     * | **длится** | «Собеседник показывает себя, ваша камера выключена» | снимается, когда кончилось |
     *
     * Второй род без снятия врёт: человек включил камеру, а строка сверху продолжает
     * говорить, что она выключена (заказчик 2026-09-20). Ключ и есть то, по чему такую
     * строку находят и убирают.
     *
     * `null` — событие первого рода, снимать его нечем и незачем.
     */
    val whileTrue: String? = null,
)

/**
 * Что можно сделать по событию — кнопка рядом с текстом.
 *
 * **Перечень, а не лямбда.** Событие живёт в состоянии и переживает пересоздание экрана;
 * лямбда, положенная в него, удержала бы вместе с собой всё, из чего её сделали. Ключ же
 * переводится в действие там, где действие есть.
 *
 * Пока одно: отказ в микрофоне чинится только в настройках телефона, и сказать об этом
 * мало — Android после второго отказа диалог больше не покажет, и другого пути у человека
 * нет вовсе.
 */
enum class CallAction {
    /** Открыть страницу приложения в настройках телефона. */
    OpenSettings,
}
