package io.tima.core.call

/**
 * Чем публикуем — пресет испытательного стенда (ПЛАН-(С)-СТЕНДА-ЗВОНКОВ.md §3.1).
 *
 * **До 2026-09-19 такого класса не могло быть.** [ADR-0006](../../../../../../../doc/adr/0006-livekit-media-policy.md)
 * Поправка-1 запрещала свои пресеты публикации: качество медиа отдано LiveKit. Поправка-2
 * приостановила запрет на время испытаний — чтобы проверить, верно ли исходное
 * утверждение, — и пресет существует **за флагом**. Выключен флаг — берётся один
 * выбранный пресет и работает как обычное поведение; никаких экранов и замеров.
 *
 * **Имя обязательно.** Сравнивать прогоны можно только тогда, когда известно, что именно
 * сравнивалось, и имя уходит в журнал вместе с числами.
 */
data class PublishPreset(
    val name: String,
    val video: VideoPreset = VideoPreset(),
    val audio: AudioPreset = AudioPreset(),
    /**
     * Кодек пресета — **закон, а не пожелание**: так в прогоне стенда (заказчик
     * 2026-09-25). Прогон «H.264» обязан мерить H.264; тихая замена на VP9 дала бы
     * числа VP9 под именем H.264. Телефон не умеет — это пишется в журнал, но кодек
     * остаётся. Вне прогона `false`: обычный звонок берёт умеемый ([CodecChoice]).
     * Прогон — звонок при нажатой «Начать прогон», а не при одном флаге режима.
     *
     * В файл и в строку пресета не пишется: это свойство звонка, а не набора.
     */
    val exact: Boolean = false,
)

/**
 * Видео.
 *
 * Набор кодеков — решения заказчика 2026-09-19: **AV1 убран совсем** (аппаратного кодера
 * нет ни на одном телефоне стенда), **VP8 возвращён 2026-09-25** (решение заказчика: мерить
 * его наравне с остальными — он кодируется на любом телефоне и единственный, кроме H.264,
 * годится в запасные),
 * **VP9 оставлен** осознанным исключением — ради SVC и аппаратного декодирования.
 *
 * @param backup запасной кодек. **Задан явно и не случайно:** SDK при VP9 молча ставит
 *   запасным VP8 с simulcast (`BackupVideoCodec(codec = "vp8", simulcast = true)`), и
 *   прогон «VP9 SVC» тогда мерит не VP9. Здесь по умолчанию H.264 — тот, что аппаратный
 *   везде. Годятся только H.264 и VP8 ([VideoCodec.backupCapable]); `null` — запасного
 *   нет на самом деле, а не «на усмотрение SDK».
 * @param scalability режим слоёв SVC. SDK по умолчанию ставит `L3T3_KEY`; названо здесь,
 *   потому что у `L3T3` числа другие, и в отчёте это должно быть видно.
 * @param dynacast SDK при SVC включает его сам — задаём явно, иначе прогоны с SVC и без
 *   окажутся в разных условиях и сравнивать их будет нельзя.
 */
data class VideoPreset(
    val codec: VideoCodec = VideoCodec.H264,
    val layers: LayerMode = LayerMode.Single,
    // ── РАЗРЕШЕНИЕ КРАТНО ШЕСТНАДЦАТИ, И ЭТО НЕ ПРИДИРКА ────────────────────
    //
    // Стояло 640×360. Высота 360 на шестнадцать не делится, и аппаратный кодер H.264 у
    // realme (`OMX.sprd.h264.encoder`, Unisoc) выдавал на ней полосатую картинку:
    // **у себя на телефоне видео выглядело целым, а у обоих собеседников — полосами**
    // (заказчик 2026-09-20).
    //
    // Собственное изображение идёт мимо кодера, прямо с камеры, — потому и было целым.
    // Это и указало на кодер: ломалось только то, что кодировалось.
    //
    // 640×480 делится на шестнадцать по обеим сторонам. Плата — на треть больше точек
    // при том же битрейте; цена за картинку, которую видно не только себе.
    val width: Int = 640,
    val height: Int = 480,
    val fps: Int = 15,
    /**
     * Верхняя граница исходящего видео, бит/с.
     *
     * ── ПОЧЕМУ ЭТО ПОЛЕ ВООБЩЕ ПОЯВИЛОСЬ ────────────────────────────────────
     *
     * Его не было, и битрейт целиком принадлежал умолчанию SDK. Вместе с
     * [Degradation.MaintainResolution] — «размер держим, остальным жертвуем» — это и дало
     * то, что заказчик увидел 2026-09-20: полосы ушли, а качество стало плохим. Цена за
     * убранные полосы легла на чёткость, и легла молча, потому что верхняя граница нам не
     * принадлежала.
     *
     * 800 кбит/с для 640×480 при 15 к/с — обычная величина для разговора: у WebRTC при
     * таком размере ориентир около 500–1000, и брать нижний край незачем.
     *
     * **Это не измерено, а выбрано.** Мерить его — работа стенда (С3, С4): там битрейт
     * одна из осей, и у каждого кодека он свой.
     */
    val bitrate: Int = 800_000,
    /** Верхний слой, бит/с. */
    val maxBitrate: Int = 800_000,
    val backup: VideoCodec? = VideoCodec.H264,
    val scalability: String = "L3T3_KEY",
    /**
     * Чем жертвовать, когда полосы не хватает: размером картинки или частотой кадров.
     *
     * ── ПОЧЕМУ УМОЛЧАНИЕ — ДЕРЖАТЬ РАЗМЕР ───────────────────────────────────
     *
     * WebRTC по умолчанию уменьшает **разрешение**, и делает это ступенями: 640×480 →
     * 480×360 → 320×240. Высота 360 на шестнадцать не делится, и аппаратный кодер realme
     * (Unisoc) выдаёт на ней полосы.
     *
     * Так и выглядело: полосило пару секунд в начале, потом ещё немного, дальше чисто —
     * то есть ровно пока кодер проходил ступени вверх и вниз (заказчик 2026-09-20).
     * Выровненное разрешение 640×480 саму ступень не отменяет, а лишь убирает ту, с
     * которой звонок начинается.
     *
     * `MaintainResolution` держит размер и роняет частоту. Ступеней по размеру не
     * остаётся вовсе — значит нет и промежуточных, на которых кодер ломается.
     *
     * **Это настройка испытаний, а не догма** (ADR-0006 Поправка-2): у стенда С3 она одна
     * из осей, и там её будут менять осознанно.
     */
    val degradation: Degradation = Degradation.MaintainResolution,
    val dynacast: Boolean = true,
    val adaptiveStream: Boolean = true,
    /**
     * Обрезка кадра до кратного 16 выключена — `true` (ПЛАН-(В)-ВИДЕО.md В2.3). На экране — галочка
     * «Обрезка до кратного 16», снятая: название без отрицания (заказчик 2026-09-30).
     *
     * ── ЧТО ПО УМОЛЧАНИЮ ────────────────────────────────────────────────────
     *
     * С 2026-09-30 кадр в **каждом** звонке перед аппаратным кодером обрезается по центру
     * до ближайшего меньшего кратного 16 размера ([CenterCrop]). WebRTC ничего не
     * заявляется: он ужимает кадр своими ступенями (270×480, 360×480, 540×960…), а кодер
     * заводится под 256×480, 352×480, 528×960, и из кадра вырезается середина. Разбор —
     * `БЕДЫ/2026-09-30-кратность-16-и-полосы.md`: без кратности кодеры производителей вне
     * гарантии (полосы realme, мусор у H.264 Honor), а заявка кратности заставляла WebRTC
     * выдавать нечётную сторону.
     *
     * ── ЗАЧЕМ ГАЛОЧКА ───────────────────────────────────────────────────────
     *
     * Воспроизвести прежнее поведение, если беда вернётся (заказчик 2026-09-30, 1а).
     * Прежние способы — «заявка на все слои» и «только один слой» — убраны: они давали
     * только нечётное. Старые наборы с их полями читаются, поля пропускаются.
     *
     * Программный кодер не обрезается и с галочкой, и без: WebRTC отдаёт ему кадры внутри
     * своей библиотеки, мимо Java (`WrappedNativeVideoEncoder.encode` — «Not implemented»),
     * и вставить обрезку перед ним нашим кодом нельзя. Что он шлёт некратное — видно строкой
     * «ушло некратное».
     */
    val noCrop: Boolean = false,
    /**
     * Кодер прогона — «как в настройках», аппаратный или программный (заказчик 2026-09-30,
     * 1а). Только на звонок прогона; после него — снова «Настройки → Звонки». Аппаратный —
     * просьба: нет у телефона кодера этого кодека в железе — WebRTC возьмёт программный, и
     * окно 0 покажет «П».
     */
    val encoder: CoderChoice = CoderChoice.Settings,
    /** Раскодировщик прогона — так же, как [encoder]. Решает принимающий телефон, за себя. */
    val decoder: CoderChoice = CoderChoice.Settings,
)

/** Выбор кодера или раскодировщика в наборе прогона (заказчик 2026-09-30, 1а). */
enum class CoderChoice(val wire: String) {
    /** Как в «Настройки → Звонки». */
    Settings("settings"),
    Hardware("hardware"),
    Software("software");

    /** Аппаратно ли — при переключателе настроек [setting]. */
    fun pick(setting: Boolean): Boolean = when (this) {
        Settings -> setting
        Hardware -> true
        Software -> false
    }

    companion object {
        fun of(wire: String?): CoderChoice = entries.firstOrNull { it.wire == wire } ?: Settings
    }
}

/**
 * Обрезка по центру до кратного 16 ([VideoPreset.noCrop] — выключить).
 *
 * [width]×[height] — размер, под который WebRTC заводит кодер. Кодер заводится под
 * [alignedWidth]×[alignedHeight], а из кадра вырезается середина: поровну слева и справа,
 * сверху и снизу. Смещения чётные — у кадра I420 цвет хранится по два пикселя.
 */
data class CenterCrop(val width: Int, val height: Int) {
    val alignedWidth: Int = down16(width)
    val alignedHeight: Int = down16(height)

    /** Обрезать нечего — размер уже кратен. */
    val none: Boolean get() = alignedWidth == width && alignedHeight == height

    /**
     * Что вырезать из кадра [frameWidth]×[frameHeight]: `x, y, ширина, высота`. Кадр обычно
     * того же размера, под который заведён кодер; другой — вырезается та же доля.
     */
    fun region(frameWidth: Int, frameHeight: Int): List<Int> {
        val w = (frameWidth.toLong() * alignedWidth / width).toInt().coerceIn(1, frameWidth)
        val h = (frameHeight.toLong() * alignedHeight / height).toInt().coerceIn(1, frameHeight)
        val x = ((frameWidth - w) / 2) and 1.inv()
        val y = ((frameHeight - h) / 2) and 1.inv()
        return listOf(x, y, w, h)
    }

    companion object {
        private const val STEP = 16

        /** Вниз до кратного 16; меньше 16 не трогается — меньше некуда. */
        private fun down16(side: Int): Int = if (side < STEP) side else side - side % STEP

        /**
         * Кратен ли кадр 16 по обеим сторонам — проверка «ушло / пришло некратное»
         * (ПЛАН-(В)-ВИДЕО.md В2.4). Сторона меньше 16 кратной считается: её не режут.
         */
        fun aligned(width: Int, height: Int): Boolean =
            (width < STEP || width % STEP == 0) && (height < STEP || height % STEP == 0)
    }
}

/** Кодеки забега. AV1 в наборе нет — решение заказчика, а не отсутствие в SDK. */
enum class VideoCodec(val wire: String) {
    H264("h264"),
    VP9("vp9"),
    H265("h265"),
    VP8("vp8"),
    ;

    /** Умеет ли кодек SVC. Из набора — только VP9; у H.264, H.265 и VP8 его в WebRTC нет. */
    val svcCapable: Boolean get() = this == VP9

    /**
     * Годится ли в запасные. **Решает SDK, а не мы:** у `livekit-android` зашит список
     * `backupCodecs = [vp8, h264]`, и по просьбе сервера он публикует вторую копию дорожки
     * только в них. VP9 или H.265 запасным серверу объявлялся бы, но не посылался никогда
     * — смотрящий, ради которого его просили, остался бы без видео.
     */
    val backupCapable: Boolean get() = this == H264 || this == VP8
}

/** Как раскладываем качество: один слой, несколько потоков или слои внутри одного. */
enum class LayerMode { Single, Simulcast, Svc }

/**
 * Чем жертвовать при нехватке полосы.
 *
 * @property MaintainResolution держать размер, ронять частоту — картинка мельче не
 *   становится, но дёргается.
 * @property MaintainFramerate держать частоту, ронять размер — плавно, но мыльно; и
 *   ступени размера ломают кодер у части телефонов.
 * @property Balanced как решит WebRTC.
 */
enum class Degradation { MaintainResolution, MaintainFramerate, Balanced }

/**
 * Звук.
 *
 * @param red избыточность Opus: вдвое больше трафика на голос, зато потери до ~20 % не
 *   слышны. **Включён по решению заказчика 2026-09-19** — на фоне видео в сотни кбит/с
 *   лишние 24 кбит/с незаметны, а разборчивость держится. Сервер сам снимет RED для тех
 *   подписчиков, кто его не умеет, — включение не ломает никого.
 * @param dtx тишина не кодируется. Для разговора — да; для звука демонстрации экрана
 *   нет, иначе музыка и речь рвутся на паузах.
 */
data class AudioPreset(
    val red: Boolean = true,
    val dtx: Boolean = true,
    val bitrate: Int = 24_000,
    val stereo: Boolean = false,
)
