package io.tima.core.call

/**
 * Спросить доступ к микрофону (и, для видеозвонка, к камере).
 *
 * ── ПОЧЕМУ ЭТО НЕ ДЕЛО ДВИЖКА ───────────────────────────────────────────────
 *
 * Разрешение спрашивает окно, а не библиотека: [LiveKitCallEngine] видит `Context`
 * приложения, и системный диалог через него не показать. Поэтому движок исходит из того,
 * что разрешение уже дано, а берёт его тот, у кого есть окно.
 *
 * ── ПОЧЕМУ ВОПРОС ЗАДАЁТСЯ ПЕРЕД ЗВОНКОМ, А НЕ ПРИ ЗАПУСКЕ ──────────────────
 *
 * Та же причина, что у контактов (`core-contacts`, Д3): диалог показывается один раз за
 * установку, и потраченный на запуск он потрачен впустую. Человек, которого спрашивают
 * про микрофон на первом экране, отказывает — и правильно делает, он ещё никому не
 * звонил. Нажавший «позвонить» уже знает, зачем спрашивают.
 *
 * ── ЧТО ЗНАЧИТ ОТКАЗ ────────────────────────────────────────────────────────
 *
 * **Без микрофона звонка нет.** Это не «звонок похуже»: комната соединится, собеседник
 * будет виден, а звука не будет ни в одну сторону — и выглядит такая беда как что угодно,
 * кроме невыданного разрешения. Поэтому `false` останавливает звонок до соединения и
 * говорит человеку словами.
 *
 * @param video нужна ли ещё и камера. Голосовому звонку она не нужна, и спрашивать про
 *   неё «заодно» нельзя: разрешение, взятое впрок, объяснить человеку нечем.
 * @param onResult `true` — можно звонить. `false` означает и «отказал», и «система больше
 *   не спрашивает», и «на этой платформе звонков нет вовсе».
 */
expect fun askCallAccess(video: Boolean, onResult: (Boolean) -> Unit)

/**
 * Открыть страницу приложения в настройках телефона.
 *
 * ── ПОЧЕМУ ЭТО ОТДЕЛЬНОЕ ДЕЙСТВИЕ, А НЕ ЧАСТЬ ОТКАЗА ────────────────────────
 *
 * Раньше мы уходили туда сами, как только система переставала спрашивать. Выглядело это
 * вылетом: приложение исчезало с экрана посреди звонка, без объяснения, и так и было
 * прочитано (2026-09-20, «вылетело приложение» — а в журнале на этом месте наш
 * собственный `APP-BACKGROUND`).
 *
 * Теперь уходит туда **человек**, нажав кнопку у события. Разница в том, кто решил.
 *
 * Не «настройки вообще»: тому, кому сказали «разрешите микрофон», нельзя открывать
 * корень настроек — он там ищет наугад.
 */
expect fun openCallSettings()
