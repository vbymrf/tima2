package io.tima.core.call

/**
 * Чем платит телефон — С5 в [ПЛАН-СТЕНДА-ЗВОНКОВ](../../../../../../../../doc_mig/ПЛАН-СТЕНДА-ЗВОНКОВ.md) §3.3.
 *
 * ── ПОЧЕМУ ЭТО СНИМАЕТ ПРИЛОЖЕНИЕ, А НЕ `adb` СНАРУЖИ ───────────────────────
 *
 * Снаружи числа берутся в те мгновения, когда до телефона дотянулись рукой, — а нужны они
 * **за прогон**: средний процессор за минуту разговора и нагрев к её концу. Команда,
 * выполненная в середине, этого не даёт, а выполненная после — не даёт вовсе: телефон
 * остывает быстрее, чем к нему успевают.
 *
 * ── ЗАЧЕМ ТУТ НАГРЕВ, ЕСЛИ ЕСТЬ ПРОЦЕНТЫ ПРОЦЕССОРА ────────────────────────
 *
 * Аппаратного кодера VP9 нет ни на одном телефоне стенда, и «дорого по процессору»
 * выглядит как горячий корпус и севшая батарея, а не как проценты в отчёте. Ровно на
 * таком же основании из забега вышел AV1 — и ровно этим числом решается, остаётся ли VP9
 * (С-В8 в плане).
 *
 * **Всё, кроме [PhoneLoad.uptimeMs], может не сняться.** Путь к датчику температуры
 * вендор волен назвать по-своему, а `/proc` у части прошивок урезан. `null` здесь — не
 * беда и не повод молчать про остальное: одно неизвестное число не отменяет четырёх
 * известных.
 */
data class PhoneLoad(
    /**
     * Сколько процессора съел **наш процесс** с прошлого замера, в процентах одного ядра.
     *
     * Процента системы здесь нет намеренно: замер про то, во что обходится звонок нам, а
     * не про то, чем ещё занят телефон. Больше ста — значит работа шла на нескольких
     * ядрах разом, и это нормальный ответ, а не ошибка.
     */
    val cpuPercent: Double? = null,
    /** Занятая нами память, МБ. */
    val memoryMb: Int? = null,
    /** Самый горячий из датчиков, °C. Вендоры зовут их по-разному, берём максимум. */
    val temperatureC: Double? = null,
    /** Заряд, %. Расход за прогон считает стенд — по разнице начала и конца. */
    val batteryPercent: Int? = null,
    /**
     * Оставшийся заряд, мкА·ч — счётчик батареи (`CHARGE_COUNTER`).
     *
     * Процент для замера слишком груб: 1 % — десятки мА·ч, и минутный звонок в него не
     * попадает. Разница счётчика за прогон даёт мА·ч, которые наборы различают
     * (заказчик 2026-09-25). Уже приведён к мкА·ч — см. [chargeToMicroAmpHours].
     */
    val chargeUah: Long? = null,
    /** Ток батареи сейчас, мА, по модулю — см. [currentToMilliAmps]. */
    val currentMa: Int? = null,
    /**
     * Подключено ли питание. **На зарядке расход не меряется:** процент и счётчик растут
     * или стоят, ток идёт в батарею. Такой прогон помечается, а не сравнивается.
     */
    val charging: Boolean? = null,
    /** Сколько прошло с начала отсчёта. Единственное, что есть всегда. */
    val uptimeMs: Long = 0,
)

/**
 * Трафик **всего приложения** — вторая колонка §3.2.
 *
 * ── ЗАЧЕМ ОН, ЕСЛИ ЧИСЛА ЕСТЬ У LIVEKIT ────────────────────────────────────
 *
 * Числа LiveKit — про медиа: столько-то байт ушло дорожкой. Числа телефона — про всё,
 * включая служебный трафик, TURN и ретрансмиссии. **Расхождение между ними само по себе
 * результат:** если телефон отдал вдвое больше, чем LiveKit насчитал по дорожкам, это и
 * есть ответ на вопрос «куда девается полоса».
 *
 * Счётчик общий на процесс, а не на звонок: сколько-то байт в нём чужие — живой канал,
 * картинки, обновление. Поэтому меряется **разница** за прогон, а не само значение, и
 * прогон ставится на тихом приложении.
 */
data class PhoneTraffic(
    val sentBytes: Long = 0,
    val receivedBytes: Long = 0,
)

/**
 * Снять числа телефона.
 *
 * **Заводится только при включённом флаге** (ПЛАН-СТЕНДА §4): снятие процессора и нагрева
 * в цикле — само по себе нагрузка, и «замер, который мешает замеряемому» — классика.
 * Поэтому сбор включается флагом, а не фильтруется на выходе.
 *
 * @return `null` там, где платформа их не отдаёт: на ПК и iOS стенда нет вовсе.
 */
expect fun phoneLoad(): PhoneLoad?

/** Трафик процесса. `null` — платформа не считает. */
expect fun phoneTraffic(): PhoneTraffic?

/**
 * Ток батареи в мА по модулю — **из того, что отдала прошивка**.
 *
 * Android велит отдавать `CURRENT_NOW` в мкА со знаком (минус — разряд), но вендоры
 * отдают и мА, и с обратным знаком. Поэтому знак отбрасывается (что это — разряд или
 * зарядка, говорит [PhoneLoad.charging]), а единица угадывается по величине: телефон в
 * звонке тянет сотни мА, то есть сотни тысяч мкА, и число меньше 20 000 может быть только
 * миллиамперами.
 *
 * `null` — прошивка не отдаёт: `Int.MIN_VALUE` или ноль.
 */
fun currentToMilliAmps(raw: Int): Int? {
    if (raw == Int.MIN_VALUE || raw == 0) return null
    val value = if (raw < 0) -raw.toLong() else raw.toLong()
    return if (value < MILLI_GUESS) value.toInt() else (value / 1000).toInt()
}

/**
 * Счётчик заряда в мкА·ч. Та же беда с единицами: часть прошивок отдаёт мА·ч. Батарея
 * телефона — тысячи мА·ч, то есть миллионы мкА·ч; число меньше 20 000 — это мА·ч.
 *
 * `null` — прошивка не отдаёт: `Int.MIN_VALUE`, ноль или отрицательное.
 */
fun chargeToMicroAmpHours(raw: Int): Long? {
    if (raw <= 0) return null
    return if (raw < MILLI_GUESS) raw.toLong() * 1000 else raw.toLong()
}

/** Граница, ниже которой число — уже милли-, а не микро-. Пояснение у [currentToMilliAmps]. */
private const val MILLI_GUESS = 20_000
