package io.tima.core.call

/**
 * Проба кодеров телефона по размерам кадра (заказчик 2026-09-30, стенд — «Проба кодеров»).
 *
 * ── ЗАЧЕМ ───────────────────────────────────────────────────────────────────
 *
 * WebRTC ужимает кадр ступенями и даёт кодеру размеры, не кратные 16: 270×480, 360×480,
 * а с заявкой кратности — даже нечётные, 352×469. Аппаратные кодеры и раскодировщики
 * гарантированно умеют только кратные 16 размеры, остальное — на совести производителя:
 * кодер H.264 realme на некратном размере давал полосы, раскодировщик VP9 Redmi — полосу
 * сверху. Какой кодер какой размер выдержит, в звонке видно только по косвенным признакам.
 *
 * Проба отвечает прямо, на одном телефоне и без звонка: для H.264, VP8, VP9 и H.265 и для
 * каждого размера из лестницы WebRTC —
 * - аппаратный кодер: объявлен ли размер, заводится ли, верна ли картинка (сжатое им
 *   разворачивает программный раскодировщик — эталон);
 * - программный кодер — то же, для сравнения;
 * - аппаратный раскодировщик: верна ли картинка, сжатая программным кодером;
 * - путь WebRTC: берёт ли WebRTC аппаратный кодер для кодека и пускает ли его на размер.
 *
 * «Верна ли картинка» — сравнением с исходной тестовой таблицей по каждой строке: полосы
 * видны числом строк и местом, а не на глаз.
 *
 * @param progress строка о ходе пробы — для экрана.
 * @return отчёт markdown или `null`, если платформа пробу не умеет (ПК, iOS).
 */
expect suspend fun probeCodecs(progress: (String) -> Unit): String?
