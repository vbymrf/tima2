package io.tima.core.notify

/**
 * Показ уведомлений — ПЛАН-УВЕДОМЛЕНИЙ.md, У5.
 *
 * ── ЧТО СЮДА ПРИХОДИТ, А ЧТО НЕТ ────────────────────────────────────────────
 *
 * Сюда приходит **готовая строка**. Правил «кому показывать» здесь нет и быть не должно:
 * они знают про блокировку, про свои устройства и про то, сошлась ли подпись, — а это
 * знание живёт в `shared`, рядом с приёмником.
 *
 * **Текста сообщения здесь не бывает никогда.** Решение заказчика 2026-09-24: показываем
 * «кто и что» — от кого и сообщение это или звонок. Зашифрованное человек увидит, открыв
 * переписку.
 *
 * Довод не в осторожности ради осторожности: содержимое уведомления уходит системе, а
 * система им делится — экран блокировки, часы, Android Auto и **любое приложение с
 * «Доступом к уведомлениям»**, которое человек когда-то разрешил и забыл. Сервер нашу
 * переписку прочитать не может; отдавать её лончеру было бы странно.
 */
interface Notifier {

    /**
     * Показать или **обновить** строку.
     *
     * Обновление по тому же [Notice.key] — не удобство, а требование У6: строка
     * сообщения живёт в двух состояниях. Сразу, по приходу конверта, она безымянная —
     * имя из открытой части конверта подписью не покрыто, и «Мама написала» подделал бы
     * кто угодно. Сошлась подпись — та же строка называет имя. Вторая строка вместо
     * обновления означала бы два уведомления об одном сообщении.
     */
    fun show(notice: Notice)

    /** Убрать строку: человек открыл переписку, звонок кончился. */
    fun hide(key: String)

    /** Убрать всё своё — при выходе из аккаунта. */
    fun hideAll()

    /** Ничего не показывает. Так собирают проверки и платформы без уведомлений. */
    companion object {
        val NONE: Notifier = object : Notifier {
            override fun show(notice: Notice) = Unit
            override fun hide(key: String) = Unit
            override fun hideAll() = Unit
        }
    }
}

/**
 * Одна строка уведомления.
 *
 * @param key чем строка опознаётся при обновлении и снятии. Для сообщения это
 *   переписка — второе сообщение из той же переписки заменяет первое, а не встаёт
 *   рядом: человеку важно, что ему написали, а не сколько раз.
 * @param kind чем звенеть и всплывать ли поверх экрана.
 * @param who как назван человек; `null` — назвать нечем. Пусто бывает законно: ник не
 *   у всех, а имя показывается только после проверки подписи (У6).
 * @param what что произошло — словами читающего, из словаря вызывающего. Не текст
 *   сообщения: его здесь не бывает.
 */
data class Notice(
    val key: String,
    val kind: NoticeKind,
    val who: String?,
    val what: String,
    /**
     * Входящий звонок — строка звонит: мелодия по кругу, во весь экран на замке, кнопки
     * «Принять» и «Отклонить» (ВЗ1–ВЗ3). `null` — обычная строка.
     */
    val call: CallAlert? = null,
    /** Звук сообщения — один раз. У звонка звучит [CallAlert.ring]. */
    val sound: SoundChoice = SoundChoice.Default,
)

/** Чем строка звенит. Важность задаётся здесь, а не у платформы: правило одно на всех. */
enum class NoticeKind {
    /**
     * Сообщение. Обычная важность: звук есть, поверх экрана не лезет.
     *
     * Всплытие поверх — право звонка, и раздавать его сообщениям значит обесценить его:
     * человек, у которого поверх экрана всплывает каждое «привет», выключит всё.
     */
    Message,

    /**
     * Звонок. Высокая важность, всплывает поверх экрана.
     *
     * Иначе вызов не отличить от сообщения, а у него сорок пять секунд: не увиденный
     * вовремя, он просто кончится.
     */
    Call,
}

/**
 * Чем показывает эта платформа.
 *
 * Тот же приём, что у `platformPhoneBook`: общий код про `Context` и про AWT не знает и
 * знать не должен. Платформа представляется один раз при запуске, а до того возвращается
 * [Notifier.NONE] — не «ошибка», а честное «показывать пока нечем».
 */
expect fun platformNotifier(): Notifier
