package io.tima.core.notify

/**
 * Звук уведомления — один на пачку, без наложений (ПЛАН-(ЖУ)-ЖУРНАЛА-УВЕДОМЛЕНИЙ.md, ЖУ3).
 *
 * ── ПОВОД ───────────────────────────────────────────────────────────────────
 *
 * 2026-09-30 на ПК четыре старых пропущенных звонка дали шестнадцать сигналов за десять
 * секунд — друг за другом. «Будет 1000 — весь день будет пиликать» (заказчик).
 *
 * ── ПРАВИЛО ─────────────────────────────────────────────────────────────────
 *
 * - **Перерыв 5 с считается от конца сигнала**, а не от начала: длинный сигнал не
 *   накроется следующим (заказчик 2026-09-30).
 * - **Событие во время сигнала или перерыва пропускается, а не ждёт** — очередь звуков и
 *   есть «пиликает весь день».
 * - **Уведомитель не достоверный**: когда сигнал кончился, приложение знает не всегда.
 *   Длина неизвестна — берётся [longestMs], перерыв делается самым длинным: ошибка обязана
 *   давать тишину, а не наложение.
 *
 * Звонок, который звонит сейчас, под правило не попадает — его сюда не спрашивают.
 *
 * Не потокобезопасен сам по себе: зовущий держит его под своим замком.
 */
class SoundGate(
    private val pauseMs: Long = PAUSE_MS,
    private val longestMs: Long = LONGEST_MS,
) {
    /** До какого времени молчать: конец последнего сигнала плюс перерыв. */
    private var quietUntil = Long.MIN_VALUE

    /** Сколько событий промолчало с последнего сигнала — для строки журнала. */
    var skipped: Int = 0
        private set

    /**
     * Можно ли звучать сейчас.
     *
     * @param lengthMs длина сигнала, если известна; `null` — берётся самая длинная.
     * @return `true` — звучать; перерыв отсчитан от конца этого сигнала.
     */
    fun ask(nowMs: Long, lengthMs: Long?): Boolean {
        if (nowMs < quietUntil) {
            skipped++
            return false
        }
        skipped = 0
        quietUntil = nowMs + (lengthMs?.coerceAtLeast(0) ?: longestMs) + pauseMs
        return true
    }

    /**
     * Сигнал прозвучал — перерыв от его **настоящего** конца. [ask] отмерил перерыв по
     * длине, известной заранее; платформа узнаёт настоящую, когда уже играет.
     *
     * @param lengthMs `null` — длина так и осталась неизвестной: берётся самая длинная.
     */
    fun played(startMs: Long, lengthMs: Long?) {
        quietUntil = startMs + (lengthMs?.coerceAtLeast(0) ?: longestMs) + pauseMs
    }

    companion object {
        /** Перерыв между сигналами — решение заказчика 2026-09-30. */
        const val PAUSE_MS = 5_000L

        /** Сигнал неизвестной длины считается таким. */
        const val LONGEST_MS = 10_000L
    }
}
