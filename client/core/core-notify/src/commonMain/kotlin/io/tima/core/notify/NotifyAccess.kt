package io.tima.core.notify

/**
 * Что произойдёт, если сейчас попросить право показывать уведомления — У1.
 *
 * Тот же приём, что у доступа к книге контактов (`ContactsAccessWay`), и по той же
 * причине: **кнопка обязана называть себя**. Нажатие ведёт либо в системный диалог, либо
 * из приложения в настройки, и человек должен знать это до нажатия, а не после.
 */
enum class NotifyAccessWay {
    /** Право уже есть либо спрашивать не у кого (ПК): кнопки нет. */
    Given,

    /** Система ещё спросит: нажатие поднимет диалог. Надпись — «Разрешить». */
    Ask,

    /**
     * Система больше не спросит; остаётся страница приложения в настройках.
     *
     * Надпись другая, потому что действие другое: человек уйдёт из приложения.
     */
    Settings,
}

/** Каким будет следующий шаг — см. [NotifyAccessWay]. */
expect fun notifyAccessWay(): NotifyAccessWay

/**
 * Спросить право показывать уведомления.
 *
 * @param onResult дано ли. На платформах, где спрашивать нечего, зовётся сразу с `true`:
 *   отсутствие вопроса — это не отказ.
 */
expect fun askNotifyAccess(onResult: (Boolean) -> Unit)

/**
 * Усыпляет ли система приложение — У14.
 *
 * `true` — нас уже не усыпляют либо усыплять некому (ПК). Спрашивать тогда не о чем, и
 * строки на экране не будет вовсе.
 */
expect fun awakeAllowed(): Boolean

/**
 * Попросить не усыплять.
 *
 * Открывает системный диалог. **Этого мало на оболочках realme и Xiaomi**: у них свои
 * списки автозапуска, и документированного способа открыть их нет. Экран говорит об этом
 * словами — обещать «нажали и работает» было бы враньём.
 */
expect fun askAwake()
