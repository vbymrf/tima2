package io.tima.core.diag

import kotlinx.datetime.Instant

/**
 * Где платформа держит журнал между запусками (ПЛАН-ОТЛАДКИ.md, «Где живёт журнал»).
 *
 * Две лямбды, как у хранилища оформления, и по той же причине: хранить надо одну строку, а
 * платформенного здесь ровно столько же — место, где эта строка лежит.
 *
 * **Зачем вообще диск.** Журнал в памяти теряется при каждом убийстве процесса, а система
 * убивает фоновые приложения постоянно. Жалоба «вчера не приходили сообщения» приходила бы
 * с журналом, начинающимся сегодня, — то есть пустым по существу. Фонового процесса у нас
 * пока нет, но он неизбежен: в v1 он был.
 */
class DiaryStore(
    val load: () -> String?,
    val save: (String) -> Unit,
) {
    companion object {
        /**
         * Хранилище, которое не хранит.
         *
         * Для проверок и для платформы, у которой места ещё нет. Названо честно: журнал
         * при таком хранилище живёт до перезапуска — ровно как жил до этой правки.
         */
        val Forgetful: DiaryStore = DiaryStore(load = { null }, save = {})
    }
}

/**
 * Строки прошлых запусков, отобранные по сроку.
 *
 * **Разбирается только время** — первое поле строки. Остальное остаётся текстом: журнал
 * пишется, чтобы его читал человек, и превращать его в структуру ради фильтрации значило
 * бы завести второй формат и следить, чтобы они не разошлись.
 *
 * Строка без разбираемого времени выбрасывается: она либо от повреждённого файла, либо
 * от версии с другим форматом, и в обоих случаях доверять ей нечего.
 */
internal fun carriedLines(raw: String, since: Long, limit: Int): List<String> {
    val kept = ArrayList<String>()
    for (line in raw.lineSequence()) {
        if (line.isBlank()) continue
        val stamp = line.substringBefore(' ', "")
        val at = runCatching { Instant.parse(stamp).toEpochMilliseconds() }.getOrNull() ?: continue
        if (at >= since) kept.add(line)
    }
    // Хвост, а не начало: свежее важнее. Предел нужен на случай, когда файл пережил
    // несколько разговорчивых суток и уложился в срок целиком.
    return if (kept.size <= limit) kept else kept.subList(kept.size - limit, kept.size)
}
