package io.tima.core.diag

/**
 * Замок журнала: в журнал пишут из любых потоков сразу — главного, сетевого, звонка.
 *
 * До 2026-09-27 на его месте стояла заглушка, которая ничего не запирала: общий код не
 * умеет `synchronized`, и замок отложили. Redmi упал посреди звонка —
 * `ConcurrentModificationException` в `Diary.flush`: главный поток собирал очередь
 * записей в строку, а поток звонка в тот же миг дописывал в неё свою. Журнал, ради
 * которого разбираются падения, сам стал падением.
 *
 * Повторный вход разрешён: `note` из-под замка не зовётся, но замок, на котором поток
 * может повиснуть сам на себе, — не то, что стоит оставлять следующему.
 */
internal expect class NotesLock() {
    fun <T> hold(block: () -> T): T
}
