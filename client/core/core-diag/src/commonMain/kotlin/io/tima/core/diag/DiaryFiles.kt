package io.tima.core.diag

import kotlinx.datetime.Instant

/**
 * Где платформа держит журнал — **по файлу на день** (решение заказчика 2026-09-06).
 *
 * **Почему день, а не один файл.** До этого журнал был одной строкой: читался целиком при
 * запуске, держался в памяти и переписывался целиком при каждом сбросе. На трёх сутках и
 * 400 КБ это незаметно. На месяце — 15–20 МБ, читаемых в память на каждом запуске и
 * переписываемых каждые полсотни записей; то есть настройка «месяц» в прежней схеме
 * сделала бы приложение медленнее на ровном месте.
 *
 * День решает это разом: в памяти только несброшенное, запись — дописывание в конец,
 * уборка — удаление файла целиком (атомарно, без разбора строк), а порча одного дня не
 * уносит остальные.
 *
 * **День — это день сброса, а не день записи** (решение заказчика). Записи, сделанные до
 * полуночи и сброшенные после, лягут в новый файл, и это осознанно: раскладывать записи
 * по дням значило бы усложнять запись ради порядка, которого никто не читает. Время стоит
 * в каждой строке, а отчёт всё равно фильтрует по времени, а не по имени файла.
 *
 * Имя дня — `2026-09-06`, **по UTC**: метки времени в журнале в UTC, и расхождение имени
 * файла с его содержимым при разборе дороже, чем сдвиг границы на часовой пояс.
 */
class DiaryFiles(
    /** Дни, за которые есть файлы. Порядок неважен — [Diary] сортирует сам. */
    val days: () -> List<String>,
    /** Дописать в конец файла дня, создав его при надобности. */
    val append: (day: String, text: String) -> Unit,
    /** Прочитать день целиком. `null` — такого дня нет. */
    val read: (day: String) -> String?,
    /** Удалить день. */
    val remove: (day: String) -> Unit,
    /** Сколько занимает день в байтах — для предела объёма. */
    val size: (day: String) -> Long,
) {
    companion object {
        /**
         * Хранилище, которое не хранит.
         *
         * Для проверок и для платформы, у которой места ещё нет. Названо честно: журнал
         * при нём живёт до перезапуска.
         */
        val Forgetful: DiaryFiles = DiaryFiles(
            days = { emptyList() },
            append = { _, _ -> },
            read = { null },
            remove = {},
            size = { 0 },
        )
    }
}

/**
 * Сколько журнала держим (решение заказчика 2026-09-06).
 *
 * **Два предела, и срабатывает тот, что раньше.** Срок защищает от давности; объём — от
 * одного разговорчивого дня, который сам по себе съест сотню мегабайт. Без второго предела
 * месяц на сбойном устройстве растёт непредсказуемо.
 *
 * @param days сколько дней держим. По умолчанию месяц; месяц здесь — ровно 30 дней, а не
 *   календарный: мусорщик считает днями, и «через месяц» обязано значить одно и то же в
 *   феврале и в марте.
 * @param bytes предел объёма всех дней вместе. Лишнее удаляется с самого старого дня.
 */
data class DiaryPolicy(
    val days: Int = MONTH,
    val bytes: Long = BYTES_DEFAULT,
) {
    companion object {
        const val WEEK: Int = 7
        const val MONTH: Int = 30

        /** Значения объёма из настроек: 20, 50, 100 МБ (решение заказчика). */
        const val MB: Long = 1024L * 1024
        const val BYTES_DEFAULT: Long = 20 * MB

        /** Запись настройки строкой: `дни объём`. Хранится там же, где оформление. */
        fun read(raw: String?): DiaryPolicy {
            val parts = raw?.trim()?.split(' ') ?: return DiaryPolicy()
            val days = parts.getOrNull(0)?.toIntOrNull()?.takeIf { it > 0 } ?: MONTH
            val bytes = parts.getOrNull(1)?.toLongOrNull()?.takeIf { it > 0 } ?: BYTES_DEFAULT
            return DiaryPolicy(days = days, bytes = bytes)
        }
    }

    fun write(): String = "$days $bytes"
}

/**
 * Похоже ли имя на день — `2026-09-06`.
 *
 * Проверяется форма, а не существование даты: `2026-99-99` тоже уйдёт в уборку по сроку,
 * и разбирать его календарём незачем. Задача проверки — отличить наш файл от чужого.
 */
internal fun looksLikeDay(name: String): Boolean =
    name.length == 10 &&
        name[4] == '-' && name[7] == '-' &&
        name.filterIndexed { index, _ -> index != 4 && index != 7 }.all { it.isDigit() }

/**
 * Следующий день после `2026-09-06`.
 *
 * Считается через `Instant`, а не сложением чисел в строке: конец месяца и високосный год
 * иначе пришлось бы держать в голове.
 */
internal fun nextDay(day: String): String =
    dayOf(Instant.parse(day + "T00:00:00Z").toEpochMilliseconds() + 24L * 60 * 60 * 1000)

/** Имя дня по времени: `2026-09-06`, UTC. */
internal fun dayOf(millis: Long): String =
    Instant.fromEpochMilliseconds(millis).toString().take(10)

/**
 * Строки, отобранные по сроку.
 *
 * **Разбирается только время** — первое поле строки. Остальное остаётся текстом: журнал
 * пишется, чтобы его читал человек, и превращать его в структуру ради фильтрации значило
 * бы завести второй формат и следить, чтобы они не разошлись.
 *
 * Строка без разбираемого времени выбрасывается: она либо от повреждённого файла, либо от
 * версии с другим форматом, и в обоих случаях доверять ей нечего.
 */
internal fun linesSince(raw: String, since: Long, limit: Int): List<String> {
    val kept = ArrayList<String>()
    for (line in raw.lineSequence()) {
        if (line.isBlank()) continue
        val stamp = line.substringBefore(' ', "")
        val at = runCatching { Instant.parse(stamp).toEpochMilliseconds() }.getOrNull() ?: continue
        if (at >= since) kept.add(line)
    }
    // Хвост, а не начало: свежее важнее. Предел нужен на случай, когда день оказался
    // разговорчивым и уложился в срок целиком.
    return if (kept.size <= limit) kept else kept.subList(kept.size - limit, kept.size)
}
