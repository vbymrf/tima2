     */
    const val VOICE = "VOICE"

    /**
     * Окно проигрывания видео и звука по ссылке (ПЛАН-(ВМ) ВМ5–ВМ7): открыто, пошло, движок не смог
     * (причина), сторож — ни кадра, ни звука за 15 с, ушли в браузер. В хвосте — сайт (домен), без
