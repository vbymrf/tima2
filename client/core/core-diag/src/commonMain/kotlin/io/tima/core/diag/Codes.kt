package io.tima.core.diag

/**
 * Коды журнала — ПЛАН-(Б)-ОТЛАДКИ.md, «Коды и формат строки»; реестр с описанием каждого —
 * `doc_mig/ЖУРНАЛ-И-ОТЛАДКА/РЕЕСТР.md`.
 *
 * **Зачем код, если рядом есть текст.** Текст пишется для человека и меняется при первой
 * же правке формулировки; по нему нельзя ни посчитать, у скольких людей эта поломка, ни
 * выбрать в базе все отчёты с ней. Код — машинная часть строки: он не меняется, ищется
 * поиском и годится в запрос к таблице отчётов.
 *
 * **Латиницей — решение заказчика 2026-09-06.** Это имя в коде, а не текст для человека:
 * оно попадает в константы Kotlin и Go, ищется `grep` и не ломается кодировкой консоли
 * Windows. Русское описание стоит в той же строке рядом.
 *
 * **Первая часть кода — область.** Отдельного `[сеть]` в строке поэтому нет: область и
 * так видна, а дублировать её значит удлинять каждую строку без пользы.
 *
 * **Общее и частное.** `NET-401` — общее: под него попадают просроченный токен, отозванное
 * устройство, чужой ключ. `AUTH-EXPIRED` — частное: это уже причина. Правило простое:
 * **общий код пишется всегда, частный — когда причина установлена**. `NET-401`, за
 * которым не идёт частная строка, сам по себе сигнал — мы чего-то не предусмотрели.
 */
object LogCode {

    // ── Запуск и сеанс ────────────────────────────────────────────────────────
    /** Приложение запущено: версия, платформа, аккаунт. */
    const val APP_START = "APP-START"

    /** Ушли в фон. Дальше в журнале будет тишина — и это надо отличать от зависания. */
    const val APP_BACKGROUND = "APP-BACKGROUND"

    /** Вернулись из фона. */
    const val APP_FOREGROUND = "APP-FOREGROUND"

    /**
     * Главное окно приложения создано / закрыто — с номером экземпляра и сколько их
     * открыто сейчас (Redmi 2026-09-27, отчёт 5KXE). Два открытых сразу — беда: каждое
     * ведёт свой звонок. В отчёте это было видно только по удвоенным строкам, а причина
     * нашлась лишь в системном журнале телефона.
     */
    const val APP_WINDOW = "APP-WINDOW"

    // ── Вход и токен ──────────────────────────────────────────────────────────
    /** Токен жив, до конца ещё есть время. */
    const val AUTH_OK = "AUTH-OK"

    /** Токен истёк. Частная причина `NET-401`. */
    const val AUTH_EXPIRED = "AUTH-EXPIRED"

    /** Токен скоро истечёт — обновляем заранее. */
    const val AUTH_SOON = "AUTH-SOON"

    /** Токена нет вовсе: устройство не вошло. */
    const val AUTH_NONE = "AUTH-NONE"

    /** Срок токена прочитать не удалось — обновляем на всякий случай. */
    const val AUTH_UNKNOWN = "AUTH-UNKNOWN"

    /** Новый токен получен. */
    const val AUTH_RENEWED = "AUTH-RENEWED"

    /** Обновить не вышло: сервер отказал или не ответил. */
    const val AUTH_RENEW_FAILED = "AUTH-RENEW-FAILED"

    /** Устройство отозвано — обновлять нечего, нужен новый вход. */
    const val AUTH_REVOKED = "AUTH-REVOKED"

    /** Подписать нечем: ключа устройства нет. */
    const val AUTH_NO_KEY = "AUTH-NO-KEY"

    /** Обновление после отказа выжидает паузу — не повторяется шквалом (А1, 2026-09-30). */
    const val AUTH_RENEW_WAIT = "AUTH-RENEW-WAIT"

    /** Часы устройства расходятся с сервером больше чем на минуту (А2, 2026-09-30). */
    const val CLOCK_SKEW = "CLOCK-SKEW"

    /** Выход из аккаунта на этом устройстве: аккаунт отложен (А4, 2026-09-30). */
    const val ACCOUNT_OUT = "ACCOUNT-OUT"

    /** Возврат отложенного аккаунта (А6, 2026-09-30). */
    const val ACCOUNT_BACK = "ACCOUNT-BACK"

    // ── Сеть ──────────────────────────────────────────────────────────────────
    /** Обычный вызов: путь, код, время. */
    const val NET_CALL = "NET-CALL"

    /** Сервер отказал по авторизации. Общий код: причину называет частный. */
    const val NET_401 = "NET-401"

    /** Сервер ответил ошибкой (не 401). */
    const val NET_ERROR = "NET-ERROR"

    /** До сервера не дошли вовсе. */
    const val NET_OFFLINE = "NET-OFFLINE"

    /**
     * Живой канал упал и поднимается заново.
     *
     * ── ЗАЧЕМ ОТДЕЛЬНЫЙ КОД ─────────────────────────────────────────────────
     *
     * До 2026-09-23 падение канала не писалось никуда: исход держался в поле
     * `Receiver.lastOutcome` и читался только отладчиком в руках. Цена выяснилась на
     * realme: телефон **двое суток не получал ни одного события**, и в журнале не было
     * ни строки об этом — ни падения, ни попытки. Выглядело как «сеть шалит», а было
     * полуоткрытое соединение, которого никто не закрывал.
     *
     * Строка обязана появляться на КАЖДОМ падении: канал, который молча не поднимается,
     * иначе неотличим от канала, по которому просто ничего не шлют.
     */
    const val NET_CHANNEL = "NET-CHANNEL"

    /**
     * В полосе доставки пропущено больше одного события — догоняем.
     *
     * ── ПОЧЕМУ ЭТО НЕ «ПРОСТО ПОТЕРЯ» ───────────────────────────────────────
     *
     * Пропущенное тут же и заберут: подсказка сработала, `sync.pull` ушёл. Ценность
     * строки в том, что разрыв **назван полосой**:
     *
     *   - `переписка` — потерянное сообщение, придёт следом;
     *   - `ключи` — **жди нечитаемых сообщений**: пропущенная ротация означает не
     *     «опоздало», а «не откроется никогда», и если следом посыплются `NO-KEY`,
     *     причина названа здесь;
     *   - `фон` — досада, не беда.
     *
     * Разбор отчёта о проблеме начинается с ответа, а не с вопроса «что потерялось».
     *
     * **Ненулевое число само по себе не беда**: шина у нас «не более одного раза», и
     * редкие пропажи — её устройство. Бедой это становится, когда строк много подряд.
     */
    const val SYNC_LANE_GAP = "SYNC-LANE-GAP"

    // ── Экраны ────────────────────────────────────────────────────────────────
    const val SCREEN_OPEN = "SCREEN-OPEN"
    const val WINDOW_OPEN = "WINDOW-OPEN"

    // ── Очередь исходящих ─────────────────────────────────────────────────────
    /** Проход очереди: сколько было, сколько осталось. */
    const val QUEUE_PASS = "QUEUE-PASS"

    /** Повтор не помог: столько же, сколько было. В хвосте — почему. */
    const val QUEUE_STUCK = "QUEUE-STUCK"

    /**
     * Очередь восстановлена после обрыва: записи вернулись из `SENDING`/`SEALED`.
     *
     * **Ненулевое значит, что прошлый запуск оборвали** — телефон убил приложение посреди
     * отправки. Это норма на Android и потому не беда; бедой это становится, когда
     * восстановления не происходит вовсе.
     */
    const val QUEUE_RECOVERED = "QUEUE-RECOVERED"

    /**
     * Сервер отказал сообщению навсегда — код причины в хвосте. До 2026-09-19 в журнале
     * оставался только `NET-ERROR 400`, и «nafig» с крестиком на Redmi разбирали по базе
     * телефона и таблице сервера вместо одной строки.
     */
    const val QUEUE_REFUSED = "QUEUE-REFUSED"

    /**
     * Человек повторил или убрал отказанное — в хвосте прежняя причина и новый круг. Пара к
     * `QUEUE-REFUSED`: по ней видно, помог ли повтор, и если второй отказ пришёл с той же
     * причиной при другом круге — это уже наш баг, а не ошибка человека.
     */
    const val QUEUE_RETRY = "QUEUE-RETRY"

    /**
     * Переписке дописан собеседник.
     *
     * Заведён 2026-09-19 по настоящей беде: вход в переписку из «Контактов» НЕ заводил
     * строку `chats`, и переписка оставалась без собеседника. Следствий было три сразу, и
     * ни одно не говорило о причине: в списке она звалась «Без имени», личная страница из
     * её шапки не открывалась, а **отправка молча не происходила** — `Sender.prepare`
     * отказывался, не зная, кому адресовать. Код ставится и при починке старых переписок,
     * и в нём видно, откуда взялся собеседник.
     */
    const val CHAT_PEER = "CHAT-PEER"

    /**
     * Звонок: начат, входящий, закончен, не начался.
     *
     * Заведён 2026-09-19 вместе с окном 0. Один код на все случаи звонка намеренно: их
     * немного, а разбирают их всегда вместе — «позвонил, не дозвонился, перезвонил»
     * читается одной лентой, а не тремя.
     */
    const val CALL = "CALL"

    /**
     * «Доставлено», «прочитано», «печатает», «в сети» — лента состояний личных переписок
     * (ПЛАН-(ОП)-ОТМЕТОК-И-ПРИСУТСТВИЯ, заведён 2026-10-08): изменившиеся отметки и отметка
     * «прочитано», которая не дошла.
     */
    const val STATES = "STATES"

    /**
     * Микрофон, колонки и камера ПК: открылись ли, сколько их и **как называются**.
     *
     * Заведён 2026-09-26 со звонками на ПК (ПЛАН-(ПК)-ЗВОНКОВ-ПК). На телефоне устройство
     * одно, и беда там — разрешение; на ПК их бывает по три, и «меня не слышно» чаще
     * всего значит «не тот микрофон». Без названий в журнале это не отличить от поломки.
     */
    const val CALL_DEVICE = "CALL-DEVICE"

    /**
     * Дорожки собеседника: опубликовал, снял, подписались, отписались, выключил, включил,
     * подписка не удалась.
     *
     * Заведён 2026-10-15 по отчёту 379C: видео собеседника пропало и не вернулось, а в журнале
     * телефона были только «приходящее видео кбит/с=0» и «не приходит» — пришла ли дорожка, ушла
     * или перевыпущена, не видно, и причину пришлось искать в журнале сервера звонков.
     */
    const val CALL_TRACK = "CALL-TRACK"

    /**
     * Сервер звонков приостановил видео собеседника нехваткой полосы — и вернул (с длительностью
     * паузы). При `allow_pause: true` (решение 2026-09-19) SFU гасит видео сам, без нашего участия;
     * отчёт 379C: пауза 2 мин до конца звонка, у собеседника — 8 мин, а телефон её не видел.
     */
    const val CALL_PAUSE = "CALL-PAUSE"

    /**
     * Подстройка видео под полосу — ПЛАН-(ПЗ)-ПОЛОСЫ-ЗВОНКА.md (2026-10-15): цепочка adaptiveStream →
     * dynacast с обоих концов (вид собеседника скрыт или показан, кодер остановлен сервером или
     * снова нужен), оценка приёма, что получатель сказал собеседнику о своём приёме и какой
     * битрейт поставил отправитель (звонок на двоих), своё видео выключено слабой связью и
     * повторная подача (групповой).
     */
    const val CALL_ADAPT = "CALL-ADAPT"

    // ── Работа по кругу ───────────────────────────────────────────────────────
    /**
     * Одна и та же запись повторяется неправдоподобно часто.
     *
     * **Ловит не событие, а частоту** — и в этом всё дело. Обратная связь, где следствие
     * снова вызывает причину, не имеет своего сообщения об ошибке: каждый её шаг
     * завершается успешно. Ни один код «отказа» на неё не срабатывает, и по журналу,
     * устроенному вокруг ошибок, её не видно вовсе.
     *
     * Заведён 2026-09-17 по настоящему случаю: приложение уходило в круг «запись в базу →
     * запрос будит слушателя → снова запись» и переставало отвечать. Разбор —
     * `doc_mig/БЕДЫ/2026-09-17-зависание-на-переписке.md`. Тогда журнал не сказал об этом
     * ни строкой.
     *
     * В хвосте: какой код повторялся, сколько раз и за сколько миллисекунд.
     */
    const val LOOP_SUSPECT = "LOOP-SUSPECT"

    // ── Копия книги между устройствами (ПЛАН-(РЗ)-РАЗДЕЛОВ Р2а) ─────────────────────
    /**
     * Ход копии книги: забрали, отдали, отказ, без сети, без ключа. В хвосте — ревизия и
     * устройство. По этим строкам видно, доехала ли книга до второго телефона.
     */
    const val BOOK_COPY = "BOOK-COPY"

    /** Сверка списка групп с сервером при запуске: сколько групп, либо отказ. */
    const val GROUPS_SYNC = "GROUPS-SYNC"

    /**
     * Доверие к устройствам собеседника (ПЛАН-(ДУ+ИУ)-УСТРОЙСТВ-И-ИСТОРИИ ДУ3): устройство не заверено
     * цепочкой «личность → ключ подписи устройств → устройство», либо ключ личности не тот,
     * что при первой встрече. Пишется один раз на устройство за запуск.
     */
    const val DEVICE_TRUST = "DEVICE-TRUST"

    /**
     * Входящее сообщение не открылось — и **почему**: нет ключа сообщения, нет ключа подписи
     * отправителя, нет ключа версии группы (`note`) или подпись не сошлась (`trouble` — это
     * возможная подмена). Пишется раз на сообщение и причину за запуск.
     *
     * Заведён 2026-10-06 (заказчик: «делай запись причины»): «Сообщение недоступно» на ПК
     * заказчика разобрать было нечем — причина лежала только в базе устройства
     * (`undecryptable_reason`), а в журнал и в отчёт о проблеме не попадала.
     */
    const val MSG_UNREADABLE = "MSG-UNREADABLE"

    /**
     * Картинка по номеру файла не показалась (загрузчик Sketch, ПЛАН-(ЗК); ПЛАН-(ЖС) §1):
     * `причина=нет-байтов` — файла нет ни в своей папке, ни на сервере, либо сеть не ответила;
     * `причина=расшифровка` — ключ не подошёл; `причина=раскодирование` — битый файл или формат не
     * по силам. Одна строка на номер файла за запуск: прокрутка списка с одним и тем же пропавшим
     * аватаром иначе утопила бы журнал. Удачная загрузка не пишется.
     *
     * Заведён 2026-10-18 вместе с загрузчиком: «аватар не грузится» без строки не отличить сети от
     * отсутствия файла.
     */
    const val MEDIA_LOAD = "MEDIA-LOAD"

    // ── Редактор, подборка, файлы почтальона (ПЛАН-(ЖС) §2–§6) ──────────────────
    //
    // Заведены 2026-10-18 вместе с редактором и почтальоном на клиенте. Текст сообщений не пишется
    // никогда — только что сделано, числа и номера.

    /** Редактор: открыт, закрыт с черновиком, отправлено (сколько рядов, ячеек, виджетов по видам), корзина и «Вернуть». */
    const val EDITOR = "EDITOR"

    /** Редактор не отправил: правила разметки, «99 не помещается», файлы на странице. */
    const val EDITOR_REFUSED = "EDITOR-REFUSED"

    /** Черновик не сохранился или не открылся (шифрование на устройстве, Решения §9). */
    const val DRAFT = "DRAFT"

    /**
     * Лишние нажатия отброшены (заказчик 2026-10-24): «Готово», «Вставить», «Отправить» нажаты ещё раз до
     * того, как окно ушло с экрана, — какая кнопка (метка), сколько лишних, за сколько мс. Одна строка на серию.
     */
    const val TAP_REPEAT = "TAP-REPEAT"

    /** Правка (ADR-0045): своя не принята сервером — причина `edit_*`. */
    const val MSG_EDIT = "MSG-EDIT"

    /** Подборка сообщений: добавлено, вставлено, полна — уровень и сколько в ней. */
    const val PICKS = "PICKS"

    /** Переход внутри переписки: к ответу, вставленному, подкладке; «назад», «вперёд»; длина цепочки. */
    const val JUMP = "JUMP"

    /** Файл и фото уходят: загрузка начата, кончилась или оборвалась — вид, размер, мс. */
    const val FILE_SEND = "FILE-SEND"

    /** Файл почтальона: забран, нет у почтальона — попросили снова, загружен снова по просьбе, «получатель забрал». */
    const val FILE_GET = "FILE-GET"

    /** Своя папка медиа: уборка по пределам, «Очистить сейчас», «Сохранить как» и его исход. */
    const val FILE_STORE = "FILE-STORE"

    /** Файл по ссылке «Облака»: ответил ли сервер файла и что в начале файла (2026-10-24). */
    const val CLOUD_FILE = "CLOUD-FILE"

    /**
     * Голосовое (ПЛАН-(ВМ) ВМ2–ВМ4): запись начата (частота), остановлена, удалена, микрофон
