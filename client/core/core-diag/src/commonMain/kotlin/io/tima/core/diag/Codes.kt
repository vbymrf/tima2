     */
    const val MSG_MARKUP = "MSG-MARKUP"

    /** Быстрое оформление: разбор строки дольше 50 мс — длина, мс (ПЛАН-(ЖС) §2). */
    const val MD_PARSE = "MD-PARSE"

    /** Разбор сообщения для показа дольше кадра (16 мс) — блоков, мс (ПЛАН-(ЖС) §4). */
    const val RENDER_SLOW = "RENDER-SLOW"

