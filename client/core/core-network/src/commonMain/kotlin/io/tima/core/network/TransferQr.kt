package io.tima.core.network

/**
 * Код передачи в виде ссылки: `tima://transfer/v1?code=…`
 *
 * **Формат наш, а не серверный** — в отличие от [LinkQr], который составляет сервер.
 * Сервер отдаёт голый код; во что его завернуть, чтобы показать камере, — дело клиента.
 * Поэтому здесь и разбор, и сборка: обе стороны наши.
 *
 * **Роли обратные привязке.** Там код показывает новое устройство, а подтверждает
 * старое; здесь код показывает **передающий**, а считывает **принимающий**. Причина в
 * том, что передающему не нужно знать, кому он передаёт — ни ника, ни номера: для
 * анонимного аккаунта это главное свойство передачи.
 *
 * **Фразы в коде нет и быть не может.** Код фотографируют, он остаётся в галерее и в той
 * переписке, куда его переслали; фраза, попавшая в картинку, живёт дольше передачи. Без
 * фразы же код не передаёт ничего — на этом и держится то, что его не страшно показать.
 */
object TransferQr {

    private const val PREFIX = "tima://transfer/v1?code="

    fun payload(code: String): String = PREFIX + code

    /**
     * Принимает и ссылку, и голый код.
     *
     * Голый — потому что код читают не только камерой: его диктуют, пересылают текстом и
     * переписывают с бумаги. Требовать вокруг него ссылку значило бы отказывать человеку,
     * который принёс ровно то, что ему дали.
     *
     * @return `null` — не наш код и не похоже на код вовсе.
     */
    fun parse(payload: String): String? {
        val line = payload.trim()
        val code = if (line.startsWith(PREFIX)) line.removePrefix(PREFIX) else line
        val clean = code.substringBefore('&').trim()
        // Длина и алфавит проверяются здесь, и это не придирка. Дальше код уходит на
        // подпись, а подписать не удаётся и по другой причине — фраза не та. Пропусти
        // сюда мусор, и человеку скажут «фраза не подходит» там, где он вставил не ту
        // строку: он начнёт перепроверять фразу вместо кода.
        if (clean.length != LENGTH) return null
        if (clean.any { it !in ALPHABET }) return null
        return clean
    }

    /** 32 байта в base64url без выравнивания — столько порождает сервер. */
    private const val LENGTH = 43
    private const val ALPHABET =
        "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_"
}
