package io.tima.core.network

import kotlinx.coroutines.flow.MutableSharedFlow
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.SharedFlow
import kotlinx.coroutines.flow.StateFlow

/**
 * Что система знает о сети — ПЛАН-УВЕДОМЛЕНИЙ.md, У17.
 *
 * ── ЗАЧЕМ, ЕСЛИ ЕСТЬ `LinkState` ────────────────────────────────────────────
 *
 * `LinkState` отвечает на вопрос «получится ли», и узнаёт это только **попыткой**. Отсюда
 * его цена: пока сети нет, мы узнаём об этом, пробуя, — а когда она вернулась, узнаём
 * через паузу отступления, до минуты. Звонок при этом живёт сорок пять секунд.
 *
 * Система знает другое — **когда пробовать**. Сеть пропала: пробовать бессмысленно.
 * Появилась или сменилась: пробовать надо сейчас, не дожидаясь паузы. И узнаём мы это
 * **без единого пробуждения по таймеру** — система будит нас сама.
 *
 * ── ЧЕГО ЭТО НЕ ЗНАЕТ, И ПОЧЕМУ `LinkState` ОСТАЁТСЯ ────────────────────────
 *
 * «Сеть есть» не значит «наш сервер доступен». Третье состояние из ADR-0016 — оператор
 * пускает соединение и душит содержимое — система видит как работающий интернет: её
 * проверка ходит к Google, а не к нам. Поэтому это знание решает **когда**, а `LinkState`
 * по-прежнему решает **с какой паузой**, если попытка не удалась.
 *
 * ── СМЕНА СЕТИ — ОТДЕЛЬНОЕ СОБЫТИЕ, А НЕ «ПРОПАЛА И ПОЯВИЛАСЬ» ──────────────
 *
 * Переход Wi-Fi → мобильная система сообщает **новой сетью по умолчанию**, без «пропала»
 * в промежутке: сеть была и есть. Но сокет остался привязан к старой, и он **полуоткрыт** —
 * ровно то, из-за чего realme 2026-09-23 двое суток не получал ни одного события. Его
 * надо рвать и поднимать заново сразу, не дожидаясь, пока пинг заметит.
 */
interface NetworkWatch {

    /** Есть ли сеть по последнему слову системы. */
    val state: StateFlow<NetworkState>

    /** Сменилась сеть по умолчанию — например, Wi-Fi на мобильную. */
    val switched: SharedFlow<Unit>

    companion object {
        /**
         * Ничего не знает и ни о чём не сообщает.
         *
         * Так на ПК (решение заказчика 2026-09-24: сеть там меняется редко, после
         * включения — почти никогда) и в проверках. Поведение с ним — прежнее: паузы
         * отступления по `LinkState`, и ничего сверх.
         */
        val NONE: NetworkWatch = object : NetworkWatch {
            override val state: StateFlow<NetworkState> = MutableStateFlow(NetworkState.UNKNOWN)
            override val switched: SharedFlow<Unit> = MutableSharedFlow()
        }
    }
}

enum class NetworkState {
    /** Система не сказала — либо некому сказать (ПК). Ведём себя как без неё. */
    UNKNOWN,

    /** Сеть по умолчанию есть. Доступен ли наш сервер — не знаем. */
    AVAILABLE,

    /** Сети нет. Пробовать бессмысленно. */
    LOST,
}

/**
 * Какой наблюдатель у процесса.
 *
 * Тот же приём, что у контактов и уведомлений: общий код про `Context` не знает, и
 * платформа ставит своего наблюдателя один раз при запуске. До этого — [NetworkWatch.NONE],
 * то есть прежнее поведение, а не ошибка.
 */
object NetworkWatches {
    @Volatile
    var current: NetworkWatch = NetworkWatch.NONE
}
