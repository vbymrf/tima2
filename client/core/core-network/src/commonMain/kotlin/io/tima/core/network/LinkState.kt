package io.tima.core.network

/**
 * Состояние связи с сервером.
 *
 * **Перенесено из v1 почти дословно** (инвентарь поведения, пункт 1). Это не код,
 * который стоит «улучшить»: признаки взяты из журналов настоящих испытаний в
 * мобильной сети, а не придуманы. Переписать их аккуратнее — значит потерять факты.
 *
 * Три состояния, а не два, потому что «не работает» бывает разным, и вести себя в
 * этих случаях надо по-разному (ADR-0016).
 *
 * **В коде намеренно нет ни слова о причине.** Сегодня трафик душит ограничение у
 * оператора, завтра его снимут, послезавтра человек окажется за корпоративным
 * файрволом или в кафе с кривым Wi-Fi. Мы различаем только то, что видим своими
 * глазами: устанавливается ли соединение и проходит ли по нему содержимое. Такое
 * различение не устаревает вместе с обстоятельствами.
 */
enum class LinkState {
    /** Соединение живёт, обмен идёт. */
    ONLINE,

    /** Сети нет: имя не разбирается, интерфейс опущен. */
    NO_NETWORK,

    /**
     * Сеть есть, соединение устанавливается — но содержимое не проходит.
     *
     * Отличается от [NO_NETWORK] тем, что TCP встаёт (и быстро: в испытаниях за
     * 57 мс), а дальше тишина. Долбиться в этом состоянии бессмысленно: это не
     * мигание сети, которое пройдёт через секунду, а стена, которая стоит часами.
     */
    BLOCKED,
    ;

    /** Через сколько пробовать снова. */
    val retryDelayMs: Long
        get() = when (this) {
            ONLINE -> 1_000
            // Сеть мигает часто и возвращается быстро — проверяем бодро.
            NO_NETWORK -> 5_000
            // Стена стоит часами. Раз в 15 секунд тут — это только севшая батарея.
            BLOCKED -> 120_000
        }
}

/**
 * По какому признаку опознаём состояние.
 *
 * Разбираем текст ошибки, потому что типы исключений на Android, ПК и iOS разные, а
 * повод один. Признаки взяты из настоящих журналов испытаний.
 *
 * Тринадцать признаков — не «столько нашлось», а столько встретилось в живой сети.
 * Добавлять новые можно, убирать существующие — только вместе с журналом, который
 * покажет, что такого больше не бывает.
 */
fun classifyFailure(error: Throwable?): LinkState {
    val text = generateSequence(error) { it.cause }
        .joinToString(" ") { "${it::class.simpleName} ${it.message.orEmpty()}" }
        .lowercase()
    return when {
        // Имя не разбирается — сети под ногами нет вовсе.
        "unknownhost" in text || "unable to resolve host" in text ||
            "no address associated" in text || "nodename nor servname" in text -> LinkState.NO_NETWORK

        // Соединение даже не начали устанавливать.
        "network is unreachable" in text || "econnrefused" in text ||
            "connection refused" in text || "no route to host" in text -> LinkState.NO_NETWORK

        // Соединение установилось, а ответа нет. Ровно это видели в мобильной сети:
        // TCP встаёт за 57 мс, дальше тишина.
        "timeout" in text || "timed out" in text -> LinkState.BLOCKED

        // Соединение оборвали снаружи посреди работы.
        "connection abort" in text || "connection reset" in text ||
            "eofexception" in text || "broken pipe" in text -> LinkState.NO_NETWORK

        else -> LinkState.NO_NETWORK
    }
}
