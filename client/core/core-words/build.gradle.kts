// core-words — словарь надписей: русский, английский, испанский (ПЛАН-ЯЗЫКА, Я-D).
//
// ── ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ ────────────────────────────────────────────────────
//
// До 2026-09-14 словарь лежал в core-ui, то есть в дизайн-системе. Вместе с ним туда
// переехали перечни оболочки — окна, вкладки, пункты настроек, — потому что словарь брал
// их параметром, а core-ui не вправе импортировать feature. Так дизайн-система узнала,
// что окон пять и что порядок их объявления — это порядок свайпа.
//
// Ни одно архитектурное правило этого не поймало: импорты шли в разрешённую сторону.
//
// ── ПОЧЕМУ ЗАВИСИМОСТЕЙ НЕТ ВОВСЕ ─────────────────────────────────────────────
//
// Это правило, а не текущее состояние. Словарь называет надписи и ничего больше: как
// только он начинает знать чужие типы, перечни снова поедут вниз — теперь уже сюда, и
// повод будет тот же. Раскладка «ключ → надпись» делается у того, чей это ключ.
//
// Compose здесь тоже нет намеренно: LocalWords и Tima.words остались в core-ui, потому
// что это раздача, а не словарь. Без Compose словарём пользуется store, который рисовать
// не умеет и не должен.
//
// Проверяется правилом «core-words без зависимостей» в architecture-tests.
