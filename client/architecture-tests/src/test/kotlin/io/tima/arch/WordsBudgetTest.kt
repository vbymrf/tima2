package io.tima.arch

import java.io.File
import kotlin.test.Test
import kotlin.test.assertTrue

/**
 * **Надписи переезжают в словарь, и счётчик это показывает** (ПЛАН-ЯЗЫКА Я2).
 *
 * Считаются строковые литералы с кириллицей в экранах — `core-ui` и модулях `feature` — **вне
 * словаря**. Словарь (`Words.kt`) исключён намеренно: надписи в него и переезжают, и
 * считать их там значило бы, что счётчик никогда не убывает.
 *
 * ── ПОЧЕМУ ТОЛЬКО ЭКРАНЫ ────────────────────────────────────────────────────
 *
 * Кириллица в `core-network`, `core-secrets`, `domain` и `shared` — это сообщения
 * `require`, тексты журнала и коды диагностики. Они **не переводятся по решению**: журнал
 * инструмент чинящего, и переведённый перестаёт находиться поиском по коду. Включить их в
 * счёт значило бы гнать в словарь то, чему там не место.
 *
 * ── КАК ЧИТАТЬ ПАДЕНИЕ ──────────────────────────────────────────────────────
 *
 * Стало больше — кто-то завёл новую надпись мимо словаря. Стало меньше — прошла партия
 * переноса, и число обязано быть понижено **тем же коммитом**: иначе счётчик перестаёт
 * что-либо значить, а работа выглядит несделанной.
 *
 * Счёт грубый: комментарии вырезаются простыми правилами, и одна-две строки могут быть
 * посчитаны неточно. Это не мешает — важна не абсолютная величина, а её движение вниз.
 */
class WordsBudgetTest {

    private val client = File(requireNotNull(System.getProperty("client.root")) {
        "не передан client.root — смотри build.gradle.kts этого модуля"
    })

    @Test
    fun надписей_вне_словаря_не_прибавляется() {
        val found = countIn(File(client, "core/core-ui")) + countIn(File(client, "feature"))

        assertTrue(
            found <= BUDGET,
            "Надписей вне словаря стало $found при бюджете $BUDGET.\n" +
                "Новая надпись строкой в экране — это надпись, которой не будет на другом " +
                "языке. Заводите её в `core-ui/Words.kt` (ПЛАН-ЯЗЫКА Я2).",
        )
        assertTrue(
            found >= BUDGET,
            "Стало $found при бюджете $BUDGET — понизьте бюджет тем же коммитом, которым " +
                "прошла партия переноса. Иначе счётчик перестанет что-либо значить.",
        )
    }

    private fun countIn(root: File): Int = root.walkTopDown()
        .filter { it.isFile && it.name.endsWith(".kt") }
        .filterNot { it.path.replace('\\', '/').contains("/build/") }
        .filterNot { it.path.contains("Test") }
        // Словарь исключён: надписи в него переезжают, и считать их там нельзя.
        .filterNot { it.name == "Words.kt" }
        .sumOf { file -> LITERAL.findAll(withoutComments(file.readText())).count { CYRILLIC.containsMatchIn(it.value) } }

    private fun withoutComments(source: String): String = source
        .replace(BLOCK_COMMENT, "")
        .replace(LINE_COMMENT, "")

    private companion object {
        val CYRILLIC = Regex("""[А-Яа-яЁё]""")

        /**
         * Строковый литерал — грубо: от кавычки до кавычки в одной строке.
         *
         * Экранированной кавычки внутри надписи у нас не встречается, а точный разбор
         * Kotlin здесь не нужен: считается движение числа вниз, а не его величина.
         */
        val LITERAL = Regex("\"[^\"\\n]*\"")
        val BLOCK_COMMENT = Regex("/\\*.*?\\*/", RegexOption.DOT_MATCHES_ALL)
        // Без «$» на конце: в строке Kotlin «$» перед кавычкой начинает подстановку,
        // а «.» и так не переходит на новую строку.
        val LINE_COMMENT = Regex("(?m)^\\s*//.*")

        /**
         * Измерено 2026-09-08. До первой партии было 838; после неё 796; после второй
         * (экран оформления целиком) — 778; после третьей (вкладки, фильтры и режимы
         * стали ключами) — 737.
         *
         * Число **только убывает**: каждая следующая партия Я2 понижает его тем же
         * коммитом, которым переносит надписи.
         *
         * **Из чего состоит остаток**, чтобы следующий не искал заново:
         *
         * - около 200 — заглушки окон («здесь будет общая лента»). Они умрут вместе с
         *   постройкой этих окон, и гнать их в словарь значит завести двести имён, чтобы
         *   потом их удалить;
         * - названия вкладок **уже перенесены** третьей партией: ключ — `WindowTab`,
         *   слово — `Words.tabs`. Разделы книги контактов при этом остались строками:
         *   их придумывает человек, это данные, а не словарь;
         * - около 30 — тело отчёта о проблеме. Оно **не переводится по решению**: его
         *   читает чинящий.
         */
        const val BUDGET = 737
    }
}
