package io.tima.testui

import androidx.compose.ui.text.font.FontFamily
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.text.platform.Font

/**
 * Эталонный шрифт снимочных проверок.
 *
 * ── ЗАЧЕМ ОН ───────────────────────────────────────────────────────────────
 *
 * Снимки меряют настоящие пиксели, а ширина текста в пикселях зависит от шрифта. Пока
 * шрифт брался системный, три проверки давали **разные ответы на разных машинах**: на
 * машине разработки зелено, на раннере сборки красно. Найдено 2026-09-15, когда
 * `client · JVM` наконец дошёл до тестов:
 *
 *   RailWidthTest.рейка_вмещает_самую_длинную_подпись_окна
 *   SecondRowTest.у_медиа_режим_стоит_в_ряду_вкладок
 *   RowFitTest.известно_какие_ряды_переносятся_на_телефоне
 *
 * Все три про ширину текста, и ни один из двух ответов не относился к телефону: там
 * рисует Roboto, а не шрифт Windows и не шрифт Ubuntu.
 *
 * Шрифт в снимках должен быть **один и тот же везде**. Тогда проверка говорит про наш
 * интерфейс, а не про машину.
 *
 * ── ПОЧЕМУ OPEN SANS ───────────────────────────────────────────────────────
 *
 * Он в списке шрифтов, выбранных для приложения (`doc_mig/ИНТЕРФЕЙС/ШРИФТЫ.md`),
 * лежит в `google/fonts` и раздаётся по OFL-1.1 — лицензия рядом с файлом. Переменное
 * начертание одно на все веса: полужирный Skia досинтезирует, и досинтезирует одинаково
 * на любой машине, а больше от эталона ничего и не требуется.
 *
 * **Это не шрифт приложения.** Приложение по-прежнему рисует системным; что положить в
 * сборку — отдельное решение, и оно не принято.
 */
object ReferenceFont {

    /**
     * Семейство для снимков.
     *
     * Оба веса грузятся из одного файла: начертание переменное, и отдельного
     * полужирного в нём нет. Полужирный Skia досинтезирует — одинаково на любой машине,
     * а больше от эталона ничего и не требуется.
     */
    val family: FontFamily by lazy {
        FontFamily(
            Font(PATH, FontWeight.Normal),
            Font(PATH, FontWeight.Bold),
        )
    }

    /** Путь в ресурсах, без ведущей косой: грузит загрузчик классов. */
    private const val PATH = "fonts/OpenSans.ttf"
}
