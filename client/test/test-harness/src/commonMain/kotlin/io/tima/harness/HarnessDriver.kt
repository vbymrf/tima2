package io.tima.harness

import app.cash.sqldelight.db.SqlDriver

/**
 * Драйвер базы для харнесса — своя реализация на каждой платформе.
 *
 * **Почему он повторяет драйвер из тестов `core-database`.** Тестовые исходники модуля
 * никуда не публикуются: их не видит ни другой модуль, ни другая сборка. Вынести
 * такой драйвер в боевой код `core-database` было бы хуже — это тестовая оснастка,
 * а не часть продукта. Дешевле повторить десять строк, чем поселить оснастку в
 * продукте.
 *
 * **Схему создаёт платформа.** Контракт стоил упавшего прогона: на Apple
 * `inMemoryDriver(Schema)` создаёт её сам, и повторный `Schema.create` валит все
 * тесты сообщением «table messages already exists».
 */
expect fun harnessDriver(): SqlDriver
