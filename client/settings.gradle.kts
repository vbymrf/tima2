include(":core:core-network")

// Здесь был спайк К1.4 (:core:spike-ios-deps) — временный модуль, проверявший,
// собираются ли зависимости крипто под iOS. Удалён в К2, как и обещал сам файл:
// на те же вопросы теперь отвечает messenger-crypto, переведённый на KMP, и
// отвечает по-настоящему — прогоном тест-векторов на симуляторе, а не round-trip
// на выдуманных данных.
//
// core-encryption (фасад над messenger-crypto) здесь НЕ появляется, хотя
// дорожная карта числит его в К2. Причина — правило из этого же файла: модуль
// заводится, когда у кода есть потребитель. Потребитель фасада — слой Data, а он
// пишется в К3. Пустой модуль ради полноты схемы дал бы минуты ожидания Gradle и
// ноль изоляции.

// Фасад над messenger-crypto: слой Data говорит с криптографией через него, а не
// собирает четыре вызова руками. К3 (Plan.md §3.6).
