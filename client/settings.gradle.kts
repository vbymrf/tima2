// ── Репозитории: только официальные источники ─────────────────────────────
//
// Здесь стояло зеркало `maven.aliyun.com` — первым вне CI и последним на CI.
// Его добавили, когда в сети разработки блокировался `dl.google.com`.
// Убрано по решению заказчика 2026-09-03. Причин две.
//
// Первая — зеркало само подводило. Прогон 2026-08-20 упал с `502 Bad Gateway`
// от `maven.aliyun.com` при загрузке `apache-18.pom`, и это выглядело поломкой
// кода, хотя код был цел. На машине разработки 2026-09-03 без `CI=1` клиент не
// собирался вовсе, а с `CI=1` — за 17 мин 45 с, 834 из 834. То есть обходом
// было именно отключение зеркала, а не его включение.
//
// Вторая — правило проекта: сборка ходит только к официальным источникам
// зависимостей, и каждый из них назван в doc_vnedren/allowed-hosts.txt. Зеркало
// третьей стороны отдаёт те самые байты, из которых собирается приложение.
// Разбор: doc_vnedren/БЕЗОПАСНОСТЬ-ЗЕРКАЛА-ALIYUN.md.
//
// Сверка скачанного — `gradle/verification-metadata.xml`: каждый артефакт сверяется
// по sha256, несовпадение останавливает сборку.
//
// Если `dl.google.com` снова окажется недоступен — это решается на стороне сети,
// а не подменой источника в сборке.

pluginManagement {
    repositories {
        google()
        gradlePluginPortal()
        mavenCentral()
    }
}

dependencyResolutionManagement {
    repositories {
        // ── mavenLocal ПЕРВЫМ, и это не «на всякий случай» ────────────────────
        //
        // Здесь лежат форки KyberKotlin и KeccakKotlin с включёнными таргетами
        // Apple (../third-party). Координаты у них те же, что у апстрима, а апстрим
        // артефактов Apple не публикует.
        //
        // Почему это нужно КЛИЕНТУ, хотя зависимость объявлена в messenger-crypto:
        // composite build подставляет проект вместо зависимости, но транзитивные
        // зависимости этого проекта резолвятся **репозиториями потребителя**. То
        // есть без mavenLocal здесь клиент честно найдёт kyber в mavenCentral — без
        // вариантов под iOS, — и падение будет выглядеть как «No matching variant
        // of asia.hombre:kyber», указывая на что угодно, кроме порядка репозиториев.
        //
        // Собрать форки: ./gradlew publishToMavenLocal в third-party/KeccakKotlin,
        // затем в third-party/KyberKotlin (kyber зависит от keccak).
        mavenLocal()
        google()
        mavenCentral()
    }
}

// ── messenger-crypto как composite build ──────────────────────────────────────
//
// Криптомодуль живёт своей сборкой и своим циклом: у него отдельные репозитории
// (mavenLocal перед mavenCentral — там лежат форки Kyber и Keccak с таргетами
// Apple) и отдельный прогон векторов. includeBuild подставляет его вместо
// зависимости io.tima:messenger-crypto, то есть правка крипто видна клиенту сразу,
// без публикации.
//
// Так же он подключался и в v1. Причина та же и не в удобстве: криптография — это
// то место, где расхождение версий даёт нечитаемую переписку, а не «немного другое
// поведение». Одна сборка на две — один код.
includeBuild("../messenger-crypto")

// Структура модулей — Plan.md §3.1. Модули добавляются по мере надобности:
// правило проекта — «модуль появляется, когда у кода есть второй потребитель
// или другой цикл сборки; до этого — пакет» (Plan.md §2.2 п.5). Пустые модули
// ради полноты схемы дают минуты ожидания Gradle и ноль изоляции.

include(":core:core-model")

// Сеть. Пока только состояние связи, перенесённое из v1: единственная часть
// сетевого слоя, измеренная в живой мобильной сети, а не спроектированная.
include(":core:core-network")

// Здесь был спайк К1.4 (:core:spike-ios-deps) — временный модуль, проверявший,
// собираются ли зависимости крипто под iOS. Удалён в К2, как и обещал сам файл:
// на те же вопросы теперь отвечает messenger-crypto, переведённый на KMP, и
// отвечает по-настоящему — прогоном тест-векторов на симуляторе, а не round-trip
// на выдуманных данных.
//
// core-encryption (фасад над messenger-crypto) здесь НЕ появляется, хотя
// дорожная карта числит его в К2. Причина — правило из этого же файла: модуль
// заводится, когда у кода есть потребитель. Потребитель фасада — слой Data, а он
// пишется в К3. Пустой модуль ради полноты схемы дал бы минуты ожидания Gradle и
// ноль изоляции.

// Фасад над messenger-crypto: слой Data говорит с криптографией через него, а не
// собирает четыре вызова руками. К3 (Plan.md §3.6).
include(":core:core-encryption")

// Локальное хранилище: схема Plan.md §3.4.2, драйверы по платформам. Здесь же
// живёт реализация OutboxStore — очередь по плану это колонки в messages, а не
// отдельная таблица.
include(":core:core-database")

// Очередь исходящих: «не теряет и не дублирует ни в одном состоянии» — это
// названный выход этапа К3, и проверяется он здесь, без базы и без корутин.
include(":core:core-outbox")

// Хранилище ключевого материала: Keystore / Keychain / DPAPI. Отдельный модуль
// потому, что в v1 секрет лежал открытым файлом рядом с базой, и шифрование покоя
// было декоративным — «хранилище ключа это часть формата» (Plan.md §3.6).
include(":core:core-secrets")
include(":core:core-contacts")

// Личность и устройства. Первый модуль слоя Domain: порядок шагов заведения
// устройства — правило продукта, а не свойство HTTP, и повторять его в каждом
// входе (экран, харнесс, отладочная команда) значило бы однажды сделать иначе.
include(":domain:domain-account")

// Переписки. Здесь правила отправки: ключ идемпотентности назначается до первой
// попытки — то, чего не было в v1 (инвентарь, пункт 8), и потому дубль после
// обрыва связи был там обычным делом.
include(":domain:domain-chat")

// Фейки и сценарии без устройства. Здесь живёт названный выход К4: сценарий
// «отправил — обрыв — повтор — доставлено» проходит без сервера.
include(":test:test-harness")

// Вход: телефон, код, заведение устройства. Водопровод готов в domain-account с К4.3 —
// здесь экраны. Email, пароля и резервных кодов нет: их нет на сервере, вопрос у
// заказчика (Д1).
include(":feature:feature-auth")

// Окно переписки. Пока только Store: признак готовности К4 сформулирован через
// него — «сценарий отправил-обрыв-повтор-доставлено проходит тестом Store без
// сервера». Экраны рисуют на работающем сквозном пути, а не до него.
include(":feature:feature-chat")

// Группы: создание, состав и групповой ключ (К6.1). Отдельно от окна переписки —
// у группы своя работа, и окну переписки управление участниками не нужно.
include(":feature:feature-group")

// feature-shell — оболочка: перечень окон, переключатель, рейка, каркас окна с
// вкладками. Экраны, а не компоненты: у переключателя своё состояние и свои переходы.
include(":feature:feature-shell")

// Дизайн-система из макета: токены, тема, компоненты (дорожка У). Экраны без неё
// собирать нечем, а её саму можно делать без ядра — поэтому она и идёт параллельно.
include(":core:core-ui")

// Снимки композиций: и дизайн-система, и экраны проверяются одним способом.
