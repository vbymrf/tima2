package io.tima.feature.shell

// Перечни настроек живут в оболочке, рядом с [Window] и [WindowTab]: **надпись лежит в
// словаре, ключ — здесь** (ПЛАН-(Я)-ЯЗЫКА Я2). Перечисление, носящее надпись, невозможно
// перевести, не сломав навигацию: имя пункта служит и ключом перехода.
//
// Раскладка «ключ → надпись» — в [group] и [item]: словарь настроек не знает
// (ПЛАН-(Я)-ЯЗЫКА, Я-D).

/**
 * Группы разделов — те же четыре, что в макете.
 *
 * **«Помощь» — первой** (заказчик 2026-10-07: «Заголовок „Помощь“ в самый верх»). В настройки с
 * бедой идут чаще всего, и искать выход внизу списка человеку, у которого что-то сломалось, —
 * лишний шаг ровно в худший момент. До этого первой строкой стоял один «Сообщить о проблеме»,
 * а остальная «Помощь» была внизу.
 */
enum class SettingsGroup {
    HELP,
    ACCOUNT,
    APPLICATION,
    BLOGGER,
}

/**
 * Пункт настроек.
 *
 * Перечень, а не строки у вызывающего: имя пункта — одновременно ключ навигации и надпись
 * на экране, и, разъехавшись в двух местах, они дают пункт, который не открывается.
 *
 * Порядок объявления — порядок на экране. Он взят из макета и держится на нём, а не на
 * вкусе: «Профиль» первым в «Аккаунте» потому, что чаще всего заходят посмотреть на себя.
 * Группа «Помощь» стоит выше всех — см. [SettingsGroup].
 */
enum class SettingsItem(val group: SettingsGroup, val glyph: String) {
    /** Первым в «Помощи» — порядок заказчика 2026-10-07: проблема, вопросы, предложить изменения, обновление. */
    PROBLEM(SettingsGroup.HELP, "🐞"),
    QUESTIONS(SettingsGroup.HELP, "❓"),

    /**
     * Предложить изменения (заказчик 2026-10-07) — сообщение и фото, как «Сообщить о проблеме», но
     * без журнала: предложение не поломка. Сервер отличает его видом `suggestion`.
     */
    SUGGEST(SettingsGroup.HELP, "💡"),

    /**
     * Обновление — пункт заказчика от 2026-08-26.
     *
     * **В макете на его месте «О приложении» с версией справа.** Разделение сделано
     * потому, что это разные вопросы: «что у меня стоит» — справка, «есть ли новее» —
     * действие, и действию нужна кнопка. Расхождение с макетом названо здесь, чтобы его
     * не обнаружили как ошибку: правится оно решением заказчика, а не молча.
     */
    UPDATE(SettingsGroup.HELP, "📥"),
    ABOUT(SettingsGroup.HELP, "ℹ"),

    PROFILE(SettingsGroup.ACCOUNT, "👤"),

    /**
     * Фраза и устройства — один пункт, а не два.
     *
     * Так в макете, и это не экономия строки: фраза и есть то, чем заводят новое
     * устройство. Разведённые по разным пунктам, они выглядят как несвязанные вещи, и
     * человек, потерявший телефон, ищет не там.
     */
    DEVICES(SettingsGroup.ACCOUNT, "🔑"),
    NOTIFICATIONS(SettingsGroup.ACCOUNT, "🔔"),

    /**
     * Разрешения — одно место для всех (заказчик 2026-09-26): уведомления, канал «Звонки»,
     * во весь экран, работа в фоне, микрофон, камера, контакты. Раньше они были разбросаны:
     * часть — в «Уведомлениях», микрофон и контакты спрашивались только по месту.
     */
    PERMISSIONS(SettingsGroup.ACCOUNT, "🛡"),

    /**
     * Микрофон и камера — выбор устройств и проверка без звонка (заказчик 2026-09-26,
     * ПЛАН-(ПК)-ЗВОНКОВ-ПК). Есть там, где устройств несколько и выбирает человек, — на ПК; на
     * телефоне пункт скрыт ([SettingsScreen] `hidden`).
     */
    MEDIA(SettingsGroup.ACCOUNT, "🎙"),

    /**
     * Виртуальные аккаунты — ПЛАН-(Д)-КОНТАКТОВ.md, Д10…Д12.
     *
     * В разделе «Аккаунт», а не в отдельном месте: это распоряжение своими аккаунтами —
     * завести, передать, принять. Переключаются между ними в другом месте (переключение
     * окон), и это не противоречие: переключаются часто, распоряжаются редко.
     */
    VIRTUALS(SettingsGroup.ACCOUNT, "🎭"),

    APPEARANCE(SettingsGroup.APPLICATION, "🎨"),

    /**
     * Шрифты и размеры — отдельным пунктом от цветов (решение заказчика 2026-09-16).
     *
     * Раньше это был один «Оформление», и он разросся: семнадцать цветов, сохранённые
     * наборы, а теперь ещё шрифт и пять ручек размера. Один пункт на всё означал бы
     * экран, по которому надо прокручивать, чтобы найти известное.
     */
    TEXT(SettingsGroup.APPLICATION, "🔠"),
    LANGUAGE(SettingsGroup.APPLICATION, "🌐"),
    PRIVACY(SettingsGroup.APPLICATION, "🔒"),
    STORAGE(SettingsGroup.APPLICATION, "💾"),

    /**
     * Звонки — аппаратное кодирование и раскодирование видео (ПЛАН-(В)-ВИДЕО.md В4, заказчик
     * 2026-09-29). Только телефон: на ПК кодеры программные, и пункт скрыт.
     */
    CALLS(SettingsGroup.APPLICATION, "📞"),

    /**
     * Испытательный режим звонков — **временный пункт**.
     *
     * Он уйдёт вместе со стендом, когда забег кончится (ПЛАН-(С)-СТЕНДА-ЗВОНКОВ С-В1: «окно
     * уходит вместе с флагом, а не остаётся „на всякий случай“»). Названо здесь, чтобы
     * через полгода его не приняли за часть приложения и не начали чинить.
     */
    CALLBENCH(SettingsGroup.APPLICATION, "🧪"),

    BLOGGER(SettingsGroup.BLOGGER, "📈"),
}
