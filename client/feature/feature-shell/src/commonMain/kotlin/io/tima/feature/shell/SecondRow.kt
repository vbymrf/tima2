/**
 * Второй ряд окна: фильтры и режимы под вкладками.
 *
 * ── ЧТО ЭТО ЗА РЯД И ЧЕМ ОН ОТЛИЧАЕТСЯ ОТ ВКЛАДОК ───────────────────────────
 *
 * `интерфейс.md §1`: «Между зоной 1 и зоной 2 живут вкладки, а под ними — режимы,
 * фильтры или полоса разделов, если они в этом окне есть».
 *
 * **Вкладка говорит, откуда содержимое; чип — про что оно.** Отсюда и разное
 * поведение: вкладка меняет экран, чип сужает список, ничего не пряча (`§13`).
 *
 * ── ЧТО РЕШЕНО 2026-09-02 ───────────────────────────────────────────────────
 *
 * **Ничего не прячется: ряд переносится на новую строку.** Первая редакция прокручивала
 * чипы вбок, и на колонке ПК в 340 точек «Каталог» просто исчезал за краем — прокрутка
 * есть, а признака прокрутки нет, и чип выглядел несуществующим. Перенос виден сразу:
 * ряд стал выше, значит в нём есть ещё.
 *
 * **Три ряда — три вида, и путать их нечем.** Вкладка — слово без заливки, текущая
 * залита салатовым; подвкладка — серая пилюля, выбранная залита тем же салатовым;
 * переключатель режима живёт в общей серой капсуле, и **капсула и есть его отличие**
 * ([ModeSwitch]).
 *
 * Вид этот собирался в три приёма, и каждый раз ряды оказывались похожи сильнее, чем
 * думалось за кодом. Сперва все три набрались одинаковыми чипами, и «Открытое» с
 * «Личным» встали пятой и шестой подвкладкой. Потом подвкладка стала серой, а
 * переключатель — капсулой, но вкладка осталась чипом с тихой заливкой: два ряда
 * залитых пилюль друг под другом, и заказчик сказал прямо — «второй ряд полностью
 * повторяет первый». Тогда вкладка вернулась к макетному `.таб` без фона, а заливка у
 * выбранного режима сменилась обводкой.
 *
 * ── ЧТО ИЗМЕНИЛОСЬ 2026-09-03 ───────────────────────────────────────────────
 *
 * **Ряд стоит одной строкой, и переключатель снова прижат вправо.** Решение заказчика,
 * макет перерисован: `.строка-фильтров { gap: 6px }`, `> .чип { padding: 3px 6px }`,
 * `.режимы { margin-left: auto }`. Прежними отступами ряд «Коллекций» просил 374 точки
 * при 348 доступных и переносился; теперь просит 331.
 *
 * Прижатое вправо и перенос друг другу мешают — прижатое либо стоит в строке, либо
 * выдавливает соседей за край. Поэтому распорка ставится **только когда есть хвост**, и
 * ровно тот ряд, где она стоит, измерен [RowFitTest] как непереносящийся. Если ряд
 * когда-нибудь всё же переедет, распорка останется в первой строке, а хвост уйдёт во
 * вторую: некрасиво, но ничего не обрезано.
 *
 * **Подложка ряда — общая серая**, та же, что у вкладок и шапки. Шапка, вкладки и этот
 * ряд образуют один блок управления; линия у него одна, снизу, и рисует её каркас окна.
 */
@OptIn(ExperimentalLayoutApi::class)
@Composable
fun FilterRow(
    /** Чипы ряда. Пусто — законный случай: бывает ряд из одного только режима. */
    items: List<String> = emptyList(),
    selected: String = "",
    onPick: (String) -> Unit = {},
    modifier: Modifier = Modifier,
    /** Хвост ряда: переключатель режимов. Есть не у всякого ряда. */
    trailing: (@Composable () -> Unit)? = null,
) {
    val colors = Tima.colors
    FlowRow(
        modifier = modifier
            .fillMaxWidth()
            .background(colors.functional)
            .padding(horizontal = TimaSpacing.about4, vertical = TimaSpacing.about2),
        horizontalArrangement = Arrangement.spacedBy(ROW_GAP),
        verticalArrangement = Arrangement.spacedBy(TimaSpacing.about2),
    ) {
        for (name in items) {
            Chip(
                label = name,
                // Нейтральная подложка, а не тихая: ряд подвкладок обязан читаться
                // иначе, чем ряд вкладок над ним. Решение заказчика — «серый, темнее
                // фона; активная — тот же салатовый».
                kind = if (name == selected) ChipKind.Selected else ChipKind.Neutral,
                onClick = { onPick(name) },
                horizontalPadding = CHIP_SIDE,
            )
        }
        if (trailing != null) {
            // Распорка, а не выравнивание всего ряда: чипы остаются у левого края,
            // переключатель уходит к правому, и пустота между ними — то, что отделяет
            // «сузить список» от «сменить контур».
            Box(Modifier.weight(1f))
            trailing()
        }
    }
}

/**
 * Переключатель режимов — `.режимы` макета, один в один.
 *
 * **Серая капсула, внутри сегменты, выбранный залит салатовым.** Форму назвал
 * заказчик: `телефон/окна/медиа.html`, где этим переключают «Лента / Слайды». В
 * `стиль.css` это три строки, и они здесь воспроизведены значениями:
 *
 * ```css
 * .режимы    { background: var(--чёрный-6); border-radius: var(--радиус-круг); padding: 3px }
 * .режим     { padding: 3px 7px; font-size: var(--щ6); color: var(--чёрный-50) }
 * .режим.тек { background: var(--навигация); color: #ffffff }
 * ```
 *
 * **Заливка вернулась 2026-09-03, обводка отменена.** Обводка стояла сутки, по пробе 04
 * из `пробы/пробы-второй-ряд.html`, и решение снято заказчиком по той же пробе: рамка
 * вокруг слова читается **тише** выбора, а не иначе его, — прищурившись, ряд выглядел
 * выключенным целиком, и на вопрос «какой контур сейчас» глаз не отвечал.
 *
 * **Цена названа и принята:** в нижнем ряду салатовых пятна два — выбранная подвкладка
 * и выбранный режим. Разделяет их не отметка выбора, а капсула: серая подложка вокруг
 * пары сегментов есть только здесь, и её видно прищурившись, когда надписи пропадают.
 * Если ряд снова начнёт читаться сплошным, чинить надо заливку **подвкладки**, а не
 * возвращать обводку сюда: подвкладок три, и серыми они уже нейтральны.
 *
 * **Рамки у сегментов больше нет.** Пока выбранное обводилось, прозрачная рамка стояла
 * у всех, чтобы выбранный сегмент не становился шире соседа. Теперь ширину держит одно
 * поле [SWITCH_SIDE], и держит её одинаково у всех сегментов по построению.
 *
 * **Капсула и есть то, что отличает переключатель от подвкладок.** Промежуточная
 * редакция того же дня набрала его отдельными чипами — вышли ещё две подвкладки, и
 * «Открытое» с «Личным» встали в один ряд с «Медиа» и «Каталогом», хотя выбирают
 * разное: подвкладка сужает список, режим переключает контур. Общая подложка склеивает
 * два сегмента в одну вещь, у которой всегда выбрана ровно одна половина.
 *
 * Два таких переключателя: «Лента / Слайды» в окне 3 — он стоит в ряду вкладок, потому
 * что это состояние всего окна, — и «Открытое / Личное» в коллекциях окна 5.
 */
@Composable
fun ModeSwitch(
    modes: List<String>,
    selected: String,
    onPick: (String) -> Unit,
    modifier: Modifier = Modifier,
) {
    val colors = Tima.colors
    Row(
        modifier = modifier
            .background(colors.quiet, CircleShape)
            .padding(SWITCH_EDGE),
        verticalAlignment = Alignment.CenterVertically,
    ) {
        for (mode in modes) {
            val current = mode == selected
            Box(
                modifier = Modifier
                    .background(
                        color = if (current) colors.navigation else Color.Transparent,
                        shape = CircleShape,
                    )
                    .clickable { onPick(mode) }
                    .padding(horizontal = SWITCH_SIDE, vertical = SWITCH_TOP),
                contentAlignment = Alignment.Center,
            ) {
                Caption(
                    text = mode,
                    fontSize = TimaType.sz6,
                    weight = FontWeight.Bold,
                    color = if (current) colors.onAccent else colors.text2,
                )
            }
        }
    }
}

/**
 * Поле капсулы вокруг сегментов — `padding: 3px` макета.
 *
 * Числом, а не токеном отступа: в лестнице `--о1…--о6` трёх точек нет, и подгонять
 * `about1` под этот случай значило бы менять её для всех остальных.
 */
private val SWITCH_EDGE = 3.dp

/**
 * Поле сегмента по бокам — `.режим { padding: 3px 7px }` плюс две точки, которые в
 * макете занимала прозрачная рамка. Рамки здесь больше нет, а ширина осталась прежней:
 * переключатель считался под неё, когда мерили ряд на перенос.
 */
private val SWITCH_SIDE = 7.dp

/** Поле сегмента сверху и снизу — те же 3 плюс 2 от снятой рамки. */
private val SWITCH_TOP = 5.dp

/**
 * Зазор между пунктами в рядах вкладок и фильтров — `gap: 6px` макета.
 *
 * Общий для [FilterRow] и [TabRow]: оба ряда сжимались одним решением заказчика
 * 2026-09-03 и обязаны сжиматься дальше вместе. Разъехавшись, они снова стали бы
 * похожи друг на друга — ровно то, от чего уходили весь сентябрь.
 */
internal val ROW_GAP = 5.dp

/**
 * Поле подвкладки по бокам в этом ряду — `.строка-фильтров > .чип { padding: 3px 6px }`.
 *
 * Ужато только здесь: чип в списке или в шапке стоит по макетным десяти, и трогать его
 * незачем. Здесь же рядом переключатель, и без этих восьми точек ряд не встаёт строкой.
 */
private val CHIP_SIDE = 5.dp
