package io.tima.feature.shell

/**
 * Запуск вместе с системой — «Настройки → Разрешения → Автозагрузка» (заказчик 2026-09-27).
 *
 * Есть только у ПК: телефон поднимает канал сам, по уведомлению. Порт объявлен здесь, а
 * исполнен платформой — так же, как установщик обновлений: общий код не знает, где у
 * системы список автозагрузки.
 */
interface LoginStart {
    /**
     * Можно ли включить вообще. Запущенное из исходников (Gradle) себя не запустит — у него
     * нет своей программы, и тогда раздел говорит об этом строкой вместо выключателя.
     */
    val available: Boolean

    /**
     * Включён ли — спрашивается у системы при каждом заходе, а не помнится: человек мог
     * выключить автозагрузку в «Диспетчере задач», мимо нас.
     */
    fun enabled(): Boolean

    fun set(on: Boolean)
}
