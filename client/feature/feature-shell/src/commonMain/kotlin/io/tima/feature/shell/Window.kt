package io.tima.feature.shell

/**
 * Окна приложения — перечень, а не строка.
 *
 * **Имён у окна два, и оба нужны** (`интерфейс.md §1`): длинное — в переключателе и
 * рейке, короткое — в собственной шапке. «Социальная лента» против «Социум». Оба лежат
 * в словаре ([WindowWords]), а здесь остался ключ: перечисление, носящее надпись,
 * невозможно перевести, не сломав навигацию (ПЛАН-ЯЗЫКА Я2).
 *
 * Живёт в оболочке, а не в словаре (ПЛАН-ЯЗЫКА, Я-D). С Я2 по Я-D перечень лежал в
 * `core-ui`, потому что словарь брал его параметром, — и дизайн-система из-за этого знала,
 * что окон пять и что порядок их объявления есть порядок свайпа. Теперь словарь окна не
 * знает: раскладка «ключ → имя» делается здесь, в [name].
 *
 * **Порядок объявления — это порядок в переключателе и порядок свайпа.** Отдельного
 * списка «в каком порядке показывать» нет намеренно: второй список однажды разойдётся
 * с первым.
 *
 * Блогерских окон 6–7 здесь нет: они включаются в настройках и появятся вместе с ними
 * (`§12` — окон блогера в макете нет вовсе).
 */
enum class Window(
    /** Знак в рейке и в переключателе. Знак — не слово: он не переводится. */
    val glyph: String,
    /**
     * Собирает ли окно сводный счётчик непрочитанного.
     *
     * У медиа-ленты и личной страницы его нет: в макете счётчик стоит у телефона,
     * социальной ленты и общения. Это не забывчивость — непрочитанное там не
     * накапливается: лента листается, а своя страница не приходит извне.
     */
    val withCounter: Boolean,
    /**
     * Окно живёт не всегда, а пока есть чему в нём быть.
     *
     * Такое окно одно — звонок (макет `21-call.md`: «окно 0, временное, первое в
     * горизонтальном переключателе»; решение заказчика 2026-09-19). Показывать его, когда
     * никто не звонит, значит держать в переключателе дверь в пустоту.
     *
     * Признаком, а не отдельным списком видимых окон: второй список однажды разойдётся с
     * первым — ровно то, от чего заведён порядок объявления.
     */
    val temporary: Boolean = false,
) {
    /**
     * Окно 0 — звонок. **Первое**, потому что порядок объявления есть порядок в
     * переключателе, а в макете звонок стоит первым. Видно его только во время звонка.
     */
    Call("\uD83D\uDCDE", withCounter = false, temporary = true),
    Phone("\uD83D\uDCDE", withCounter = true),
    Social("\uD83D\uDCF0", withCounter = true),
    Media("\uD83D\uDDBC", withCounter = false),
    Activity("\uD83D\uDCAC", withCounter = true),
    Page("\uD83D\uDC64", withCounter = false),
    ;

    companion object {
        /**
         * Окна, которые сейчас показываются: постоянные всегда, временные — когда есть
         * чему в них быть.
         *
         * Один источник и для рейки, и для переключателя, и для свайпа: три списка
         * разъехались бы, и человек получил бы окно, до которого доходит свайпом, но не
         * видит в переключателе.
         *
         * @param inCall идёт ли звонок.
         */
        fun shown(inCall: Boolean): List<Window> =
            entries.filter { !it.temporary || (it == Call && inCall) }
    }
}
