package io.tima.feature.shell

/**
 * Окна приложения — перечень, а не строка.
 *
 * **Имён у окна два, и оба нужны** (`интерфейс.md §1`): длинное — в переключателе и
 * рейке, короткое — в собственной шапке. «Социальная лента» против «Социум». Держать
 * их в одном месте важнее, чем экономить поле: разошедшись, они дают окно, которое
 * называется по-разному в двух местах одного экрана, и никто не может сказать, какое
 * из имён настоящее.
 *
 * **Порядок объявления — это порядок в переключателе и порядок свайпа.** Отдельного
 * списка «в каком порядке показывать» нет намеренно: второй список однажды разойдётся
 * с первым.
 *
 * Блогерских окон 6–7 здесь нет: они включаются в настройках и появятся вместе с ними
 * (`§12` — окон блогера в макете нет вовсе).
 */
enum class Окно(
    /** Как окно называется в переключателе и рейке. */
    val полное: String,
    /** Как оно называется в собственной шапке. */
    val краткое: String,
    /** Вторая строка в переключателе: названия мало, чтобы понять, зачем туда идти. */
    val очём: String,
    /** Знак в рейке и в переключателе. */
    val знак: String,
    /**
     * Собирает ли окно сводный счётчик непрочитанного.
     *
     * У медиа-ленты и личной страницы его нет: в макете счётчик стоит у телефона,
     * социальной ленты и общения. Это не забывчивость — непрочитанное там не
     * накапливается: лента листается, а своя страница не приходит извне.
     */
    val соСчётчиком: Boolean,
) {
    Телефон("Телефон", "Телефон", "чаты, книга, звонки", "📞", соСчётчиком = true),
    Социум("Социальная лента", "Социум", "общая, друзья, каталог", "📰", соСчётчиком = true),
    Медиа("Медиа-лента", "Медиа", "лента и слайды", "🖼", соСчётчиком = false),
    Общение("Свободное общение", "Общение", "истории, ответы, реакции", "💬", соСчётчиком = true),
    Страница("Личная страница", "Страница", "профиль, коллекции, роли", "👤", соСчётчиком = false),
}
