package io.tima.feature.shell

import androidx.compose.foundation.layout.Box
import androidx.compose.foundation.layout.fillMaxSize
import androidx.compose.runtime.Composable
import androidx.compose.ui.Modifier
import io.tima.core.ui.TimaColors
import io.tima.testui.FOREIGN_BACKGROUND
import io.tima.testui.Snapshot
import io.tima.testui.capture
import kotlin.test.Test
import kotlin.test.assertEquals

/**
 * Какие ряды не помещаются в телефонную строку — и это известно поимённо.
 *
 * ── ЗАЧЕМ ЭТА ПРОВЕРКА СУЩЕСТВУЕТ ───────────────────────────────────────────
 *
 * Заказчик спросил ровно это: «на вторую строку переносится, если на первой нет места.
 * Мне кажется, вмещается?» Ответ «кажется» здесь не годится — ширина ряда складывается
 * из кегля, отступов чипа, зазора и длины слов, и ни одно из этих чисел не лежит рядом
 * с другим. Ровно так уже обрезались подписи рейки: см. [RailWidthTest].
 *
 * **Перенос не запрещён — он именно то, что решено делать вместо прокрутки.** Запрещено
 * другое: чтобы он появлялся молча. Список ниже — перечень рядов, про которые известно,
 * что они переносятся; новый ряд в этом списке означает решение, а не случайность.
 *
 * ── КАК МЕРЯЕТСЯ ────────────────────────────────────────────────────────────
 *
 * Один и тот же ряд снимается дважды: на телефонной ширине и на заведомо широкой.
 * Перенос — это когда узкий снимок **выше** широкого. Считать ширину арифметикой
 * нельзя: отступы чипа, вкладки и сегмента живут в трёх разных файлах, и тест,
 * повторяющий их числами, разошёлся бы с вёрсткой молча — то есть заболел бы ровно той
 * болезнью, от которой лечит.
 */
class RowFitTest {

    @Test
    fun известно_какие_ряды_переносятся_на_телефоне() {
        val wrapping = ROWS.filter { (name, row) ->
            val narrow = capture("ряд-мера-узкий-$name", PHONE, 200, dark = false, backdrop = FOREIGN_BACKGROUND) { row() }
            val wide = capture("ряд-мера-широкий-$name", WIDE, 200, dark = false, backdrop = FOREIGN_BACKGROUND) { row() }
            height(narrow) > height(wide)
        }.keys

        assertEquals(
            WRAPS_ON_PHONE,
            wrapping,
            "перечень переносящихся рядов изменился. Перенос сам по себе не брак — " +
                "брак в том, чтобы он появился незамеченным. Либо укоротите ряд, либо " +
                "впишите его сюда осознанно",
        )
    }

    /** Высота серой полосы ряда: до какой строки сверху идёт функциональный фон. */
    private fun height(snapshot: Snapshot): Int {
        var last = 0
        for (y in 0 until snapshot.height) {
            if (Snapshot.close(snapshot.color(2, y), TimaColors.light.functional)) last = y + 1
        }
        return last
    }

    private companion object {
        /** Узкая телефонная ширина из снимков: та же, на которой меряют остальные тесты. */
        const val PHONE = 380

        /** Заведомо широкая: на ней не переносится ничто. */
        const val WIDE = 900

        /**
         * Ряды окон — те, что рисуются шириной во всё окно.
         *
         * Надписи берутся из самих окон (`Windows.kt`), а не переписаны сюда: копия
         * разошлась бы с окном, и тест мерил бы слова, которых на экране уже нет.
         */
        val ROWS: Map<String, @Composable () -> Unit> = mapOf(
            "телефон-звонки" to { Row { FilterRow(CALL_FILTERS, "Все", {}) } },
            "медиа-вкладки" to {
                Row {
                    TabRow(COMMON_TABS, COMMON_TABS.first(), {}) {
                        ModeSwitch(MEDIA_MODES, MEDIA_MODES.first(), {})
                    }
                }
            },
            "социум-реакции" to { Row { FilterRow(REACTION_FILTERS, "Все", {}) } },
            "страница-вкладки" to { Row { TabRow(PAGE_TABS, "Коллекции", {}) } },
            "страница-коллекции" to {
                Row {
                    FilterRow(COLLECTION_TABS, COLLECTION_TABS.first(), {}) {
                        ModeSwitch(COLLECTION_MODES, "Личное", {})
                    }
                }
            },
        )

        /**
         * Ряды, которые на телефоне в одну строку не помещаются. Измерено 2026-09-02
         * при [PHONE] = 380 точек, из которых ряду достаётся 348: по 16 на поля.
         *
         * ```
         * медиа-вкладки        378 = вкладки 241 + зазор 8 + переключатель 129
         * страница-вкладки     358 = четыре вкладки 334 + три зазора 24
         * страница-коллекции   374 = подвкладки 218 + зазор 8 + переключатель 148
         * ```
         *
         * **Два из трёх переносов появились в этот же день** — вместе с переходом
         * вкладки на макетный `.таб`. Прежняя вкладка была чипом: кегль 11 вместо 13,
         * поля 10 вместо 14, и ряд вкладок «Медиа» занимал 332 точки вместо 378. То
         * есть перенос — цена того, что ряды перестали выглядеть одинаково, и цена
         * названа здесь числом, а не «стало чуть шире».
         *
         * **«Коллекции» переносились и до того**: 374 точки ряд просил и раньше.
         *
         * Макет обходит это в окне «Медиа» знаками `▤ ▣` вместо слов «Лента | Слайды»
         * (`.режимы.знаками` — 66 точек вместо 129) и держит переключатель в шапке, а
         * не в ряду вкладок. У нас он стоит правее вкладок по решению заказчика, и
         * вторая строка — цена этого решения.
         */
        val WRAPS_ON_PHONE = setOf("медиа-вкладки", "страница-вкладки", "страница-коллекции")
    }
}

/** Ряд во всю ширину снимка: сам ряд красит свою подложку, а вокруг — чужой фон. */
@Composable
private fun Row(content: @Composable () -> Unit) = Box(Modifier.fillMaxSize()) { content() }
