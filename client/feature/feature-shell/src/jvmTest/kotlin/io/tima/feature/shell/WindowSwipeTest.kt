package io.tima.feature.shell

import io.tima.core.words.RussianWords
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

/**
 * Зоны свайпа — арифметика, а не картинка.
 *
 * Снимком это не проверить: жест не рисуется. Но правило простое и его легко потерять
 * — «средняя зона считается от границ историй и перемотки», — поэтому проверяется сам
 * расчёт границ, а не отрисовка.
 *
 * Числа те же, что в [свайпОкон]: 96 сверху (ряд историй), 46 снизу (полоса перемотки
 * со временем). Если кто-то поменяет их в одном месте и забудет в другом, тест упадёт.
 */
class WindowSwipeTest {

    @Test
    fun середина_экрана_переключает_окна() {
        assertTrue(inMiddle(y = 400f, height = 800f), "середина экрана обязана менять окна")
        assertTrue(inMiddle(y = 97f, height = 800f), "сразу под историями уже средняя зона")
        assertTrue(inMiddle(y = 753f, height = 800f), "сразу над перемоткой ещё средняя зона")
    }

    @Test
    fun истории_и_перемотка_свои_зоны_не_отдают() {
        assertTrue(!inMiddle(y = 0f, height = 800f), "самый верх принадлежит историям")
        assertTrue(!inMiddle(y = 96f, height = 800f), "нижняя граница историй — их же")
        assertTrue(!inMiddle(y = 754f, height = 800f), "верхняя граница перемотки — её же")
        assertTrue(!inMiddle(y = 799f, height = 800f), "самый низ принадлежит перемотке")
    }

    /**
     * На коротком экране средней зоны не остаётся вовсе.
     *
     * Так и должно быть: 142 точки — это высота двух строк списка, и ни истории, ни
     * слайды туда не поместятся. Важно, что при этом ничего не ломается — свайп просто
     * не срабатывает, а видимый способ сменить окно остаётся.
     */
    @Test
    fun на_коротком_экране_средней_зоны_нет() {
        assertTrue(!inMiddle(y = 70f, height = 140f), "на 140 точек средней зоны быть не может")
    }

    @Test
    fun порядок_окон_и_есть_порядок_свайпа() {
        // Свайп идёт по перечню, а не по отдельному списку: второй список однажды
        // разошёлся бы с первым, и окна начали бы меняться не в том порядке, что в
        // переключателе.
        //
        // Без звонка окно 0 в перечне есть, а в показе его нет: временное окно
        // показывается, только пока есть чему в нём быть.
        assertEquals(
            listOf("Телефон", "Социальная лента", "Медиа-лента", "Свободное общение", "Личная страница"),
            Window.shown(inCall = false).map { RussianWords.windows.full(it) },
        )
    }

    @Test
    fun во_время_звонка_окно_ноль_становится_первым() {
        // Макет `21-call.md`: «окно 0, временное, первое в горизонтальном переключателе»
        // (решение заказчика 2026-09-19). Первое — потому что порядок объявления и есть
        // порядок показа, а не потому, что его куда-то вставили.
        assertEquals(
            listOf("Звонок", "Телефон", "Социальная лента", "Медиа-лента", "Свободное общение", "Личная страница"),
            Window.shown(inCall = true).map { RussianWords.windows.full(it) },
        )
    }

    @Test
    fun временных_окна_два_и_у_каждого_своё_условие() {
        // Их стало два 2026-09-20: к звонку добавился стенд (ПЛАН-СТЕНДА-ЗВОНКОВ С-В1).
        // Проверка существует затем, чтобы третье не завелось молча: у `shown` условие
        // на каждое временное окно пишется отдельной строкой, и забытая строка означает
        // окно, до которого доходит свайп, но которого нет в переключателе.
        assertEquals(listOf(Window.Call, Window.Bench), Window.entries.filter { it.temporary })
    }

    @Test
    fun ряд_окон_замкнут_в_кольцо() {
        // Решение заказчика 2026-09-21, обратное прежнему «края не заворачиваются».
        // Довод прежнего был не пустой, но временные окна стоят по РАЗНЫМ концам ряда:
        // звонок первым, стенд последним. Без кольца из звонка до стенда пять свайпов —
        // ровно в тот момент, когда нужен один.
        //
        // Проверяется арифметика кольца, а не жест: у отрицательного числа остаток в
        // Kotlin отрицателен, и свайп с первого окна ушёл бы в -1, то есть никуда.
        val order = Window.shown(inCall = true, bench = true)
        assertEquals(Window.Call, order.first())
        assertEquals(Window.Bench, order.last())

        assertEquals(Window.Bench, order.ring(order.indexOf(Window.Call), -1), "с первого окна назад — на последнее")
        assertEquals(Window.Call, order.ring(order.indexOf(Window.Bench), 1), "с последнего окна вперёд — на первое")
    }

    /** Та же арифметика, что в `switchWindow`: шаг по кольцу. */
    private fun List<Window>.ring(at: Int, step: Int): Window = this[(at + step + size) % size]

    @Test
    fun стенд_показывается_только_при_включённом_флаге() {
        // Выключенный стенд — это не «окно без содержимого», а отсутствие окна: держать
        // в переключателе дверь в пустоту не за что. И наоборот: включённый флаг обязан
        // давать окно и без звонка — числа смотрят и между прогонами.
        assertEquals(
            listOf("Телефон", "Социальная лента", "Медиа-лента", "Свободное общение", "Личная страница"),
            Window.shown(inCall = false, bench = false).map { RussianWords.windows.full(it) },
        )
        assertEquals(
            listOf("Телефон", "Социальная лента", "Медиа-лента", "Свободное общение", "Личная страница", "Стенд звонков"),
            Window.shown(inCall = false, bench = true).map { RussianWords.windows.full(it) },
        )
    }

    /** Та же арифметика, что в модификаторе: точка начала жеста против границ. */
    private fun inMiddle(y: Float, height: Float, top: Float = 96f, bottom: Float = 46f): Boolean =
        y > top && y < height - bottom
}
