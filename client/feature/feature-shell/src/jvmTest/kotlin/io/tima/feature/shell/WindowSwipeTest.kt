package io.tima.feature.shell

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

/**
 * Зоны свайпа — арифметика, а не картинка.
 *
 * Снимком это не проверить: жест не рисуется. Но правило простое и его легко потерять
 * — «средняя зона считается от границ историй и перемотки», — поэтому проверяется сам
 * расчёт границ, а не отрисовка.
 *
 * Числа те же, что в [свайпОкон]: 96 сверху (ряд историй), 46 снизу (полоса перемотки
 * со временем). Если кто-то поменяет их в одном месте и забудет в другом, тест упадёт.
 */
class СвайпОконTest {

    @Test
    fun середина_экрана_переключает_окна() {
        assertTrue(вСредней(y = 400f, высота = 800f), "середина экрана обязана менять окна")
        assertTrue(вСредней(y = 97f, высота = 800f), "сразу под историями уже средняя зона")
        assertTrue(вСредней(y = 753f, высота = 800f), "сразу над перемоткой ещё средняя зона")
    }

    @Test
    fun истории_и_перемотка_свои_зоны_не_отдают() {
        assertTrue(!вСредней(y = 0f, высота = 800f), "самый верх принадлежит историям")
        assertTrue(!вСредней(y = 96f, высота = 800f), "нижняя граница историй — их же")
        assertTrue(!вСредней(y = 754f, высота = 800f), "верхняя граница перемотки — её же")
        assertTrue(!вСредней(y = 799f, высота = 800f), "самый низ принадлежит перемотке")
    }

    /**
     * На коротком экране средней зоны не остаётся вовсе.
     *
     * Так и должно быть: 142 точки — это высота двух строк списка, и ни истории, ни
     * слайды туда не поместятся. Важно, что при этом ничего не ломается — свайп просто
     * не срабатывает, а видимый способ сменить окно остаётся.
     */
    @Test
    fun на_коротком_экране_средней_зоны_нет() {
        assertTrue(!вСредней(y = 70f, высота = 140f), "на 140 точек средней зоны быть не может")
    }

    @Test
    fun порядок_окон_и_есть_порядок_свайпа() {
        // Свайп идёт по перечню, а не по отдельному списку: второй список однажды
        // разошёлся бы с первым, и окна начали бы меняться не в том порядке, что в
        // переключателе.
        assertEquals(
            listOf("Телефон", "Социальная лента", "Медиа-лента", "Свободное общение", "Личная страница"),
            Окно.entries.map { it.полное },
        )
    }

    /** Та же арифметика, что в модификаторе: точка начала жеста против границ. */
    private fun вСредней(y: Float, высота: Float, верх: Float = 96f, низ: Float = 46f): Boolean =
        y > верх && y < высота - низ
}
