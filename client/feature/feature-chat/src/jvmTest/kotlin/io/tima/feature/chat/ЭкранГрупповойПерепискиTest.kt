package io.tima.feature.chat

import io.tima.domain.chat.ChatLine
import io.tima.domain.chat.MessageDisplay
import io.tima.testui.снять
import kotlin.test.Test
import kotlin.test.assertTrue

/**
 * Окно групповой переписки в снимках.
 *
 * Проверяется одно, ради чего групповой экран и отличается от личного: **видно, кто
 * написал**. В личной переписке собеседник один и назван в шапке; в группе реплика без
 * автора теряет половину смысла — «кто это сказал» и есть половина сообщения.
 */
class ЭкранГрупповойПерепискиTest {

    private val реплики = listOf(
        строка("m2", "u-3", "а я уже там"),
        строка("m1", "u-2", "выходим в семь"),
    )

    @Test
    fun в_группе_автор_нарисован_а_в_личной_нет() {
        val личная = снять("группа-личная", ШИРИНА, ВЫСОТА, тёмная = false) {
            экран(ChatState(lines = реплики, группа = false))
        }
        val групповая = снять("группа-групповая", ШИРИНА, ВЫСОТА, тёмная = false) {
            экран(
                ChatState(
                    lines = реплики,
                    группа = true,
                    имена = mapOf("u-2" to "Аня", "u-3" to "Петя"),
                ),
            )
        }
        assertTrue(
            групповая.расхождение(личная) > 0.0,
            "групповая переписка нарисована так же, как личная — автор не показан",
        )
    }

    @Test
    fun два_автора_подряд_не_слипаются() {
        // Смена автора обязана разрывать цепочку: иначе два человека подряд выглядят
        // одним, и имя второго не показывается вовсе.
        val разные = снять("группа-разные", ШИРИНА, ВЫСОТА, тёмная = false) {
            экран(ChatState(lines = реплики, группа = true, имена = имена))
        }
        val одинаковые = снять("группа-одинаковые", ШИРИНА, ВЫСОТА, тёмная = false) {
            экран(
                ChatState(
                    lines = listOf(строка("m2", "u-2", "а я уже там"), строка("m1", "u-2", "выходим в семь")),
                    группа = true,
                    имена = имена,
                ),
            )
        }
        assertTrue(разные.расхождение(одинаковые) > 0.0, "смена автора не разорвала цепочку")
    }

    @Test
    fun неизвестное_имя_не_выдумывается() {
        // Показать чужое имя хуже, чем не показать никакого: человек решит, что писал
        // не тот, кто писал.
        val безИмени = снять("группа-без-имени", ШИРИНА, ВЫСОТА, тёмная = false) {
            экран(ChatState(lines = реплики, группа = true, имена = emptyMap()))
        }
        val сИменами = снять("группа-с-именами", ШИРИНА, ВЫСОТА, тёмная = false) {
            экран(ChatState(lines = реплики, группа = true, имена = имена))
        }
        assertTrue(безИмени.расхождение(сИменами) > 0.0, "имена никак не влияют на экран")
    }

    private companion object {
        const val ШИРИНА = 380
        const val ВЫСОТА = 600

        val имена = mapOf("u-2" to "Аня", "u-3" to "Петя")

        fun строка(ключ: String, автор: String, текст: String) = ChatLine(
            dedupKey = ключ,
            chatId = "g-1",
            display = MessageDisplay.RECEIVED,
            text = текст,
            outgoing = false,
            atMs = 1_750_000_000_000,
            localId = ключ.last().code.toLong(),
            senderId = автор,
        )

        @androidx.compose.runtime.Composable
        fun экран(состояние: ChatState) = ЭкранЧата(
            состояние = состояние,
            собеседник = "Поход",
            onНабор = {},
            onОтправить = {},
            onНазад = {},
        )
    }
}
