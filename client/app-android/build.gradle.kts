// Вход для Android. Здесь и только здесь разрешено знать о платформе как о
// платформе (Plan.md §1.3): Activity, манифест, разрешения, push, сервисы.
//
// Приложение здесь тонкое намеренно: интерфейс, навигация и правила поведения живут в
// `shared`, общие для ПК и телефона. В v1 сборка приложения была по копии на платформу, и
// Android с Desktop разошлись молча — одна платформа получала починку, другая нет.
kotlin {
    jvmToolchain(17)
    androidTarget()

    sourceSets {
        androidMain.dependencies {
            // Всё общее — одним модулем. Платформенного здесь два: драйвер базы и
            // Activity. material3 больше не нужен: у нас своя система форм и цветов.
            implementation(project(":shared"))
            implementation(project(":core:core-database"))
            implementation(project(":core:core-ui"))
            // Хранилищу секретов нужен контекст: AndroidKeyStore вместо DPAPI.
            implementation(project(":core:core-secrets"))
            implementation(project(":core:core-contacts"))
            // Уведомления: разрешение спрашивает ОКНО, а показывает служба (У1, У3).
            implementation(project(":core:core-notify"))
            // Слежение за сетью (У17): порт в core-network, исполнение — здесь, потому
            // что у core-network нет своей Android-цели, а `ConnectivityManager` — есть
            // только у Android.
            implementation(project(":core:core-network"))
            // Движок звонка собирается здесь: ему нужен Context, а общий код его
            // не видит. Вместе с ним приезжает libwebrtc — те самые 48 МБ.
            implementation(project(":core:core-call"))
            // Оболочка объявляет порт установщика обновлений, реализация платформенная и
            // живёт здесь (О4): DownloadManager, проверка подписи, PackageInstaller.
            implementation(project(":feature:feature-shell"))
            // Журнал: точка входа ловит падения и кладёт их в очередь отчётов вместе с
            // тем, что человек успел сделать (ПЛАН-ОТЛАДКИ.md, Б7).
            implementation(project(":core:core-diag"))
            implementation(libs.androidx.activity.compose)
            // foundation нужен самой Activity: тема системы (isSystemInDarkTheme) живёт там.
            implementation(compose.foundation)
        }
    }
}

android {
    namespace = "io.tima.app"
    compileSdk = 35

    // BuildConfig генерируется по требованию (AGP 8). Нужен ровно для одного: показать

    // номер сборки на экране входа — иначе «обновление доехало» проверяется на слово.

    buildFeatures { buildConfig = true }


    defaultConfig {
        applicationId = "io.tima.app"
        // API 26+ — из tech-stack.md. Пересмотр минимума — отдельное решение,
        // а не побочный эффект правки сборки.
        minSdk = 26
        targetSdk = 34
        // Версия — из gradle.properties, одна на все сборки. Литерал здесь означал бы
        // второй источник правды, а расходятся они молча.
        versionCode = (property("tima.versionCode") as String).toInt()
        // Номер тестовой сборки (правило заказчика 2026-09-19): «поднимаешь версию от
        // предыдущей, ставишь ей номер теста, тоже можешь поднять». Версия растёт один раз
        // на работу, проверочные сборки внутри неё отличаются номером: -t1, -t2, -t3.
        // Готовая — без номера, и она же числится в КЛИЕНТЫ.md.
        //
        // Растить сам номер версии на каждую пробу нельзя: телефонов несколько, обновлять
        // их все ради одной проверки дорого, и тогда номер перестал бы означать «вот эта
        // работа». Номер теста виден на экране «О программе» и в журнале — по нему и
        // видно, какая сборка на каком телефоне. Ставится так: `-Ptima.test=2`.
        val testBuild = (findProperty("tima.test") as String? ?: "0").toInt()
        versionName = (property("tima.versionName") as String) +
            (if (testBuild > 0) "-t" + testBuild else "")
        // Поток в BuildConfig, а не литералом в коде: он обязан совпадать с тем, что
        // сервер называет в /app/version, иначе обновление либо молчит, либо предлагает
        // чужую сборку.
        buildConfigField("String", "TIMA_STREAM", "\"${property("tima.stream")}\"")

        // ── ABI: телефонам телефонное ───────────────────────────────────────
        //
        // **Вопрос, отложенный здесь же до появления нативного кода.** Прежняя редакция
        // этого места говорила: ограничения нет, эмулятор работает, вернуться к вопросу,
        // когда приедут нативные библиотеки. Они приехали — libwebrtc внутри
        // `livekit-android`, 2026-09-19.
        //
        // Что из этого вышло, измерено, а не предположено:
        //
        // | Что в APK | Сколько |
        // |---|---|
        // | `lib/x86_64` | 16,1 МБ |
        // | `lib/x86` | 12,9 МБ |
        // | `lib/arm64-v8a` | 12,2 МБ |
        // | `lib/armeabi-v7a` | 7,1 МБ |
        //
        // **29 МБ из 64 — под архитектуры, которых нет ни на одном телефоне.** x86 и
        // x86_64 бывают у эмулятора и у редких планшетов; каждый телефон качает их и
        // выбрасывает. И это не «лишний вес»: на 64 МБ обновление у заказчика не
        // скачалось вовсе (отчёт `MBRY` 2026-09-19).
        //
        // **Эмулятор не брошен, а переведён на просьбу:** `-Ptima.abi=all` собирает всё
        // как раньше. Умолчание выбрано в пользу того, что уезжает людям, потому что
        // ошибка в эту сторону стоит дороже — забытый флаг на своей машине заметен сразу,
        // забытые 29 МБ в раздаче незаметны никому, кроме того, у кого не качается.
        ndk {
            val forEveryone = (project.findProperty("tima.abi") as String?) == "all"
            if (!forEveryone) {
                abiFilters += setOf("arm64-v8a", "armeabi-v7a")
            }
        }
    }

    // ── Отладочная сборка ставится РЯДОМ с v1, а не вместо ──────────────────
    //
    // На телефоне разработки живёт v1 (`io.tima.app`, versionCode 23), и она нужна: пока
    // v2 не работает целиком, сравнивать поведение больше не с чем. Установка v2 поверх
    // невозможна и технически — подпись другая, Android отвечает «приложение конфликтует
    // с другим пакетом» (инвентарь поведения, пункт 14).
    //
    // Поэтому отладочная сборка v2 берёт другой идентификатор и живёт рядом. РЕЛИЗНЫЙ
    // идентификатор не меняется: обновить человека на месте можно только сохранив его.
    buildTypes {
        getByName("debug") {
            applicationIdSuffix = ".v2"
            versionNameSuffix = "-v2"
        }
    }

    // ── Подпись ─────────────────────────────────────────────────────────────
    // Инвентарь поведения, пункт 14: отладочный ключ генерируется на каждой
    // машине свой, поэтому смена машины сборки давала «Приложение конфликтует с
    // другим пакетом» у всех установленных — Android не даёт обновить приложение
    // с другой подписью. Стабильный ключ лежит в keystore/ вне гита; его потеря
    // означает переустановку у всех пользователей.
    //
    // Ключа нет (свежий клон или CI) — собираем отладочной подписью, чтобы сборка
    // не падала. Настройка появится вместе с распространением, в К7.

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    // Инвентарь поведения, пункт 15: дубликаты метаданных из зависимостей ломают
    // слияние ресурсов APK. Появятся вместе с зависимостями — тогда и список.
}

