#Requires -Version 5.1
<#
.SYNOPSIS
    Кладёт на рабочий стол ярлыки запускалок TIMA.

.DESCRIPTION
    Два ярлыка: «ОБНОВИТЬ И ЗАПУСТИТЬ ПК» и «ОБНОВИТЬ ТЕЛЕФОНЫ». Первый был сделан
    руками и живёт на столе с августа; второй до 2026-09-16 не существовал вовсе —
    телефоны обновляли, набирая путь к `.bat` в консоли.

    ── ПОЧЕМУ ЯРЛЫК, А НЕ ФАЙЛ С КИРИЛЛИЦЕЙ В КОРНЕ ────────────────────────────

    У ПК запускалка называется `ОБНОВИТЬ-И-ЗАПУСТИТЬ-ПК.bat` — это исключение,
    решение заказчика 2026-08-26, и оно ОДНО: `LatinTest` держит бюджет
    кириллических имён на единице и падает в обе стороны. Второй такой файл уронил
    бы проверку, а понижать её ради удобства нельзя — она и заведена, чтобы имена не
    расползались.

    Поэтому в репозитории лежит `update-and-install-phone.bat` латиницей, а русское
    имя живёт **в ярлыке**: ярлык на рабочем столе, git его не видит, и читает его
    человек. Ровно то разделение, которое правило и имело в виду.

    ── ПОЧЕМУ ЭТОТ СКРИПТ ОТСЛЕЖИВАЕТСЯ ──────────────────────────────────────

    Ярлык — машинное, но СПОСОБ его сделать общий. На новой машине проекта иначе
    пришлось бы вспоминать, что вообще бывают ярлыки и куда они ведут.

.PARAMETER Куда
    Каталог для ярлыков. По умолчанию — рабочий стол текущего пользователя.
#>
[CmdletBinding()]
param(
    [string]$Куда = [Environment]::GetFolderPath('Desktop')
)

$ErrorActionPreference = 'Stop'
$корень = Split-Path -Parent $MyInvocation.MyCommand.Path
$оболочка = New-Object -ComObject WScript.Shell

function Ярлык {
    param(
        [Parameter(Mandatory)][string]$Имя,
        [Parameter(Mandatory)][string]$Цель,
        [string]$Описание = '',
        [string]$Значок = ''
    )

    $путь = Join-Path $корень $Цель
    if (-not (Test-Path $путь)) {
        Write-Host "нет файла $Цель — ярлык «$Имя» не сделан" -ForegroundColor Red
        return
    }

    $файл = Join-Path $Куда "$Имя.lnk"
    $ярлык = $оболочка.CreateShortcut($файл)
    $ярлык.TargetPath = $путь
    # Рабочий каталог — корень репозитория: скрипты зовут gradlew по относительному
    # пути, и из чужого каталога сборка не найдётся.
    $ярлык.WorkingDirectory = $корень
    $ярлык.Description = $Описание
    if ($Значок) { $ярлык.IconLocation = $Значок }
    $ярлык.Save()
    Write-Host "готов: $файл" -ForegroundColor Green
    Write-Host "        → $путь"
}

Write-Host ''
Write-Host '=== Ярлыки TIMA ==='
Write-Host ''

Ярлык -Имя 'ОБНОВИТЬ-И-ЗАПУСТИТЬ-ПК' -Цель 'ОБНОВИТЬ-И-ЗАПУСТИТЬ-ПК.bat' `
    -Описание 'Собрать приложение для ПК из текущих исходников и запустить' `
    -Значок "$env:SystemRoot\System32\imageres.dll,109"

Ярлык -Имя 'ОБНОВИТЬ ТЕЛЕФОНЫ' -Цель 'update-and-install-phone.bat' `
    -Описание 'Собрать APK из текущих исходников и поставить на все подключённые телефоны' `
    -Значок "$env:SystemRoot\System32\imageres.dll,177"

Write-Host ''
Write-Host 'Телефоны ставятся обновлением (install -r): переписка и аккаунт остаются.'
Write-Host 'Телефон на чужой машине — запускать с -AdbServer host:port или задать'
Write-Host 'TIMA_ADB_SERVER; сейчас все три висят прямо на этой машине.'
Write-Host ''
