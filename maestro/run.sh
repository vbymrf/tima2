#!/bin/sh
# Запуск сценария так, чтобы телефон не спал. Пользоваться этим, а не `maestro test`.
#
# ── ЗАЧЕМ ОБЁРТКА ───────────────────────────────────────────────────────────
#
# Спящий телефон — самая дорогая беда этого стенда, потому что она НЕ выглядит как
# сон. 2026-09-16 она дважды притворилась чужой поломкой, и оба раза вывод был неверным:
#
#   «Maestro не умеет параллельно, ветки дерутся за общий adb»
#        — нет. На снимках упавших шагов чёрный экран, screen_off_timeout 30 000.
#   «По сетевому adb драйвер не успевает встать, таймаут обязателен»
#        — нет. С разбуженным телефоном прогон без таймаута идёт 123 с и проходит.
#
# Общая причина у обоих — телефон погас. Разбудить его помнит человек, а человек
# забывает; поэтому пробуждение здесь пришито к запуску, а не оставлено в памяти.
#
# ── ЧТО ЭТО НЕ ЧИНИТ ────────────────────────────────────────────────────────
#
# Телефоны стенда стоят НЕ на зарядке (`dumpsys battery`: ACpowered:false). Экран им
# держит только `screen_off_timeout`, выставленный в сутки, — и это разряжает батарею.
# Обёртка убирает забывчивость, а не расход. Правильное лекарство — питание: на зарядке
# работает `stay_on_while_plugged_in 7`, штатная галка из меню разработчика.
#
# Использование:  sh maestro/run.sh update.yaml                    — все телефоны
#                 sh maestro/run.sh update.yaml 192.168.3.226:35273 — один
set -eu

FLOW="${1:?нужен сценарий, например: sh maestro/run.sh update.yaml}"
shift

HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
ADB="${ADB:-$LOCALAPPDATA/Android/Sdk/platform-tools/adb.exe}"
export ADB

if [ "$#" -gt 0 ]; then
    DEVICES="$1"
else
    DEVICES=$("$ADB" devices | grep -v "List of" | awk '$2 == "device" {print $1}' | paste -sd, -)
fi
[ -n "$DEVICES" ] || { echo "ни один телефон не отвечает" >&2; exit 1; }

# Пробуждение — по одному, с проверкой: `wm dismiss-keyguard` срабатывает не всегда с
# первого раза, и молчаливый отказ здесь стоит целого прогона.
for d in $(echo "$DEVICES" | tr ',' ' '); do
    sh "$HERE/wake-phone.sh" "$d"
done

SHARDS=$(echo "$DEVICES" | tr ',' '\n' | grep -c .)

# Таймаут подъёма драйвера. Обмерено 2026-09-16: на разбуженном телефоне он НЕ нужен —
# прогон без него проходит за 123 с. Оставлен как страховка: потолок ожидания временем не
# оплачивается, пока драйвер встаёт быстро, а вот его нехватка стоит всего прогона.
export MAESTRO_DRIVER_STARTUP_TIMEOUT="${MAESTRO_DRIVER_STARTUP_TIMEOUT:-240000}"

echo "телефонов $SHARDS: $DEVICES"
exec maestro --device "$DEVICES" test --shard-all="$SHARDS" "$HERE/$FLOW"
